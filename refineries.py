OUT = Path("targets.json")


def main():
    data = json.load(open(OUT, encoding="utf-8")) if OUT.exists() else \
        {"colors": {}, "objects": []}
    # прибрати попередній курований набір, щоб повторний запуск не дублював
    objs = [o for o in data["objects"] if o.get("src") != "curated"]
    for name, lat, lon, cat in CURATED:
        objs.append({"cat": cat, "lat": lat, "lon": lon, "name": name,
                     "osm": "", "src": "curated"})
    data["objects"] = objs
    data.setdefault("colors", {})
    data["colors"].setdefault("refinery", "#ffd23f")
    data["colors"].setdefault("fuel_depot", "#ffa03f")
    json.dump(data, open(OUT, "w", encoding="utf-8"), ensure_ascii=False)

    import collections
    n = sum(1 for _, _, _, c in CURATED)
    by = collections.Counter(c for *_, c in CURATED)
    print(f"додано {n} курованих обʼєктів -> {OUT}")
    for k, v in by.most_common():
        print(f"  {v:3}  {k}")
    print(f"всього у targets.json: {len(objs)}")


if __name__ == "__main__":
    main()
