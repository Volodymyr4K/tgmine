def coords_in(text: str) -> list[tuple[float, float]]:
    """Координати з тексту: «55.644523,37.805698», «50.094131° 43.237939°»,
    «47°16'24.52"N 39°37'56.20"E». Точка знімання («POV: …») — не ціль."""
    out = []
    for m in list(_DEC.finditer(text)) + list(_DMS.finditer(text)):
        if _POV.search(text[max(0, m.start() - 8):m.start()]):
            continue
        g = m.groups()
        try:
            if len(g) == 2:
                la, lo = float(g[0]), float(g[1])
            else:
                la = int(g[0]) + int(g[1]) / 60 + float(g[2]) / 3600
                lo = int(g[3]) + int(g[4]) / 60 + float(g[5]) / 3600
        except ValueError:
            continue                          # «36..5”» — описка, не координата
        if 41 <= la <= 72 and 19 <= lo <= 180:
            out.append((round(la, 5), round(lo, 5)))
    return out


def hav(a, b) -> float:
    R = 6371.0
    la1, lo1, la2, lo2 = map(math.radians, (*a, *b))
    h = (math.sin((la2 - la1) / 2) ** 2
         + math.cos(la1) * math.cos(la2) * math.sin((lo2 - lo1) / 2) ** 2)
    return 2 * R * math.asin(math.sqrt(h))


