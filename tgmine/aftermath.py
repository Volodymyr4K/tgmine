def _tok_stem(tok):
    """Основа слова для наступності серії: кістяк без закінчення відмінка."""
    sk = skel(tok)
    for e in sorted(NOUN_END, key=len, reverse=True):
        if e and sk.endswith(e) and len(sk) - len(e) >= 4:
            return sk[:-len(e)]
    return sk


def _pid(u):
    m = re.search(r"/(\d+)$", u or "")
    return int(m.group(1)) if m else None


def _reply_parent(p):
    """Батько відповіді в тому ж каналі (`reply_to` — адреса)."""
    u = p.get("reply_to") or ""
    if f"/{CHANNEL}/" not in u:
        return None
    return _pid(u)


def build(posts: list[dict], gaz, targets=None, *, point_region=None,
          depth_km=None, front_km=None) -> list[dict]:
    """Інциденти з сирих постів каналу. Детерміновано: той самий вхід — той
    самий вихід, у тому ж порядку."""
    if point_region is None or depth_km is None or front_km is None:
        from . import store as ST
        point_region = point_region or ST.point_region
        depth_km = depth_km or ST.depth_km
        front_km = front_km or (lambda reg: ST.FRONT_KM_BY_REGION.get(reg, ST.FRONT_KM))
    # Глибина й область — з полігонів, дорого; міст на весь корпус кількасот.
    _dm, _rm = {}, {}
    raw_depth, raw_region = depth_km, point_region

    def depth_km(pt):
        pt = (round(pt[0], 5), round(pt[1], 5))
        if pt not in _dm:
            _dm[pt] = raw_depth(pt)
        return _dm[pt]

    def point_region(la, lo):
        k = (round(la, 5), round(lo, 5))
        if k not in _rm:
            _rm[k] = raw_region(la, lo)
        return _rm[k]

    places = Places.load(gaz, targets)
    posts = sorted((p for p in posts if p.get("channel", CHANNEL) == CHANNEL and p.get("date")),
                   key=lambda p: (p["date"], p["id"]))
    incs: list[dict] = []
    of_post: dict[int, list[int]] = {}           # id поста -> інциденти, куди він пішов

    def key_of(r):
        return (r["name"], r["lat"], r["lon"])

    cells = collections.defaultdict(list)          # клітинка 0.1° -> інциденти
    by_tok = collections.defaultdict(list)         # основа слова -> інциденти

    def cell(pt):
        return (round(pt[0], 1), round(pt[1], 1))

    def find(k, pt, t, nights=None, back_h=None, hit=False, span_h=None):
        best = None
        cy, cx = cell(pt)
        near = sorted({j for dy in (-1, 0, 1) for dx in (-1, 0, 1)
                       for j in cells.get((round(cy + dy / 10, 1), round(cx + dx / 10, 1)), ())})
        for j in near:
            inc = incs[j]
            same = inc["key"] == k or hav(inc["pt"], pt) <= 5
            if not same:
                continue
            if hit and not any(x["hit"] for x in inc["posts"]):
                continue
            if nights is not None and inc["night"] not in nights:
                continue
            if back_h is not None and not (0 <= (t - inc["last"]).total_seconds() / 3600 <= back_h):
                continue
            # серія не тягнеться вічно: пожежа, що горить добу, не має
            # ковтати новий удар по тому ж місту через ніч (Капотня 15 і 17
            # червня, Перм 28 і 29 квітня)
            if span_h is not None and (t - inc["first"]).total_seconds() / 3600 > span_h:
                continue
            # живий пост не йде в інцидент, відкритий поясненням на давню
            # ніч («11 вересня… Губаха», а за дві години — новий удар по
            # Губасі): такий інцидент приймає лише пости своєї ночі
            if span_h is not None and inc["t0"] is None and inc["night"] != night_of(t):
                continue
            if best is None or inc["last"] > incs[best]["last"]:
                best = j
        return best

    def new(a, r, night, timed):
        incs.append({"key": key_of(r), "rec": r, "pt": (r["lat"], r["lon"]),
                     "night": night, "t0": a["t"] if timed else None, "first": a["t"],
                     "last": a["t"], "posts": [], "votes": collections.Counter(),
                     "recs": {}, "toks": set()})
        cells[cell((r["lat"], r["lon"]))].append(len(incs) - 1)
        return len(incs) - 1

    def attach(j, a, via, r=None, tok=""):
        inc = incs[j]
        if tok:
            st = _tok_stem(tok)
            if st not in inc["toks"]:
                inc["toks"].add(st)
                by_tok[st].append(j)
        if r is not None:
            # голос за назву інциденту: «Дзержинский, Люберцы … ТЭЦ» і
            # двадцять постів «Капотня … горит НПЗ» — це Капотня
            k = key_of(r)
            inc["votes"][k] += 3 if a["hit"] else 1
            inc["recs"].setdefault(k, r)
        if a["id"] in {x["id"] for x in inc["posts"]}:
            return
        inc["posts"].append({**a, "via": via})
        inc["last"] = max(inc["last"], a["t"])
        of_post.setdefault(a["id"], []).append(j)

    def series(tok, t):
        """Жива серія з тим самим словом: «Софьино» -> «Соф'їно» ->
        «Софиьно» (з помилкою) — те саме місце, хоч газетир і знає десяток
        тезок. Шукаємо серед інцидентів, де останній пост не старший за
        LINK_H, за основою слова."""
        st = _tok_stem(tok)
        if len(st) < 4:
            return None
        best = None
        for j in by_tok.get(st, ()):
            inc = incs[j]
            if 0 <= (t - inc["last"]).total_seconds() / 3600 <= LINK_H and \
                    (best is None or inc["last"] > incs[best]["last"]):
                best = j
        return best

    def place(a, r, retro, when, anchored, via, tok=""):
        """Пост із місцем -> інцидент. Повертає, чи пост кудись пішов."""
        # (наступність серії — лише для слів, яких газетир не знає: розвʼязане
        # місце не замінюємо — «Великий Новгород» після «Нижнього Новгорода»
        # мав одну основу останнього слова й зникав)
        k, pt = key_of(r), (r["lat"], r["lon"])
        if retro:
            nights = None
            if when and when[0] == "night":
                nights = {when[1].isoformat()}
            elif when and when[0] == "day":
                nights = {(when[1] - timedelta(days=1)).isoformat(), when[1].isoformat()}
            # Пояснення підтверджує відомий удар: спершу інцидент із
            # наслідком у названій ночі, потім із наслідком за тиждень, лише
            # потім будь-який у названій ночі. «Учора Генштаб повідомив про
            # Московський НПЗ» — «учора» тут про звіт, а не про удар.
            # Дата названа — лише та ніч: «Вчора, в День Незалежності…
            # вражено» — окремий удар, а не подробиці тижневої давнини.
            # Без дати — найсвіжіший інцидент із наслідком за тиждень.
            if nights:
                j = find(k, pt, a["t"], nights=nights, hit=True)
                if j is None:
                    j = find(k, pt, a["t"], nights=nights)
            else:
                j = find(k, pt, a["t"], back_h=RETRO_DAYS * 24, hit=True)
                if j is None:
                    j = find(k, pt, a["t"], back_h=RETRO_DAYS * 24)
            if j is None and nights and anchored:
                # Удар, про який дізнались лише з пояснення: на ту ніч, про
                # яку воно каже, без часу. «В ніч на N» — ніч однозначна;
                # голе «N вересня» — або ніч перед ним, або день N. Беремо
                # ту, де канал того ж регіону вже звітував (Пуровський ЗПК
                # «09.09» — тієї ж доби, що й Уренгойський, удень), інакше
                # ніч перед датою: нальоти здебільшого нічні.
                if when[0] == "night":
                    night = when[1]
                else:
                    # голе «N вересня»: ніч перед ним, якщо тоді канал звітував
                    # про цей регіон (Губаха «11 вересня» — хвиля Березників
                    # у ніч на 11-те); інакше день N, якщо звітував тоді
                    # (Пуровський ЗПК «09.09» — денний удар по Ямалу); інакше
                    # ніч перед датою — нальоти здебільшого нічні
                    reg = point_region(r["lat"], r["lon"])
                    act = {inc["night"] for inc in incs
                           if reg and point_region(*inc["pt"]) == reg}
                    d1 = when[1] - timedelta(days=1)
                    night = d1 if d1.isoformat() in act else (
                        when[1] if when[1].isoformat() in act else d1)
                j = new(a, r, night.isoformat(), timed=False)
            if j is None:
                return False
            attach(j, a, "retro", r, tok)
            return True
        # Місце без події в реченні не йде нікуди: «Ми встоїмо / Москва
        # ляже» під звітом СБС про кораблі чіплялось до живої московської
        # серії тієї ночі.
        if not anchored:
            return False
        j = find(k, pt, a["t"], back_h=LINK_H, span_h=SPAN_H)
        if j is None:
            j = new(a, r, night_of(a["t"]), timed=True)
        attach(j, a, via, r, tok)
        return True

    parents, loose = {}, []
    for p in posts:
        # контекст дрібного місця — місто інциденту батька
        par = _reply_parent(p)
        ctx = []
        if par in of_post:
            ctx = [incs[j]["pt"] for j in of_post[par]]
        a = analyse(p, places, point_region, ctx, depth_km)
        parents[p["id"]] = par
        placed = False
        cities = []
        # Перелік міст через країну («кораблі в Новоросійську, С-400 під
        # Сочі, літаки в Міллерово, у Криму») — огляд, а не репортаж: нових
        # ударів він не відкриває, лише доповнює наявні.
        distinct = {key_of(pl["rec"]): pl["rec"] for pl in a["places"]}
        if len(distinct) >= 3 and max(
                hav((x["lat"], x["lon"]), (y["lat"], y["lon"]))
                for x in distinct.values() for y in distinct.values()) > 150:
            for pl in a["places"]:
                pl["retro"] = True
                pl["anchored"] = False          # огляд нових ударів не відкриває
        for pl in a["places"]:
            r = pl["rec"]
            k = key_of(r)
            if any(key_of(c) == k for c in cities):
                continue
            cities.append(r)
            if place(a, r, pl["retro"], pl["when"], pl["anchored"], "live", pl["tok"]):
                placed = True
        # точні координати без міста в тексті: «Себряковцемент … у
        # Волгоградській області … 50.094131° 43.237939°». Спершу — інцидент
        # батька, якщо координата коло нього; інакше найближче місто.
        if not cities and a["coords"]:
            c = a["coords"][0]
            js = [j for j in of_post.get(par, ()) if hav(incs[j]["pt"], c) <= COORD_CITY_KM]
            if js:
                for j in js:
                    attach(j, a, "coords")
                placed = True
            else:
                city = _nearest_city(places, c)
                if city is not None:
                    # точка — самі координати (міст на трасі Маріуполь—Донецьк
                    # за 30 км від міста — не Донецьк); місто — лише підпис
                    r = {**city, "lat": c[0], "lon": c[1], "_city": city}
                    if place(a, r, a["retro"], a["when"], True, "coords"):
                        placed = True
        # Слово, яке газетир не впізнав, але серія ним уже названа:
        # «Еще кадры с Софиьно.» (з помилкою, без гілки) — у Софьино. Лише
        # короткий пост без координат і лише окреме слово: «трасі
        # Маріуполь-Донецьк» — не донецька серія.
        text = p.get("text") or ""
        if not cities and not placed and not a["coords"] and len(text) <= 150:
            for tok, at in _tokens(text):
                e = at + len(tok)
                if (at > 0 and text[at - 1] == "-") or (e < len(text) and text[e] == "-"):
                    continue
                if tok[:1].isupper() and not _stopword(skel(tok)):
                    j = series(tok, a["t"])
                    if j is not None:
                        attach(j, a, "live", incs[j]["rec"], tok)
                        placed = True
                        break
        # Відповідь без свого місця — до інциденту батька, якщо вона в межах
        # його серії. Відповідь через тиждень чи місяць на старий пост
        # (канал так звʼязує «знову Котовськ») — місце батька, але
        # інцидент за своїм часом, як звичайний пост.
        if not placed and par in of_post:
            for j in of_post[par]:
                inc = incs[j]
                age = (a["t"] - inc["first"]).total_seconds() / 3600
                if age <= SPAN_H:
                    attach(j, a, "reply")
                    placed = True
                elif a["when"]:
                    # «В ніч на 11-те вересня…» у відповідь на пост два дні
                    # по тому — на ту ніч, про яку каже
                    placed = place(a, inc["rec"], True, a["when"], a["event"], "reply") or placed
                elif age <= RETRO_DAYS * 24:
                    # подробиці за кілька днів — до того самого удару
                    attach(j, a, "retro")
                    placed = True
                elif place(a, inc["rec"], False, None, a["event"], "reply"):
                    # відповідь через місяць («знову Котовськ») — новий удар
                    placed = True
        if not placed and par is not None:
            loose.append(a)

    # Відповіді, чий предок дістав інцидент пізніше за них: корінь «Вибухи на
    # території АТ «Себряковцемент» у Волгоградській області» місця не має,
    # «після вибухів підприємство в диму» відповідає на нього раніше, ніж
    # пост із координатами відкриє інцидент. Беремо лише пости зі свідченням
    # (наслідок чи обʼєкт): гілка збору коштів із кадром Таганрога не має
    # тягнути туди подяки донатерам.
    def root_of(i):
        seen = set()
        while parents.get(i) is not None and parents[i] in parents and i not in seen:
            seen.add(i)
            i = parents[i]
        return i
    by_root = collections.defaultdict(set)
    for i, js in of_post.items():
        by_root[root_of(i)].update(js)
    for a in loose:
        if not (a["hit"] or a["objs"]):
            continue
        js = by_root.get(root_of(a["id"]), set())
        if len(js) == 1:
            attach(next(iter(js)), a, "reply")

    # Мільйонник і конкретне місце в ньому тієї ж ночі — одне: «Москва після
    # атаки», «небо Москви» і двадцять постів «Капотня … горит НПЗ» — це
    # Капотня, а не дві позначки за 17 км.
    for inc in incs:
        inc["merged"] = False
    for a_ in incs:
        if a_["rec"]["pop"] < 500_000:
            continue
        spots = [b_ for b_ in incs if b_ is not a_ and not b_["merged"]
                 and b_["night"] == a_["night"] and b_["rec"]["pop"] < a_["rec"]["pop"]
                 and hav(a_["pt"], b_["pt"]) <= 35 and any(x["hit"] for x in b_["posts"])]
        if not spots:
            continue
        b_ = max(spots, key=lambda x: (sum(1 for y in x["posts"] if y["hit"]), -x["t0"].timestamp() if x["t0"] else 0))
        ids = {x["id"] for x in b_["posts"]}
        b_["posts"] += [x for x in a_["posts"] if x["id"] not in ids]
        if a_["t0"] and (b_["t0"] is None or a_["t0"] < b_["t0"]):
            b_["t0"] = a_["t0"]
        a_["merged"] = True
    # Одне місце за ніч — одна позначка: дві серії про Туапсе тієї ж ночі
    # (живий репортаж і денне «пекло триває») — один інцидент.
    # (і так само два інциденти тієї ночі ближче за 5 км — Губаха з назви й
    # цех Метафраксу з координат за пів кілометра)
    by_night = collections.defaultdict(list)
    for inc in incs:
        if inc["merged"]:
            continue
        base = next((b for b in by_night[inc["night"]]
                     if b["key"] == inc["key"] or hav(b["pt"], inc["pt"]) <= 5), None)
        if base is None:
            by_night[inc["night"]].append(inc)
            continue
        ids = {x["id"] for x in base["posts"]}
        base["posts"] += [x for x in inc["posts"] if x["id"] not in ids]
        if inc["t0"] and (base["t0"] is None or inc["t0"] < base["t0"]):
            base["t0"] = inc["t0"]
        base["votes"].update(inc["votes"])
        for k2, r2 in inc["recs"].items():
            base["recs"].setdefault(k2, r2)
        inc["merged"] = True
    out = []
    for inc in incs:
        if inc["merged"]:
            continue
        res = _finish(inc, places, point_region, depth_km, front_km)
        if res:
            out.append(res)
    # Порядок — як у драйвера злиття (`mergejsonl.py`, ключ `id`): інакше
    # злитий файл відрізнявся б від зібраного, хоч дані ті самі.
    out.sort(key=lambda x: (x["night"], x["id"]))
    return out


def _nearest_city(places, pt):
    """Місто для точних координат: найбільше серед близьких. «58.897,57.573»
    (цех Метафраксу) — Губаха, а не її селище Углеуральський за 3 км."""
    seen, near = set(), []
    for lst in places.noun.values():
        for words, r in lst:
            if id(r) in seen:
                continue
            seen.add(id(r))
            d = hav(pt, (r["lat"], r["lon"]))
            if d <= 60:
                near.append((d, r))
    if not near:
        return None
    dmin = min(d for d, _ in near)
    close = [(d, r) for d, r in near if d <= max(10.0, 1.5 * dmin)]
    return max(close, key=lambda x: (x[1]["pop"], -x[0]))[1]


def _finish(inc, places, point_region, depth_km, front_km):
    # назва — за голосами; за рівних — перша
    r = inc["rec"]
    if inc["votes"]:
        top = max(inc["votes"].values())
        for k, v in inc["votes"].items():
            if v == top:
                r = inc["recs"][k]
                break
    # інцидент із самих координат: точка — вони, назва — місто поруч
    fixed = None
    if "_city" in r:
        fixed, r = (r["lat"], r["lon"]), r["_city"]
    city = (r["lat"], r["lon"])
    posts = sorted(inc["posts"], key=lambda a: (a["t"], a["id"]))
    # точка: координати з тексту коло міста > курований обʼєкт > місто
    pt, obj_name = fixed or city, None
    for a in ([] if fixed else posts):
        cs = [c for c in a["coords"] if hav(c, city) <= COORD_CITY_KM]
        if cs:
            pt = cs[0]
            break
    else:
        for a in ([] if fixed else posts):
            op = places.object_point(a["sk"], r)
            if op:
                pt, obj_name = op
                break
    la, lo = pt
    depth = depth_km((la, lo))
    reg = point_region(la, lo)
    if depth <= 0 or depth > MAX_KM or (r.get("cc") == "UA" and r["name"] in UA_HELD):
        return None
    # Прифронт — лише коли це тактика: ФПВ, «мідлстрайк» по логістиці,
    # бензовози й колони на ТОТ. Та сама межа, що в `store.tactical`, і
    # так само лише для тактичних постів: склади в Бєлгороді — удар у
    # глибину, хоч місто й за 40 км від кордону.
    if depth <= front_km(reg) and any(TACTICAL_RX.search(a["sk"]) for a in posts):
        return None
    # Наслідок + удар. Пожежа без слова про атаку (опівдні горить
    # підстанція, «Магніт» після вибуху) — ні; але пожежа на НПЗ, нафтобазі,
    # аеродромі — так: «В Тюмені горить Антипінський НПЗ» без «атаки» в
    # тексті — це наслідок удару, інших у цього каналу не буває.
    # Спростування в гілці після останнього наслідку («Upd. Пожежа … не
    # повʼязана з атакою») гасить наслідок
    # (лише справжнє спростування, а не «ймовірно недоліт» до іншого
    # корабля тієї ж серії)
    hit_t = [a["t"] for a in posts if a["hit"]]
    neg_t = [a["t"] for a in posts if NEG_STRONG.search(a["sk"])]
    if hit_t and neg_t and max(neg_t) >= max(hit_t):
        posts_hit = False
    else:
        posts_hit = bool(hit_t)
    strategic = any(set(a["objs"]) & STRATEGIC for a in posts if a["hit"])
    hit = posts_hit and (
        strategic or any(a["attack"] or a["official"] for a in posts))
    objs = collections.Counter()
    for a in posts:
        if a["hit"] or a["official"]:
            objs.update(a["objs"])
    names = []
    for a in posts:
        for n in a["names"]:
            if n not in names:
                names.append(n)
    conf = ("official" if any(a["official"] and a["hit"] for a in posts)
            else "visible" if hit else "attack")
    t0 = inc["t0"]
    return {
        # перший пост + місто: один пост про два міста відкриває два
        # інциденти («Сіріус … Сочі»), і id мусить їх розрізняти — ним
        # редактор памʼятає покладене, а драйвер злиття зводить рядки
        "id": f"{CHANNEL}/{posts[0]['id']}/{r['name']}",
        "night": inc["night"],
        "t": t0.astimezone(MSK).strftime("%H:%M") if t0 else "",
        "lat": round(la, 5), "lon": round(lo, 5),
        # місто — для підпису (`uknames` відновлює запис за назвою й
        # координатою, як у подій сховища)
        "place": r["name"], "plat": r["lat"], "plon": r["lon"],
        "region": reg, "depth": round(depth),
        "hit": hit, "conf": conf,
        "objs": [o for o, _ in sorted(objs.items(), key=lambda x: (-x[1], x[0]))][:3],
        "names": names[:2], "refinery": obj_name,
        "n": len(posts),
        "src": [{"u": a["url"], "t": a["t"].astimezone(MSK).strftime("%H:%M"),
                 "d": a["t"].astimezone(MSK).strftime("%d.%m"),
                 "k": ("наслідок" if a["hit"] else "атака") + (" (заднім числом)" if a["via"] == "retro" else "")}
                for a in posts],
    }


