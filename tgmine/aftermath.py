def _reg(stems, standalone=()):
    """Область: прикметник + «область/край/республіка» або самостійне слово.
    `lits` — підрядки, без яких шаблон не спрацює (дешевий відсів)."""
    adj = "|".join(stems)
    parts = [rf"\b(?:{adj})\w*\s+(?:обл|кра|респ|ао\b|автоном)"] if stems else []
    parts += [rf"\b(?:{s})" for s in standalone]
    return (re.compile("|".join(parts)), tuple(stems) + tuple(standalone))


