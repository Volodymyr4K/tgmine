def write(incs: list[dict], root: Path, since: str | None = None) -> int:
    """`store/aftermath/<ніч>.jsonl`, по рядку на інцидент. Файли ночей без
    інцидентів видаляються — інакше скасований удар жив би вічно."""
    d = Path(root) / "store" / "aftermath"
    d.mkdir(parents=True, exist_ok=True)
    by = collections.defaultdict(list)
    for x in incs:
        # на диск — лише те, що йде на карту: інциденти без наслідку («лунають
        # вибухи») потрібні тільки під час збірки, щоб пояснення заднім
        # числом мали до чого чіплятись; їхні зміни не мають перебудовувати ночі
        if not x["hit"] or (since and x["night"] < since):
            continue
        by[x["night"]].append(x)
    changed = 0
    for f in sorted(d.glob("*.jsonl")):
        if f.stem not in by:
            f.unlink()
            changed += 1
    for night, xs in sorted(by.items()):
        body = "".join(json.dumps(x, ensure_ascii=False, sort_keys=True) + "\n" for x in xs)
        f = d / f"{night}.jsonl"
        if not f.exists() or f.read_text(encoding="utf-8") != body:
            f.write_text(body, encoding="utf-8")
            changed += 1
    return changed


def read(root: Path, night: str) -> list[dict]:
    f = Path(root) / "store" / "aftermath" / f"{night}.jsonl"
    if not f.exists():
        return []
    return [json.loads(l) for l in f.read_text(encoding="utf-8").splitlines() if l.strip()]


#: Скільки діб до вікна сховища ще читати: відповіді на старі пости й
#: пояснення заднім числом. Далі — ні: скрапер щогодини дотягує сторінку
#: давньої історії кожного каналу (~500 постів на добу вглиб), і без межі
#: збірка шару повзла б угору разом із сирим.
RAW_MARGIN_DAYS = 30


def load_raw(root: Path, since: str | None = None) -> list[dict]:
    """Сирі пости каналу; з `since` (перша доба сховища) — лише від
    since − RAW_MARGIN_DAYS."""
    f = Path(root) / "data" / f"{CHANNEL}.jsonl"
    if not f.exists():
        return []
    rows = [json.loads(l) for l in f.read_text(encoding="utf-8").splitlines() if l.strip()]
    if since:
        lo = (date.fromisoformat(since) - timedelta(days=RAW_MARGIN_DAYS)).isoformat()
        rows = [p for p in rows if (p.get("date") or "")[:10] >= lo]
    return rows


def main(argv=None):
    """`python3 -m tgmine.aftermath` — перебудувати шар наслідків із сирого
    каналу без перебудови сховища подій; `--list` — показати інциденти."""
    import argparse
    import sys
    ap = argparse.ArgumentParser("aftermath")
    ap.add_argument("--list", metavar="НІЧ", nargs="?", const="",
                    help="надрукувати інциденти (усі або від ночі НІЧ)")
    a = ap.parse_args(argv)
    root = Path(__file__).resolve().parent.parent
    sys.path.insert(0, str(root))
    from . import geocode as GC
    gaz = GC.Gazetteer.load(str(root / "gazetteer" / "RU.txt"), str(root / "gazetteer" / "UA.txt"))
    try:
        targets = json.loads((root / "targets.json").read_text(encoding="utf-8"))
    except FileNotFoundError:
        targets = None
    days = sorted(p.stem for p in (root / "store" / "events").glob("*.jsonl"))
    incs = build(load_raw(root, days[0] if days else None), gaz, targets)
    if a.list is not None:
        for x in incs:
            if x["hit"] and x["night"] >= a.list:
                print(f"{x['night']} {x['t'] or '--:--'} {x['place']:<22} {x['conf']:<8} "
                      f"{', '.join(x['objs']):<30} n={x['n']:<3} {x['id']}")
        return 0
    since = days[0] if days else ""
    ch = write(incs, root, since=since or None)
    print(f"наслідки: інцидентів {len(incs)}, на карту "
          f"{sum(1 for x in incs if x['hit'] and x['night'] >= since)}, змінено файлів ночей {ch}")
    return 0


