def night_of(t: datetime) -> str:
    """Оперативна доба 12:00 -> 12:00 МСК, як у `raid.py`."""
    return (t.astimezone(MSK) - timedelta(hours=12)).date().isoformat()


def _sentences(text: str) -> list[str]:
    """Речення — до розділового знака, а не до переносу: у превʼю t.me/s/
    жирне й посилання рвуть рядок посеред речення («Вранці 11 вересня БПЛА /
    повторно / атакували / … / у Губасі, Пермський край.»)."""
    return [s for s in re.split(r"(?<=[.!?…])\s+", text) if s.strip()]


def _date_of(sent_sk: str, posted: datetime):
    """Дата, про яку каже речення: («night", ніч) для «в ніч на N», («day",
    день) для «N вересня» / «учора». None — дати нема."""
    t = posted.astimezone(MSK)
    m = NIGHT_OF.search(sent_sk)
    if m:
        d = _mkdate(int(m.group(1)), MONTHS[m.group(2)], t)
        return ("night", d - timedelta(days=1)) if d else None
    m = NIGHT_OF_NUM.search(sent_sk)
    if m and 1 <= int(m.group(2)) <= 12:
        d = _mkdate(int(m.group(1)), int(m.group(2)), t)
        return ("night", d - timedelta(days=1)) if d else None
    days = {_mkdate(int(a), MONTHS[b], t) for a, b in DAY_OF.findall(sent_sk)}
    # «09.09.2026», «16.09.26»
    for a, b, y in NUM_DATE.findall(sent_sk):
        try:
            days.add(date(2000 + int(y) % 100, int(b), int(a)))
        except ValueError:
            pass
    for a, b in NUM_DM.findall(sent_sk):
        if 1 <= int(b) <= 12:
            days.add(_mkdate(int(a), int(b), t))
    days.discard(None)
    days.discard(None)
    # сьогоднішня дата — не заднє число: «Ураження … 06.07.2026» о 14:00
    # 06.07 — це репортаж, ніч за часом поста
    days.discard(t.date())
    if len(days) == 1:
        return ("day", days.pop())
    if len(days) > 1:
        return ("many", None)
    # «Учора Генштаб повідомив про Московський НПЗ» — учора звіт, а не
    # удар: дата невідома, пояснення шукає свій удар за тиждень
    if _YESTERDAY.search(sent_sk) and not REPORTED.search(sent_sk):
        return ("day", t.date() - timedelta(days=1))
    # Пост пополудні про «сьогодні вночі / зранку / после ночной атаки» —
    # про ніч, що вже скінчилась: оперативна ніч D-1, а не поточна D.
    if t.hour >= 12 and LAST_NIGHT.search(sent_sk):
        return ("night", t.date() - timedelta(days=1))
    return None


def _mkdate(d, m, t):
    """Дата без року: рік поста, а якщо так виходить майбутнє — минулий."""
    try:
        x = date(t.year, m, d)
    except ValueError:
        return None
    if x > t.date() + timedelta(days=1):
        try:
            x = date(t.year - 1, m, d)
        except ValueError:
            return None
    return x


def _pick(alts, coords, regs, context, sk, places, point_region, depth_km):
    """Тезки: котрий із записів. Порядок доказів: точні координати поста
    поруч; названа область; місто інциденту батька поруч; НПЗ із переліку
    поруч, коли пост каже «НПЗ» («Словʼянський НПЗ» — Кубань, а не
    Словʼянськ); не підконтрольна Україні територія (канал пише про удари по
    РФ і ТОТ); населення."""
    if len(alts) == 1:
        return alts[0]

    def score(r):
        pt = (r["lat"], r["lon"])
        return (
            not any(hav(pt, c) <= COORD_CITY_KM for c in coords),
            not (regs and point_region(r["lat"], r["lon"]) in regs),
            not any(hav(pt, c) <= SMALL_KM for c in context),
            not (OIL.search(sk) and places.near_oil(pt)),
            depth_km is not None and depth_km(pt) <= 0,
            # театр (європейська РФ, Кавказ, Урал і ТОТ) важить більше за
            # населення: «Гвардійське» — кримська авіабаза, а не Гвардейськ
            # під Калінінградом; «Каспійськ» — Дагестан (42.9° пн.), а не
            # Лагань, чия стара назва «Каспийский»
            not (41.0 <= pt[0] <= 62.0 and 22.0 <= pt[1] <= 70.0),
            -r["pop"], r["lat"], r["lon"])
    return min(alts, key=score)


def analyse(p: dict, places: Places, point_region, context=(), depth_km=None) -> dict:
    """Що каже пост: місця (з ознакою «заднім числом» для кожного), обʼєкти,
    наслідок, заперечення, офіційність, точні координати."""
    text = p.get("text") or ""
    sk = skel(text)
    t = datetime.fromisoformat(p["date"])
    regs = regions_in(sk)
    sents = _sentences(text)
    # Дата й заднє число — за реченням, де стоїть місце: «Самара сьогодні
    # вранці… / Учора Генштаб повідомив… Московський НПЗ» — Самара жива,
    # Москва — пояснення.
    spans, pos = [], 0
    for s in sents:
        i = text.find(s, pos)
        spans.append((i, i + len(s), s))
        pos = i + len(s)
    whole_retro = bool(RETRO.search(sk))
    # Річниця — спогад усім постом: «Сьогодні рік, як… "Павутина"… аеродром
    # "Бєлая" у вогні» відкривав удар у реченні без слова «рік».
    anniversary = bool(ANNIV.search(sk))
    # Дата, названа в пості один раз, стосується всього поста: «2-го вересня
    # ми повідомляли про пожежу … під Пермі … у Лядах».
    post_when = _date_of(sk, t)
    if post_when and post_when[0] == "many":
        post_when = None
    short = len(text) <= 100
    post_event = bool(ANCHOR.search(sk) or HIT.search(sk) or RAW_ANCHOR.search(text))

    memo = {}

    def sent_hit(at):
        """Наслідок у тому ж реченні, що й місце."""
        for a, b, s in spans:
            if a <= at < b:
                return bool(HIT.search(NOT_HIT.sub(" ", skel(s))))
        return False

    def sent_regions(at):
        """Області, названі в тому ж реченні, що й місце."""
        for a, b, s in spans:
            if a <= at < b:
                return regions_in(skel(s))
        return []

    def sent_info(at):
        for a, b, s in spans:
            if a <= at < b:
                if a in memo:
                    return memo[a]
                ss = skel(s)
                # Місце без події поруч — не привід відкривати інцидент:
                # «Москва ляже» під звітом про генерала на ТОТ, «напрямками —
                # Москва, Петербург» у пості про авіакомпанії. Короткий пост
                # («Капотня.», «Нижнекамск.») — сам собі подія: він у серії.
                # Рядок-підпис («… на території Камського заводу масел.
                # Пермь.») — місце всього поста: подію бере з поста.
                dateline = len(_TOK.findall(s)) <= 3
                anchored = short or bool(ANCHOR.search(ss) or HIT.search(ss) or RAW_ANCHOR.search(s)
                                         or _OBJ_ANY.search(ss)) or (dateline and post_event)
                memo[a] = (bool(RETRO.search(ss)), _date_of(ss, t) or post_when, anchored)
                return memo[a]
        return whole_retro, post_when, short

    coords = coords_in(text)
    ms = places.mentions(text)
    near = [(m["rec"]["lat"], m["rec"]["lon"]) for m in ms] + list(context)
    # зайняті слова: і сама згадка, і перші слова складеної назви («Набережні
    # Челни» — не село Набережний у Татарстані)
    spans_taken = [(m.get("pos0", m["pos"]), m["pos"]) for m in ms]
    ms += [m for m in places.small_mentions(text, near, regs, point_region)
           if not any(a <= m["pos"] <= b for a, b in spans_taken)]
    out = []
    for m in ms:
        r = _pick(m.get("alts") or [m["rec"]], coords, regs, context, sk,
                  places, point_region, depth_km)
        # Пост назвав область, а жоден тезка в ній не лежить — це не те місце:
        # «аеродром у Гвардейському, Крим» не може бути Гвардейськом під
        # Калінінградом. Краще без місця, ніж за тисячу кілометрів.
        sregs = sent_regions(m["pos"])
        if sregs and point_region(r["lat"], r["lon"]) not in sregs and not context and \
                not any(hav((r["lat"], r["lon"]), c) <= COORD_CITY_KM for c in coords):
            continue
        # Пост дав координати, а назване місто далеко від них — тезка не
        # той: «Коледино … 55.386, 37.586» — не Коледино за 55 км. Беремо
        # тезку коло координат; нема — без міста (візьмуть координати).
        if coords and min(hav((r["lat"], r["lon"]), c) for c in coords) > COORD_CITY_KM:
            near = places.near_same(m["tok"], coords)
            if near is None:
                continue
            r = near
        # Відповідь у гілці: тезка коло інциденту батька важить більше за
        # далекого великого. «Соф'їно» у гілці про Підмосков'я — Софьино під
        # Раменським, а не Софино в Ярославській.
        rr = point_region(r["lat"], r["lon"])
        if context and min(hav((r["lat"], r["lon"]), c) for c in context) > SMALL_KM and \
                rr not in regs and all(point_region(*c) != rr for c in context):
            near = places.near_same(m["tok"], context)
            if near is not None:
                r = near
        retro, when, anchored = sent_info(m["pos"])
        if when and when[0] == "many":
            when = None
        out.append({"rec": r, "how": m["how"], "retro": retro or bool(when) or anniversary,
                    "when": when, "tok": m["tok"], "anchored": anchored,
                    "hit_here": sent_hit(m["pos"])})
    # Два місця одного поста ближче за 20 км — одне місце, і конкретніше
    # з них менше: «Санкт-Петербург … склад у Шушарах» — Шушари, «Дзержинский,
    # Люберцы … ТЭЦ-22» — Дзержинський, «Анапа … Витязево» — Витязево.
    keep = []
    for x in sorted(out, key=lambda x: (x["rec"]["pop"], x["rec"]["name"])):
        pt = (x["rec"]["lat"], x["rec"]["lon"])
        twin = next((k for k in keep if hav(pt, (k["rec"]["lat"], k["rec"]["lon"])) <= 20), None)
        if twin is None:
            keep.append(x)
        else:
            twin["anchored"] = twin["anchored"] or x["anchored"]
            twin["hit_here"] = twin["hit_here"] or x["hit_here"]
            twin["retro"] = twin["retro"] and x["retro"]
    order = {id(x): i for i, x in enumerate(out)}
    out = sorted(keep, key=lambda x: order[id(x)])
    # Єдине місце поста — місце всієї події поста: «Туапсе станом на ранок.
    # … резервуари не вибухнули … коли все догорить». Але не тоді, коли пост
    # називає іншу область: «Москва ляже» під звітом про ТОТ Донеччини.
    if len(out) == 1 and not out[0]["anchored"] and post_event:
        rg = point_region(out[0]["rec"]["lat"], out[0]["rec"]["lon"])
        if not regs or rg in regs:
            out[0]["anchored"] = True
    # Друге й далі місто поста відкриває удар, лише коли наслідок — у його ж
    # реченні: «Ураження Сизранського НПЗ … (як на Омському НПЗ)» — удар по
    # Сизрані, а Омськ — порівняння.
    for x in out[1:]:
        if x["anchored"] and not x["hit_here"]:
            x["anchored"] = False
    # Дрібне місце поза областями, які пост назвав, — тезка не з того кінця
    # країни: «…Запорожской области. Мост … в районе села Владимировка» —
    # не Володимирівка на Донеччині.
    if regs and not context:
        out = [x for x in out if x["rec"]["pop"] >= 300_000
               or point_region(x["rec"]["lat"], x["rec"]["lon"]) in regs
               or any(hav((x["rec"]["lat"], x["rec"]["lon"]), c) <= COORD_CITY_KM for c in coords)]
    objs = objects_in(sk)
    # «завод» — лише коли нема конкретнішого
    if len(objs) > 1 and "завод" in objs:
        objs.remove("завод")
    names = []
    for m in _OBJ_NAME.finditer(text):
        n = m.group(1).strip()
        if n not in names:
            names.append(n)
    neg = bool(NEG.search(sk))
    return {"id": p["id"], "t": t, "url": p.get("url") or f"https://t.me/{CHANNEL}/{p['id']}",
            "places": out, "regions": regs, "objs": objs, "names": names[:2],
            "hit": bool(HIT.search(NOT_HIT.sub(" ", sk))) and not neg, "neg": neg,
            "official": bool(OFFICIAL.search(sk) or RAW_OFFICIAL.search(text)), "coords": coords,
            "retro": whole_retro or bool(post_when), "when": post_when, "sk": sk,
            "event": post_event, "attack": bool(ATTACKW.search(sk) or RAW_ANCHOR.search(text))}


