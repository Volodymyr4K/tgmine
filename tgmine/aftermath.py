#: Імʼя перед прізвищем: «губернатора Олександра Соколова» — не Соколовий.
FIRST_NAME = re.compile(r"^(?:олександр|александр|серги|серге|володимир|владимир|андри|андре|дмитр|"
                        r"олекс|алекс|михайл|михаил|иван|микол|никола|виктор|юри|евген|игор|"
                        r"павл|павел|роман|антон|вадим|максим|денис|артем|олег|валери|анатол|"
                        r"генади|рустам|радий|ренат|гл[еи]б|кирил|станислав|вячеслав|борис|"
                        r"петр|федор|федир|григор|леонид|рамзан|мих)")
#: Слово перед назвою, після якого вона — маршрут, а не місце удару:
#: «забезпечує експорт через порт Приморськ», «у напрямку порту Приморськ».
ROUTE = re.compile(r"^(?:через|напрям\w*|направлен\w*|транзит\w*|експорт\w*)$")
TITLE = re.compile(r"^(?:адмирал|генерал|фрегат|крейсер|корабел|корабл|палац|дворец|"
                   r"дворц|позивн|позивн|майор|полковник|лейтенант|командир|мини|"
                   r"имени|вулиц|улиц|проспект|пр)$")
#: Лапки: усе в них — назва обʼєкта, корабля, ракети чи цитата, а не місце:
#: «Ангара» — ракета, а не Перевальне; “родившийся в Казани” — цитата.
QUOTED = re.compile(r"«[^»]{0,200}»|“[^”]{0,200}”|\"[^\"]{0,200}\"|„[^“”]{0,200}[“”]")


AIRFIELD_Q = re.compile(r"(?:аеродром|аэродром|авіабаз|авиабаз|аеропорт|аэропорт)\w*\s*$", re.I)


def _tokens(text):
    # «аеродромі «Борисоглєбськ»» — назва аеродрому і є місцем
    quoted = [m.span() for m in QUOTED.finditer(text)
              if not AIRFIELD_Q.search(text[max(0, m.start() - 25):m.start()])]
    out = []
    for m in _TOK.finditer(text):
        if any(a <= m.start() < b for a, b in quoted):
            continue
        out.append((m.group(0), m.start()))
    return out


_NOT_STEMS = None


#: Прикметник у переліку областей: «у Донецькій, Луганській областях»,
#: «Донецької та Луганської областей».
_ADJ_LIST = re.compile(r"\w+к(ий|ой|ои|ая|ую|ом|ого|ому|им|их)$")


def _before_region(sks, i):
    """Слово стоїть перед «область/край/регіон», можливо через перелік
    прикметників: тоді це назва області, а не однойменне селище
    («Донецькій» — не Донецький, «Ярославському регіоні» — не Ярославський)."""
    if i + 1 < len(sks) and REGION_WORD.match(sks[i + 1]):
        return True
    # перелік — лише від прикметника («В Курске и области» — місто Курськ) і
    # лише в тому самому відмінку: «у Каменськ-Шахтинському Ростовської
    # області» — місто, а за ним область у родовому
    m = _ADJ_LIST.match(sks[i])
    if not m:
        return False
    j = i + 1
    while j < len(sks) and j <= i + 4:
        if REGION_WORD.match(sks[j]):
            return True
        n = _ADJ_LIST.match(sks[j])
        # перелік не повторює того самого слова: «Станица Луганская, Луганская
        # область» — станиця й область
        if sks[j] in ("та", "и", "і", "й", "або", "или") or (
                n and n.group(1) == m.group(1) and sks[j] != sks[i]):
            j += 1
            continue
        return False
    return False


def _stopword(sk):
    """Стоп-слово в будь-якому відмінку: «Волги», «Криму», «Медведєва»."""
    global _NOT_STEMS
    if _NOT_STEMS is None:
        _NOT_STEMS = set()
        for w in NOT_PLACES:
            _NOT_STEMS |= _noun_stems(w)
    return any(sk[:k] in _NOT_STEMS and (sk[k:] in NOUN_END or sk[k:] in ADJ_END)
               for k in range(max(2, len(sk) - 3), len(sk) + 1))


def _candidate(tok, sk, text, pos, toks, sks, i):
    """Чи може слово бути назвою місця взагалі."""
    if len(sk) < 3 or _stopword(sk):
        return False
    # абревіатури: НПЗ, ГРЕС («Гресівський»), ССО, ППД
    if len(tok) <= 5 and tok.isupper():
        return False
    if i > 0 and TITLE.match(sks[i - 1]):
        return False
    if i > 0 and toks[i - 1][0][:1].isupper() and FIRST_NAME.match(sks[i - 1]):
        return False
    if any(ROUTE.match(x) for x in sks[max(0, i - 3):i]):
        return False
    return True


#: Іменник, до якого прикметник-назва чіпляється в цьому каналі:
#: «Московський НПЗ», «Ударні БПЛА», «московські ППОшники», «Кієвскій режим».
NEXT_NOUN = re.compile(r"^(?:ударник|дрон|бпла|пошник|по$|пво|реб|режим|купол|неб|"
                       r"ракет|авиац|флот|губер|мер|суд|телевиз|паблик|канал|жител|"
                       r"мешкан|житл|вокзал|аеро|мор|узбереж|берег|залив|затоц|"
                       r"заток|озер|ричк|рек|водосх|проспект|шосе|улиц|вулиц|булвар|"
                       r"переул|провул|площ|трас|развяз|розвяз|мист|мост|полуостр|пивостр|"
                       r"напрям|направлен|фронт|угрупов|групиров)")


def _punct_after(text, toks, i):
    tok, pos = toks[i]
    if i + 1 >= len(toks):
        return True
    return bool(re.search(r"[,.:;!?()\n—–/]", text[pos + len(tok):toks[i + 1][1]]))


def _modifies(toks, sks, i):
    """Прикметник-назва стоїть перед своїм іменником («Московський НПЗ»,
    «Ударні БПЛА»), а не окремо («Дзержинский, Люберцы», «у Жуковському
    лунають вибухи»)."""
    if i + 1 >= len(toks):
        return False
    nt, nsk = toks[i + 1][0], sks[i + 1]
    if nt.isupper() and len(nt) <= 6:
        return True
    return bool(NEXT_NOUN.match(nsk) or _OBJ_ANY.search(nsk))


_PLACES: dict = {}


class Places:
    """Покажчик населених пунктів для каналу наслідків (див. шапку модуля)."""

    def __init__(self, gaz, targets=None):
        self.noun: dict[str, list[tuple]] = collections.defaultdict(list)   # основа -> (слова назви, запис)
        self.adj: dict[str, list[dict]] = collections.defaultdict(list)     # основа прикметника -> записи
        self.small: dict[str, list[dict]] = collections.defaultdict(list)   # основа -> дрібні записи
        # назви-прикметники: основа без закінчення -> записи (відмінки — ADJ_END)
        self.noun_adj: dict[str, list[tuple]] = collections.defaultdict(list)
        self.small_adj: dict[str, list[tuple]] = collections.defaultdict(list)
        # Курований перелік (`refineries.py`) — без OSM-ідентифікатора: НПЗ і
        # нафтотермінали. Селище поруч із таким обʼєктом — у великому
        # покажчику, хоч би й було менше за BIG_POP: Усть-Луга, Приморськ.
        self.oil = [o for o in (targets or {}).get("objects", [])
                    if o.get("cat") in ("refinery", "fuel_depot") and not o.get("osm")]
        # кириличні назви великих міст (кістяк першого слова) — впізнати «свій»
        # НПЗ за назвою (`object_point`); окремо, щоб не чіпати записи газетира
        self.cyr: dict[tuple, set] = collections.defaultdict(set)
        oil_cells = {(round(o["lat"] + dy / 10, 1), round(o["lon"] + dx / 10, 1))
                     for o in self.oil for dy in (-1, 0, 1) for dx in (-2, -1, 0, 1, 2)}
        seen = set()
        for n, recs in gaz.by_name.items():
            for r in recs:
                if r["fclass"] != "P":
                    continue
                big = r["pop"] >= BIG_POP or r["fcode"] in ("PPLA", "PPLA2", "PPLC") or \
                    (r["pop"] >= 500 and (round(r["lat"], 1), round(r["lon"], 1)) in oil_cells)
                words = _words(n)
                if not words or len(words) > 3:
                    continue
                # ключ — уся назва: «Дон умбалне Ростов» (альт-назва іншою
                # мовою) не має гасити просте «Ростов» того ж запису
                key = (tuple(words), id(r))
                if key in seen:
                    continue
                seen.add(key)
                # «Кама», «Республика», «Аэродром» — не місця в цьому каналі
                if len(words) == 1 and _stopword(words[0]):
                    continue
                # назва-прикметник відмінюється як прикметник: «Гвардейское»
                # -> «в Гвардейском», «Жуковский» -> «Жуковского»
                if ADJ_NAME.search(words[-1]) and len(words[-1]) > 5:
                    st = words[-1][:-2]
                    if big:
                        self.noun_adj[st].append((tuple(words), r))
                    elif len(words) == 1:
                        self.small_adj[st].append((tuple(words), r))
                for st in _noun_stems(words[-1]):
                    if big:
                        self.noun[st].append((tuple(words), r))
                        self.cyr[(r["name"], r["lat"], r["lon"])].add(words[0])
                    elif len(words) == 1 and len(st) >= 4:
                        # дрібні — лише однослівні: `small_mentions` інших не
                        # бере, а покажчик і так найбільша частина кешу
                        self.small[st].append((tuple(words), r))
                if big and len(words) == 1:
                    for st in _adj_stems(words[0]):
                        self.adj[st].append(r)
                    # назва-прикметник сама є прикметником: «Ільський НПЗ»
                    # — селище Ільський, «Афіпський НПЗ» — Афіпський
                    if ADJ_NAME.search(words[0]) and len(words[0]) > 5:
                        self.adj[words[0][:-2]].append(r)
        self.abbr = {}
        for a, city in ABBR.items():
            recs = [r for r in gaz.by_name.get(city, []) if r["fclass"] == "P"]
            if recs:
                self.abbr[a] = max(recs, key=lambda r: r["pop"])
        for a, city in ADJ_IRREG.items():
            recs = [r for r in gaz.by_name.get(city, []) if r["fclass"] == "P"]
            recs = recs or [r for r in gaz.by_name.get(city.replace("-", " "), [])
                            if r["fclass"] == "P"]
            if recs:
                self.adj[a].append(max(recs, key=lambda r: r["pop"]))
        # Курований перелік НПЗ (`refineries.py` у targets.json) і аеродроми:
        # координата обʼєкта, коли пост його називає, а він коло міста поста.
        self.refineries, self.airfields = [], []
        for o in (targets or {}).get("objects", []):
            if o.get("cat") == "refinery":
                self.refineries.append(o)
            elif o.get("cat") == "airfield":
                self.airfields.append(o)

    @classmethod
    def load(cls, gaz, targets=None):
        """Покажчик — раз на процес і з кешем на диску поруч із газетиром.
        Будується 10+ с (сотні тисяч назв); щогодинний прогін CI не має
        платити за це щоразу. Ключ — вміст газетира (той самий, що в
        `Gazetteer.load`), цей модуль і курований перелік нафти."""
        import hashlib
        import pickle
        from . import geocode as GC
        oil = sorted((o["name"], o["lat"], o["lon"]) for o in (targets or {}).get("objects", [])
                     if o.get("cat") in ("refinery", "fuel_depot", "airfield"))
        paths = [Path(__file__).resolve().parent.parent / "gazetteer" / f
                 for f in ("RU.txt", "UA.txt")]
        memo = (id(gaz), repr(oil))
        if memo in _PLACES:
            return _PLACES[memo]
        cache = None
        if all(p.exists() for p in paths):
            h = hashlib.sha1(GC._gaz_key([str(p) for p in paths], 0, ("P", "A"), GC.EXTRA).encode())
            h.update(Path(__file__).read_bytes())
            h.update(repr(oil).encode())
            cache = paths[0].parent / ".cache" / f"aft-{h.hexdigest()[:16]}.pkl"
            if cache.exists():
                try:
                    with open(cache, "rb") as f:
                        pl = pickle.load(f)
                    _PLACES[memo] = pl
                    return pl
                except Exception:
                    pass
        pl = cls(gaz, targets)
        _PLACES[memo] = pl
        if cache is not None:
            try:
                cache.parent.mkdir(exist_ok=True)
                for old in cache.parent.glob("aft-*.pkl"):
                    old.unlink()
                tmp = cache.with_suffix(".tmp")
                with open(tmp, "wb") as f:
                    pickle.dump(pl, f, protocol=pickle.HIGHEST_PROTOCOL)
                tmp.replace(cache)
            except OSError:
                pass
        return pl

    # -- розбір тексту -------------------------------------------------

    def mentions(self, text: str) -> list[dict]:
        """Місця поста у порядку появи: {rec, how, i, pos, n, tok, alts}.
        `how`: noun | adj."""
        toks = _tokens(text)
        sks = [skel(t) for t, _ in toks]
        out = []
        for i, (tok, pos) in enumerate(toks):
            sk = sks[i]
            if sk in self.abbr:
                out.append({"rec": self.abbr[sk], "how": "abbr", "i": i, "pos": pos,
                            "n": 1, "tok": tok})
                continue
            cand = _candidate(tok, sk, text, pos, toks, sks, i)
            if not cand and not (len(sk) >= 3 and tok[:1].isupper() and i > 0):
                continue
            cap = tok[:1].isupper()
            nxt_region = _before_region(sks, i)
            hits = [] if nxt_region else self._noun_hits(sk, i, sks)
            # другу частину складеної назви («Усть-Луга», «Ростов-на-Дону»)
            # окремим містом не беремо — лише всю назву
            end = pos + len(tok)
            hyph = (pos > 1 and text[pos - 1] == "-" and text[pos - 2].isalpha()) or \
                (end + 1 < len(text) and text[end] == "-" and text[end + 1].isalpha())
            for words, r in hits:
                if hyph and len(words) == 1:
                    continue
                # стоп-слово окремим містом не буває, але частиною назви —
                # так: «Слов'янськ-на-Кубані», «Ростов-на-Дону»
                if not cand and len(words) == 1:
                    continue
                # Власна назва — з великої літери. Малою пишуть лише
                # мільйонники («на москву», «у москві» — стиль каналу).
                if not cap and r["pop"] < 500_000:
                    continue
                # Селище-прикметник (Московский, Ударный, Самарский)
                # — лише окремим словом: «Московський НПЗ», «Ударні БПЛА»
                # — це прикметники, а не селища.
                if len(words) == 1 and ADJ_NAME.search(words[0]):
                    if _modifies(toks, sks, i):
                        continue
                    # Селище-тезка прикметника великого міста («Донецький» —
                    # «Донецький аеропорт», «Самарский» — «Самарский КНПЗ»):
                    # селище — лише окремим словом, як «Дзержинский, Люберцы».
                    if self._adj_city(sk, r) and not _punct_after(text, toks, i):
                        continue
                out.append({"rec": r, "how": "noun", "i": i, "pos": pos,
                            "pos0": toks[max(0, i - len(words) + 1)][1],
                            "n": len(words), "tok": tok})
            if cand and cap and not nxt_region and not any(m["i"] == i for m in out):
                for st, ends in self._split(sk):
                    if ends not in ADJ_END:
                        continue
                    for r in self.adj.get(st, ()):
                        # прикметник міста — лише перед обʼєктом: «Саратовский
                        # Озон», «Сизранський НПЗ», а не «московські ППОшники»
                        # і не «в Азовському морі» (море — не обʼєкт міста Азов)
                        if i + 1 < len(sks) and NEXT_NOUN.match(sks[i + 1]) and \
                                not _OBJ_ANY.search(sks[i + 1]):
                            continue
                        nxt = " ".join(sks[i + 1:i + 3])
                        if not _OBJ_ANY.search(nxt):
                            continue
                        out.append({"rec": r, "how": "adj", "i": i, "pos": pos, "n": 1,
                                    "tok": tok})
        return self._best(out)

    def small_mentions(self, text: str, near: list[tuple[float, float]],
                       regions: list[str], point_region) -> list[dict]:
        """Дрібні місця (Софьино, Дагомис без населення) — лише коло
        контексту: не далі SMALL_KM від `near` або в названій області."""
        if not near and not regions:
            return []
        out = []
        toks = _tokens(text)
        sks = [skel(t) for t, _ in toks]
        for i, (tok, at) in enumerate(toks):
            sk = sks[i]
            if not tok[:1].isupper() or len(sk) < 5 or not _candidate(tok, sk, text, at, toks, sks, i):
                continue
            if i + 1 < len(sks) and REGION_WORD.match(sks[i + 1]):
                continue
            e = at + len(tok)
            if (at > 1 and text[at - 1] == "-" and text[at - 2].isalpha()) or \
                    (e + 1 < len(text) and text[e] == "-" and text[e + 1].isalpha()):
                continue
            best = None
            for st, ends in self._split(sk):
                cands = []
                if ends in NOUN_END:
                    cands += self.small.get(st, [])
                if ends in ADJ_END:
                    cands += self.small_adj.get(st, [])
                for words, r in cands:
                    if len(words) != 1:
                        continue
                    if ADJ_NAME.search(words[0]) and _modifies(toks, sks, i):
                        continue
                    d = min((hav((r["lat"], r["lon"]), p) for p in near), default=None)
                    ok = (d is not None and d <= SMALL_KM) or (
                        regions and point_region(r["lat"], r["lon"]) in regions)
                    if not ok:
                        continue
                    score = d if d is not None else SMALL_KM * 2
                    if best is None or score < best[0]:
                        best = (score, r)
            if best:
                out.append({"rec": best[1], "how": "small", "i": -1, "pos": at,
                            "n": 1, "tok": tok})
        return out

    def _adj_city(self, sk, town):
        """Чи є слово ще й прикметником міста, більшого за селище вдесятеро."""
        for st, ends in self._split(sk):
            if ends in ADJ_END:
                for r in self.adj.get(st, ()):
                    if r["pop"] >= 10 * max(town["pop"], 1):
                        return True
        return False

    def _split(self, sk):
        for k in range(len(sk), max(1, len(sk) - 4), -1):
            yield sk[:k], sk[k:]

    def _noun_hits(self, sk, i, sks):
        found = []
        for st, end in self._split(sk):
            cands = []
            if end in NOUN_END:
                cands += self.noun.get(st, [])
            if end in ADJ_END:
                cands += self.noun_adj.get(st, [])
            for words, r in cands:
                # коротка основа («уф» від «Уфі») — лише для великих міст;
                # у складеній назві («Усть-Лузі») її тримає перше слово
                if len(st) < 4 and r["pop"] < 300_000 and len(words) == 1:
                    continue
                if len(words) > 1:
                    # багатослівна назва: попередні слова — за початком
                    # («Нижньому Новгороді», «Новий Уренгой»)
                    prev = sks[max(0, i - len(words) + 1):i]
                    # перші дві літери: «Слов'янськ» / «Славянск» у кістяку
                    # різняться вже третьою
                    if len(prev) != len(words) - 1 or not all(
                            p[:2] == w[:2] for p, w in zip(prev, words[:-1])):
                        continue
                found.append((words, r))
        return found

    @staticmethod
    def _best(ms):
        """Один запис на згадку: багатослівний збіг важить більше за
        однослівний («Новий Уренгой», а не село «Уренгой»); далі — населення.
        Тезки лишаються кандидатами (`alts`) для області й контексту."""
        by = collections.defaultdict(list)
        covered = set()
        for m in ms:
            by[m["i"]].append(m)
            if m["n"] > 1:
                covered.update(range(m["i"] - m["n"] + 1, m["i"]))
        out = []
        for i in sorted(by):
            # «Новий Уренгой»: слово «Новий» — частина назви, а не селище
            if i in covered:
                continue
            group = sorted(by[i], key=lambda m: (-m["n"], -m["rec"]["pop"],
                                                 m["rec"]["lat"], m["rec"]["lon"]))
            top_n = group[0]["n"]
            alts = [m["rec"] for m in group if m["n"] == top_n]
            out.append({**group[0], "alts": alts})
        return out

    def near_same(self, tok, context):
        """Запис із тією ж назвою (будь-якого розміру) не далі SMALL_KM від
        контексту — найближчий."""
        sk, best = skel(tok), None
        for st, ends in self._split(sk):
            cands = []
            if ends in NOUN_END:
                cands += self.noun.get(st, []) + self.small.get(st, [])
            if ends in ADJ_END:
                cands += self.noun_adj.get(st, []) + self.small_adj.get(st, [])
            for words, r in cands:
                if len(words) != 1:
                    continue
                d = min(hav((r["lat"], r["lon"]), c) for c in context)
                if d <= SMALL_KM and (best is None or d < best[0]):
                    best = (d, r)
        return best[1] if best else None

    def near_oil(self, pt, km=OBJ_CITY_KM):
        """НПЗ чи нафтотермінал із курованого переліку поруч: «Приморськ …
        нафтопорт» — Ленінградська, а не Приморськ на Запоріжжі."""
        return any(hav(pt, (o["lat"], o["lon"])) <= km for o in self.oil)

    # -- обʼєкти з координатою -----------------------------------------------

    def object_point(self, text_sk: str, city: dict):
        """Координата обʼєкта коло міста: НПЗ із курованого переліку чи
        аеродром. None — лишається місто."""
        c = (city["lat"], city["lon"])
        if re.search(OBJECTS[0][1], text_sk):
            # НПЗ цього міста: у назві місто («Куйбишевський НПЗ (Самара)»)
            # або він поруч — не найближчий у 40 км (Чапаєвськ ставав на НПЗ
            # Новокуйбишевська)
            stems = {w[:5] for w in self.cyr.get((city["name"], city["lat"], city["lon"]), ())}
            near = [(hav(c, (o["lat"], o["lon"])), o) for o in self.refineries]
            near = [x for x in near if x[0] <= 12 or (
                x[0] <= OBJ_NAMED_KM and any(st in skel(x[1]["name"]) for st in stems))]
            if near:
                o = min(near, key=lambda x: (x[0], x[1]["name"]))[1]
                return (o["lat"], o["lon"]), o["name"]
        if re.search(dict(OBJECTS)["аеродром"], text_sk):
            near = [(hav(c, (o["lat"], o["lon"])), o) for o in self.airfields]
            near = [x for x in near if x[0] <= 25]
            if near:
                o = min(near, key=lambda x: (x[0], x[1]["name"]))[1]
                return (o["lat"], o["lon"]), None
        return None


