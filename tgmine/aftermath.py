_APOS = re.compile(r"[’ʼ'`´]")


@functools.lru_cache(maxsize=1 << 18)
def skel(s: str) -> str:
    """Спільний кістяк української й російської: «Нижньокамськ» і
    «Нижнекамск» ще різні, але «Саратові»/«Саратове», «Сизрань»/«Сызрань»,
    «Тольятті»/«Тольятти», «Новоросійськ»/«Новороссийск» зводяться до
    однакового. і/ы/и -> и, є/э/ё -> е, ї -> и, ь/ъ/апостроф геть, подвоєні
    літери — одна."""
    s = _APOS.sub("", s.lower())
    s = s.translate(str.maketrans({"ё": "е", "є": "е", "э": "е", "ї": "и", "і": "и",
                                   "ы": "и", "ґ": "г", "ь": None, "ъ": None}))
    # лише літери: «11 вересня» не має ставати «1 вересня»
    return re.sub(r"([^\W\d_])\1+", r"\1", s)


