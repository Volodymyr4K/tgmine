def _noun_stems(sk: str) -> set[str]:
    out = {sk}
    if sk[-1:] in "аяоеийу":
        out.add(sk[:-1])
    # чергування перед «-і» в українському місцевому: Таганрог -> Таганрозі,
    # Губаха -> Губасі, Кременчук -> Кременчуці
    for a, b in (("г", "з"), ("к", "ц"), ("х", "с")):
        if sk.endswith(a):
            out.add(sk[:-1] + b)
        if sk.endswith(a + "а"):
            out.add(sk[:-2] + b)
    # випадне «е/о»: Орел -> Орла, Кстово ні
    m = re.match(r"^(.*[^аеиоуя])[ео]([лкц])$", sk)
    if m:
        out.add(m.group(1) + m.group(2))
    return {s for s in out if len(s) >= 2}


def _adj_stems(sk: str) -> set[str]:
    """Основа прикметника міста: «саратов» -> «саратовск», «курск» -> «курск»,
    «сизран» -> «сизранск», «таганрог» -> «таганрогск»/«таганрозк»,
    невідмінювані «нерюнгри» -> «нерюнгринск», «сочи» -> «сочинск»."""
    if sk.endswith(("ск", "цк")):
        return {sk}
    if sk[-1:] in "иоеу":
        return {sk + "нск", sk[:-1] + "ск"}
    base = sk[:-1] if sk[-1:] in "аяоеиу" else sk
    out = {base + "ск"}
    for a, b in (("г", "з"), ("к", "ц"), ("х", "с")):
        if base.endswith(a):
            out.add(base[:-1] + b + "к")
    return out


