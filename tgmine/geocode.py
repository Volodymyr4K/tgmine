"""Офлайн-геокодування топонімів через дамп GeoNames.

Три проблеми, які тут вирішуються:
  1. Омоніми — «Троицкое» в РФ десятки штук. Розвʼязуємо контекстом: якщо в тому ж
     пості є регіон, беремо найближчий до нього НП; інакше — найбільший за населенням.
  2. Відмінки й прикметникові форми — «Шебекинский район» проти «Шебекино» в базі.
  3. Райони — «Крымский район» це не місто Крымск; шукаємо і серед адмінодиниць.
"""
from __future__ import annotations

import collections
import math
import pathlib
import re
import unicodedata

# GeoNames: 1=name 3=alternatenames 4=lat 5=lon 6=class 7=code 8=country 14=population
NAME, ALT, LAT, LON, FCLASS, FCODE, CC, ADM1, POP = 1, 3, 4, 5, 6, 7, 8, 10, 14

# Навмисно БЕЗ і/ї/є/ґ, попри назву. Фільтр вирішує, які альтернативні назви з
# газетира взагалі потраплять в індекс, і для російськомовного корпусу вужчий
# індекс точніший.
#
# Перевірено на даних, а не на око: у 25 956 запитах НП з трьох каналів рівно 0
# містять українські літери — канали пишуть «Кривой Рог», не «Кривий Ріг».
# Розширення фільтра додає 21 989 ключів (41.9% альт-назв UA.txt) і змінює
# 19 з 25 956 прив'язок: 9 краще (Галициновка -250 км помилки), 3 гірше
# (сміттєві запити «Над Качей» починають резолвитись у вигадану точку за 500 км),
# 7 неоднозначних. Чистий ефект близький до нуля, тому лишаємо як є.
#
# Переглянути, якщо в конвеєр заведуть україномовний канал із розбором НП:
# configs/ua-air.yaml зараз витягує лише назви областей, а вони резолвляться
# через cfg.geo, не через газетир — тому й там фільтр не заважає.
CYRILLIC = re.compile(r"^[а-яё\s\-']+$", re.I)
PUNCT = re.compile(r"[^\w\s-]", re.UNICODE)

# Знаки наголосу й латинські двійники в кириличних альт-назвах GeoNames.
# «Че́рнский райо́н», «Вя́земский райо́н», «Венëвский» (латинська ë) фільтр
# CYRILLIC відкидав цілком — і район для геокода не існував: так зникали 149
# районів (Чернский, Ершичский, Вяземский, Узловский, Дубенский, Ельнинский…),
# які BACKLOG §3 вважав діркою в GeoNames. Латиницю міняємо лише в слові, де
# решта літер кирилична, — англійська назва кириличною не стає.
_ACCENTS = dict.fromkeys(map(ord, "\u0300\u0301\u0306\u0308"), None)
_HOMO = str.maketrans("aceopxyёëABCEHKMOPTXY", "асеорхуеeАВСЕНКМОРТХУ")


def clean_alt(x: str) -> str:
    x = unicodedata.normalize("NFD", x)
    # «й» у NFD — це «и» + U+0306; повертаємо її до знімання знаків
    x = x.replace("и\u0306", "й").replace("И\u0306", "Й")
    x = x.translate(_ACCENTS)
    x = unicodedata.normalize("NFC", x)
    if re.search(r"[а-яА-Я]", x) and re.search(r"[a-zA-Zë]", x):
        x = x.translate(_HOMO)
    return x

# прикметник -> ймовірна основа НП: "шебекинский" -> "шебекин"
#
# Непрямі відмінки (-ского, -ским, -ских, -скую, -цкого, -цкой…) додано 21
# вересня 2026 (BACKLOG §4): без них «валуйского» давало стем «валуйск», а
# ключ «валуйский район» — «валуй», і вони не зустрічались у жодному кошику.
# «Аннинским районом», «Погарского района», «Унечским» падали на центр області.
ADJ_SUFFIX = re.compile(r"(ского|скому|ским|ских|скую|ский|ская|ское|ские|ской|ском|"
                        r"цкого|цкому|цким|цких|цкую|цкий|цкая|цкое|цкие|цкой|цком)$")
# Форми, у яких російською називають саму область: «Харьковская»,
# «Николаевской». Лише для винятку ADM1 у `lookup`.
REGION_ADJ = re.compile(r"(ский|ская|ское|ские|цкий|цкая|цкое|ской|скому|ском)$")
CASE_SUFFIX = re.compile(r"(ого|ому|ыми|ами|ой|ей|ом|ым|ах|ях|у|е|а|ы|и|о)$")


def norm(s: str) -> str:
    s = PUNCT.sub(" ", s.lower().replace("ё", "е"))
    return re.sub(r"\s+", " ", s).strip()


def haversine(a, b):
    R = 6371.0
    la1, lo1, la2, lo2 = map(math.radians, (*a, *b))
    h = (math.sin((la2 - la1) / 2) ** 2 +
         math.cos(la1) * math.cos(la2) * math.sin((lo2 - lo1) / 2) ** 2)
    return 2 * R * math.asin(math.sqrt(h))


# Театр дій: європейська частина РФ + ТОТ. За цією рамкою збіг назви майже
# завжди означає сибірського тезку, а не реальну ціль: Angarsk за 4400 км від
# кордону — це не удар, це помилка розвʼязання омоніма.
#
# Рамка діє ТІЛЬКИ для пошуку без області (фолбек за населенням, якір).
# Коли пост назвав область, `lookup` шукає навколо неї без рамки — інакше
# Урал і Західний Сибір (Єкатеринбург 60.6°, Новий Уренгой 76.6°) не
# знаходились узагалі, хоч область у пості стояла явно.
THEATER = (43.0, 61.0, 22.0, 60.0)   # lat_min, lat_max, lon_min, lon_max


def in_box(lat, lon, box=THEATER):
    return box[0] <= lat <= box[1] and box[2] <= lon <= box[3]


# Російські назви з Wikidata для записів GeoNames, де кириличної назви нема
# (tools/wd_names.py, зʼєднання за geonameid, P1566). Відсутній файл — не
# помилка: газетир працює як раніше.
EXTRA = pathlib.Path(__file__).resolve().parent.parent / "refdata" / "wikidata_ru.tsv"


def _load_extra(path) -> dict[str, list[str]]:
    out = {}
    if not path or not pathlib.Path(path).exists():
        return out
    with open(path, encoding="utf-8") as f:
        for line in f:
            gid, _, names = line.rstrip("\n").partition("\t")
            ok = [y for y in map(clean_alt, names.split("|")) if CYRILLIC.match(y)]
            if ok:
                out[gid] = ok
    return out


class Gazetteer:
    def __init__(self):
        self.by_name: dict[str, list[dict]] = collections.defaultdict(list)
        self.stems: dict[str, list[str]] = collections.defaultdict(list)
        # Індекс за повним коренем. Окремий від stems, бо 7-літерний стем сам
        # собі не транзитивний: «гвардейского» дає «гвардей», а «гвардейское»
        # — «гвард» (з нього встигає зрізатись ще й «ей»), і два відмінки тієї
        # самої назви не зустрічались у жодному спільному кошику.
        self.roots: dict[str, list[str]] = collections.defaultdict(list)
        self.adm1: list[dict] = []       # записи ADM1 — для region_codes()
        # корені власних прикметникових назв субʼєктів, на набір кодів ADM1
        self._self_roots: dict[frozenset, set[str]] = {}

    @classmethod
    def load(cls, *paths, min_pop: int = 0, classes=("P", "A"),
             extra=EXTRA) -> "Gazetteer":
        g = cls()
        extra_names = _load_extra(extra)
        for path in paths:
            with open(path, encoding="utf-8") as f:
                for line in f:
                    c = line.rstrip("\n").split("\t")
                    if len(c) < 15 or c[FCLASS] not in classes:
                        continue
                    if c[FCLASS] == "A" and not c[FCODE].startswith("ADM"):
                        continue
                    try:
                        pop = int(c[POP] or 0)
                        lat, lon = float(c[LAT]), float(c[LON])
                    except ValueError:
                        continue
                    if pop < min_pop and c[FCLASS] == "P":
                        pass  # дрібні села лишаємо: саме вони й згадуються
                    rec = {"name": c[NAME], "lat": lat, "lon": lon, "pop": pop,
                           "cc": c[CC], "fclass": c[FCLASS], "fcode": c[FCODE],
                           "a1": c[ADM1]}
                    names = {c[NAME]}
                    names.update(y for y in map(clean_alt, c[ALT].split(","))
                                 if CYRILLIC.match(y))
                    names.update(extra_names.get(c[0], ()))
                    if c[FCODE] in ("ADM1", "ADM1H"):
                        g.adm1.append({**rec, "alts": list(names)})
                    for n in names:
                        n = norm(n)
                        if len(n) >= 3:
                            g.by_name[n].append(rec)
        for n in g.by_name:
            for st in _stems(n):
                g.stems[st].append(n)
            for rt in _roots(n):
                g.roots[rt].append(n)
        return g

    def candidates(self, query: str, box=THEATER, wide: bool = False) -> list[dict]:
        """Кандидати на запит.

        wide=False (типово) — точна назва, і лише якщо її нема, морфологічні
        варіанти за стемом. Саме так шукалось завжди; звужений набір потрібен,
        бо відбір зважує населення, і зайвий великий тезка з чужої області
        перемагає правильне село.

        wide=True — ОБ'ЄДНАННЯ точних і стемових. Точний збіг замикав пошук
        накоротко, тому «Красногвардейский» бачив лише буквальних тезок (район
        Пітера, pop 337 тис.), а кримський Красногвардейське (Курман) у список
        не потрапляв узагалі: він лежить під ключем «красногвардейское». Так
        само ховалось ростовське Міллерово від «Миллеровский» і бєлгородський
        Красноярузький від «Краснояружский».

        Широкий набір вмикається ТІЛЬКИ під узгодженням топонімів усередині
        поста (`_consensus`): там вибір робить не населення, а близькість до
        точки, на якій зійшлись інші назви, і зайві кандидати нешкідливі.
        Ввімкнути його всюди — виміряно — ламає 16 із 91 еталонів: якірний
        прохід починає чіплятись за великих далеких тезок.
        """
        q = norm(query)
        cands = list(self.by_name.get(q) or [])
        if wide or not cands:
            seen = {id(c) for c in cands}
            keys = [k for st in _stems(q) for k in self.stems.get(st, [])]
            roots = None
            if wide:
                roots = _roots(q)
                keys += [k for rt in roots for k in self.roots.get(rt, [])]
            for key in keys:
                # у широкому наборі 7-літерного префікса замало: звіряємо
                # ще й повний корінь, інакше «красноперекопск» тягне
                # «краснопахорский»
                if roots is not None and not (roots & _roots(key)):
                    continue
                for c in self.by_name[key]:
                    if id(c) not in seen:
                        seen.add(id(c))
                        cands.append(c)
        if box:
            cands = [c for c in cands if in_box(c["lat"], c["lon"], box)]
        return cands

    def _variant_cands(self, q: str, near, box) -> tuple[list, bool]:
        """Точні збіги відмінкових варіантів назви: (кандидати, чи брати місто
        замість області). Лише точні ключі газетира — без основи."""
        ok = lambda c: near or in_box(c["lat"], c["lon"], box)
        if " " not in q:
            # Іменник у непрямому відмінку: «Одессы», «Анапы», «Орла», «Ялты»,
            # «Качи»; прикметникова назва — «Веселого», «Широкого». Короткі
            # назви `_word_stem` не зрізає, тож ні точний, ні стемовий пошук
            # їх не бачив (366 згадок «Одессы» лише за вікно сховища).
            #
            # Лише варіанти, що МІНЯЮТЬ закінчення. Дописування «+ы/+и» (його
            # `_nominatives` має для «от Сум») тут давало сміття: «Шарк» ->
            # Шарки, «Через» -> Черезы. Загальні слова з відмінковим
            # закінченням («Победы», «Силы», «Уйти») за формою від назв не
            # відрізнити — їх відсікає NOT_PLACES.
            for v in _nominatives(q)[1:] + _fleeting(q) + _adj_nominatives(q):
                if v.startswith(q):
                    continue
                # Лише НП чи ціла область (її `_seat_over_region` замінить
                # адмінцентром). «Лимана» інакше ставав Лиманським районом ADM2H.
                c = [c for c in self.by_name.get(v, []) if ok(c)
                     and (c["fclass"] == "P" or c.get("fcode") in ("ADM1", "ADM1H"))]
                if c:
                    return c, True        # «Одессы» — місто, а не область
            if "-" in q:
                # «От Каменки-Днепровской» — кожна частина до називного окремо
                for k in _hyphen_nominatives(q):
                    c = [c for c in self.by_name.get(k, []) if ok(c)]
                    if c:
                        return c, False
        elif q.count(" ") == 1:
            # Складена назва в непрямому відмінку: «Через Великую Лепетиху»,
            # «Малую Белозерку», «Белой Березки», «Нижнего песочного».
            w1, w2 = q.split()
            a = _ADJ_OBL.sub(lambda m: _ADJ_NOM[m.group(1)], w1)
            for b in [w2] + _nominatives(w2)[1:] + _adj_nominatives(w2) + (
                    [w2[:-1] + "а"] if w2.endswith("у") else
                    [w2[:-1] + "я"] if w2.endswith("ю") else []):
                k = f"{a} {b}"
                if k != q and self.by_name.get(k):
                    c = [c for c in self.by_name[k] if ok(c)]
                    if c:
                        return c, False
        return [], False

    def has_compound(self, q2: str) -> bool:
        """Двослівна назва є в газетирі — точно або в називному відмінку.

        Без основи: «Большая группа» за першим словом дістала б «Большая
        Знаменка», а тут питання одне — чи існує саме ця пара слів."""
        k = norm(q2)
        if self.by_name.get(k):
            return True
        w1, _, w2 = k.partition(" ")
        a = _ADJ_OBL.sub(lambda m: _ADJ_NOM[m.group(1)], w1)
        for b in [w2] + _nominatives(w2)[1:] + _adj_nominatives(w2) + (
                [w2[:-1] + "а"] if w2.endswith("у") else []):
            if self.by_name.get(f"{a} {b}"):
                return True
        return False

    def region_codes(self, entities_region: dict, geo: dict) -> dict:
        """Регіон конфіга -> код admin1 у GeoNames, напр. Ростовська -> RU.61.

        Навіщо: досі належність до області вгадувалась за відстанню до її
        центроїда, а область — 300-500 км завширшки, тож відстань не відрізняє
        «всередині цієї області» від «одразу за межею в сусідній». Через це
        «Дмитровский район / Орловская область» ставав однойменним районом
        Москви за 339 км, а «Красносулинский / Ростовская» — Краснослободськом
        за 398 км. admin1 — це фактична належність, не проксі.

        Зіставляємо за КИРИЛИЧНИМИ альт-назвами ADM1-записів, використовуючи ті
        самі патерни регіонів, що вже є в конфізі — окрема ручна таблиця не
        потрібна й не розʼїдеться.

        Не «найближчий ADM1 до центроїда»: перевірено, так помиляється на 3 з 39
        (Костромська -> Іванівська, Татарстан -> Марій Ел, Ленінградська ->
        Санкт-Петербург, який є окремим субʼєктом). За назвою — 39 з 39.

        Повертає МНОЖИНУ кодів на регіон, бо два регіони конфіга покривають по
        два субʼєкти: Крим — це UA.11 плюс Севастополь UA.20, а Московська —
        RU.47 плюс місто Москва RU.48. Спершу тут був один код (найближчий), і
        це мовчки вимикало фільтр саме для двох НАЙБІЛЬШИХ регіонів набору:
        811 і 754 точкових спостережень.
        """
        out = {}
        for reg, rx in entities_region.items():
            hits = [a for a in self.adm1
                    if any(rx.search(x) for x in a["alts"]) or rx.search(a["name"])]
            if not hits:
                continue
            c = geo.get(reg)
            if c:
                hits.sort(key=lambda a: haversine(c, (a["lat"], a["lon"])))
                # Сусідній субʼєкт із тією ж назвою — так, далекий тезка — ні.
                # Найдальший потрібний випадок: Севастополь за 66 км від
                # центроїда Криму; найдальший коректний одиночний — Костромська
                # за 185 км. 300 км лишає запас і не тягне чужих.
                hits = [a for a in hits
                        if haversine(c, (a["lat"], a["lon"])) <= 300] or hits[:1]
            out[reg] = frozenset((a["cc"], a["a1"]) for a in hits)
        return out

    def self_roots(self, codes) -> set[str]:
        """Корені ПРИКМЕТНИКОВИХ власних назв субʼєкта: RU.84 -> {"волгоград"}.

        Навіщо. Область російською називають прикметником, і той прикметник
        через стем дотягується до ОДНОЙМЕННОГО МІСТА: «Волгоградская область»
        -> Волгоград (pop 1 013 533). Для `refine_regions` це виглядало як
        маркер-місто, хоч міста пост не називав узагалі.

        Морфологія тут не критерій — перевірено на корпусі: прикметникових
        збігів, що дали city-marker, 8644, і більшість із них маркери чесні
        («Стародубский район» -> Стародуб, «Симферопольский» -> Сімферополь,
        «Дзержинский» -> Дзержинськ: центр району і є те саме місто). Відрізняє
        не форма слова, а те, чи називає збіг САМУ область.

        Тому корені беруться з альт-назв ADM1 цього ж субʼєкта («Волгоградская
        Область»), і лише з тих, де перше слово прикметникове. Севастополь і
        Москва — теж ADM1, але їхні назви іменникові, тому «Севастопольской
        бухте» маркером лишається.
        """
        out = set()
        for a in self.adm1:
            if (a["cc"], a["a1"]) not in codes:
                continue
            for alt in a["alts"]:
                w = norm(alt).split()
                if w:
                    out.add(_adj_base(w[0]))
        out.discard(None)
        return out

    def names_the_region(self, query: str, codes) -> bool:
        """Збіг — це назва самої області, а не міста в ній.

        Обидві сторони проходять через `_adj_base`, тому іменник маркером
        лишається: «над Волгоградом» це місто, «Волгоградская область» — ні.
        """
        if not codes:
            return False
        key = frozenset(codes)
        if key not in self._self_roots:
            self._self_roots[key] = self.self_roots(codes)
        w = norm(query).split()
        return bool(w) and _adj_base(w[0]) in self._self_roots[key]

    def lookup(self, query: str, near: tuple[float, float] | None = None,
               max_km: float = 400.0, allow_far: bool = False, near_a1=None,
               box=THEATER, prefer_seat: bool = False) -> dict | None:
        """Знаходить НП. `near` — центроїд регіону з того ж поста, для омонімів.

        Якщо регіон відомий, а жодного тезки в радіусі немає — повертає None.
        Інакше «Западное» при Кримі підхоплює однойменне село в Примор'ї за
        7800 км: назва збіглася, сенсу нуль.
        """
        q = norm(query)
        # Загальне слово — не місце, хоч би що знайшлось за основою: «Высоко»
        # діставало Высокое, «России» — село Россия (друга рецензія).
        if q in NOT_PLACES:
            return None
        # Розвʼязання через відмінковий фолбек нижче (родовий, складена назва,
        # дефіс) — «морфологічне». `store.point_entity` ставить його нижче за
        # пряме: інакше ціль у родовому («в сторону Смоленска или Рославля»,
        # «в сторону на Орла») перебивала назване місце.
        morph = False
        # Рамка театру потрібна лише там, де вибирає населення: у фолбеку
        # «найбільший тезка» і в якорі. Коли область відома, її й так
        # обмежують радіус max_km і near_a1, а рамка тільки шкодила: «Новый
        # Уренгой» при ЯНАО не знаходився взагалі, бо лежить за 60° сходу, і
        # подія падала на центр округу. Заміряно на архіві: без рамки при
        # `near` 277 подій Уралу отримують місто замість центроїда, жодна
        # європейська координат не втрачає. «Ангарск» при Криму й далі None —
        # його відсікає радіус, не рамка.
        cands = self.candidates(query, None if near else box)
        if not cands and q:
            cands, seat = self._variant_cands(q, near, box)
            if cands:
                morph = True
                prefer_seat = prefer_seat or seat
        if not cands and near and q and "-" in q and " " not in q:
            # Відрізок траси «Луганск-Лисичанск», «Урзуф-Мангуш»: такої назви
            # нема, а перший кінець є. Доки лукахед не відсував «Трасса», розбір
            # сам різав рядок на слова й знаходив другий кінець; тепер дефісна
            # пара приходить цілою (рецензія: ~25 подій падали на центр).
            # Беремо перший кінець — рядок 1 цих каналів називає місце першим.
            #
            # Лише коли КОЖНА частина — назва і пост назвав область. Інакше
            # ріжеться одна назва: «Ай-Петри» -> Petri у Псковській,
            # «Князе-Григоровка» -> Григорівка, «Воздушно-десантных» -> Десантне.
            parts = q.split("-")
            got = [self.candidates(x, None) for x in parts]
            if all(len(x) >= 3 for x in parts) and all(got):
                cands, morph = got[0], True
        if not cands:
            return None
        if near:
            scoped = [(haversine(near, (c["lat"], c["lon"])), c) for c in cands]
            scoped = [(d, c) for d, c in scoped if d <= max_km]
            if (not scoped and self.by_name.get(q)
                    and not _FEM_ADJ.search(q.split()[0])):
                # Те саме для області: усі точні тезки далеко («Вяземский» —
                # село на Далекому Сході, «Губкинский» — місто в ЯНАО), а
                # район під боком лежить під ключем «… район» і досяжний лише
                # за основою. Раніше точний збіг обривав пошук, і подія падала
                # на центр області (BACKLOG §3, «район є, але не знайшовся»).
                seen = {id(c) for c in cands}
                more = [c for st in _stems(q) for k in self.stems.get(st, [])
                        for c in self.by_name[k] if id(c) not in seen]
                scoped = [(d, c) for d, c in
                          ((haversine(near, (c["lat"], c["lon"])), c) for c in more)
                          if d <= max_km]
            if not scoped and not morph:
                # Жоден кандидат не лежить в області поста — а кандидатами були
                # далекі збіги за основою («каменки…», «малой…»). Тоді пробуємо
                # відмінкові варіанти: «От Каменки-Днепровской» ->
                # «каменка-днепровская», «Малой белозерки» -> «малая
                # белозерка». Раніше тут був None, тож гірше не стане.
                alt, seat = self._variant_cands(q, near, box)
                scoped = [(d, c) for d, c in
                          ((haversine(near, (c["lat"], c["lon"])), c) for c in alt)
                          if d <= max_km]
                if scoped:
                    morph = True
                    prefer_seat = prefer_seat or seat
            # Якщо в самій області є тезка — беремо тільки з неї. Це відсікає
            # однойменні райони сусідніх регіонів ДО того, як їх порівнює
            # формула: населення в GeoNames — ненадійний сигнал (pop=0 стоїть у
            # 97% населених пунктів і означає «невідомо», а не «порожньо»),
            # тому мільйонне місто за 300 км завжди перемагало правильний район
            # під боком. Фолбек на всіх кандидатів, якщо в області нема жодного.
            if near_a1:
                # ADM1 (сама область) з фільтра виведена, але ЛИШЕ для
                # прикметникової форми запиту. Область російською називають
                # прикметником — «Харьковская область», «Николаевской области»;
                # без винятку «Харьковская» ставала однойменним селом під
                # Бєлгородом за 200 км.
                #
                # Форма й розрізняє: «Николаевки» — це родовий відмінок СЕЛА
                # («От Николаевки в направлении Севастополь»), і воно дотягується
                # до Миколаївської області лише через стем. З винятком для всіх
                # ADM1 така подія їхала за 350 км в іншу країну.
                #
                # Райони (ADM2/ADM3) винятку не мають узагалі — саме їх і треба
                # відсікати: «Дмитровский район» при Орловській це не однойменний
                # район Москви.
                # Старий перелік закінчень свідомо: ширший ADJ_SUFFIX (з
                # «-ским», «-ского») пускав сюди ЧУЖІ області — «Краснодонским
                # районом» ставало Краснодарським краєм, бо стем «краснод».
                adjectival = bool(REGION_ADJ.search(q.split()[0])) if q else False
                same = [(d, c) for d, c in scoped
                        if (c.get("cc"), c.get("a1")) in near_a1
                        or (adjectival and c.get("fcode") in ("ADM1", "ADM1H"))]
                if same:
                    scoped = same
                # Відмінковий здогад поза областю поста НЕ відкидається —
                # спробу зроблено й знято 21 вересня 2026. Область поста — перша
                # названа, і часто це область ЦІЛІ («От Великой Лепетихи … в
                # направлении Мелитополь»), тож правильне місце опинялось «поза
                # областю»; а ненайдені цілі рвали ланцюг напрямку («в сторону
                # Глазуновка, Тросны, Кромы, Орёл» — Орел ставав крапкою).
                # Ціна — поодинокі «Жукова, Брянская» -> Жуков у Калузькій.
            # Іменник — це місто, а не район: «от Старобельска» давав
            # Старобільський РАЙОН (123 тис.) замість міста (16 тис.), коли
            # район дістав російську назву з Wikidata, — і `point_entity`
            # площу відкидав, подія падала на центр ЛНР. Назви районів —
            # прикметники; для іменника район лишається, лише коли НП нема.
            if q and not _ADJ_STEM.search(q.split()[0]):
                ppl = [(d, c) for d, c in scoped if c["fclass"] == "P"]
                if ppl:
                    scoped = ppl + [(d, c) for d, c in scoped
                                    if c.get("fcode") in ("ADM1", "ADM1H")]
            if scoped:
                # Компроміс населення/відстань. Чиста максимізація населення
                # кидала "ГО Богородск, Московская область" у нижегородський
                # Богородск за 370 км: він більший, але не той. Чиста
                # мінімізація відстані навпаки чіпляє хутори-тезки під боком.
                def score(dc):
                    dist, c = dc
                    return (c["pop"] + 500) / (1 + dist / 50.0)
                best = max(scoped, key=score)
                d, c = best
                seat = (self._seat_over_region(q, c, [x for _, x in scoped])
                        if prefer_seat else c)
                if seat is not c:
                    d = haversine(near, (seat["lat"], seat["lon"]))
                return {**seat, "dist_km": round(d), "conf": "region", "morph": morph}
            if not allow_far:
                return None
        best = max(cands, key=lambda c: c["pop"])
        if prefer_seat:
            best = self._seat_over_region(q, best, cands)
        return {**best, "dist_km": None, "conf": "global", "morph": morph}

    @staticmethod
    def _seat_over_region(q: str, best: dict, pool: list[dict]) -> dict:
        """Місто, а не його область, коли назва — іменник.

        «Пуски БПЛА из-под Чернигова в направлении Брянской» віддавало
        Чернігівську ОБЛАСТЬ: запис ADM1 на 959 тис. за формулою населення
        перебивав місто Чернігів, область — площа, крапки нема, і пуск падав на
        область-ціль поста. Те саме з «Одесса» (місто лежить у газетирі поруч
        із записом області під тим самим імʼям).

        Беремо адмінцентр (PPLA/PPLC) САМЕ ЦІЄЇ області, і лише для іменникової
        форми. Прикметник («Черниговская») — це і є область, його не чіпаємо;
        назва республіки без однойменного міста («Адыгея», «Чувашия») свого
        адмінцентру серед кандидатів не має й лишається площею, як і було.
        """
        if best.get("fcode") not in ("ADM1", "ADM1H"):
            return best
        # Прикметник — за основою «-ск-/-цк-» з БУДЬ-ЯКИМ закінченням. ADJ_SUFFIX
        # тут не годиться: він не знає «-цкой», і «Липецкой области» ставала
        # іменником, тобто містом Липецьк (перша версія правила, +2500 подій).
        if q and _ADJ_STEM.search(q.split()[0]):
            return best
        seats = [c for c in pool if c.get("fcode") in ("PPLA", "PPLC")
                 and c.get("cc") == best.get("cc") and c.get("a1") == best.get("a1")]
        return max(seats, key=lambda c: c["pop"]) if seats else best


def _stem(s: str) -> str:
    w = s.split()[0] if s else s
    return _word_stem(w)


def _word_stem(w: str) -> str:
    w = ADJ_SUFFIX.sub("", w)
    if len(w) > 6:
        w = CASE_SUFFIX.sub("", w)
    return w[:7]


# Прикметник жіночого/середнього роду чи множини. Обхід далеких точних тезок
# для такого слова не вмикається: район — «-ский район», чоловічий рід, а
# «Брянская» (область), «Большая», «Старая» (перше слово складеної назви)
# через основу діставали місто Брянськ, Велику Знамʼянку, Стару Царичанку.
# «-ой» свідомо тут: «Брянской» частіше область, ніж «Донской» район.
_FEM_ADJ = re.compile(r"(ая|яя|ую|юю|ое|ее|ой|ей|ые|ие)$")


# Слова-класифікатори: самі по собі місця не називають, а стем від них тягне
# сотні чужих кандидатів («мыс» -> будь-який Мыс, «трасса» -> Тростянець).
GENERIC = {"мыс", "бухта", "бухты", "трасса", "трассе", "трассу", "станция",
           "станции", "парк", "поселок", "посёлок", "село", "хутор", "город",
           "аэродром", "порт", "озеро", "коса", "залив", "район", "дорога",
           "дороги", "дороге", "апп", "кпп", "го", "мо", "нпз", "тэс", "аэс"}


# Повний корінь — БЕЗ обрізання до 7 літер. Обрізання нешкідливе, поки стем
# спрацьовує лише як остання надія (точної назви нема), але у широкому наборі
# воно основне джерело сміття: «красноперекопск» і «краснопахорский» обидва
# дають «красноп», і узгодження зшивало Крим із Підмосковʼям за 1079 км.
ADJ_FULL = re.compile(r"(ского|ская|ские|ских|ским|скую|ской|ском|скому|ский|"
                      r"цкого|цкая|цкие|цкий|цкое|ское)$")


def _root(w: str) -> str:
    w = ADJ_FULL.sub("", w)
    if len(w) > 5:
        w = CASE_SUFFIX.sub("", w)
    return w


# Основа ПРИКМЕТНИКОВОЇ назви: «волгоградская» -> «волгоград». None, якщо
# слово не прикметник або основа коротша за 5 літер.
#
# Поріг не косметичний, він і є запобіжником. Основи областей, де вада справді
# є, довгі: волгоград (9), астрахан (8), воронеж (7), ленинград (9), москов (6),
# ульянов (7). Коротші основи дають випадкові збіги з чужими назвами: «крымское»
# -> «крым» (4) це СЕЛО, а не Крим (36 згадок); «курская» -> «кур», «омская» ->
# «ом», «липецкая» -> «липе», «донецкая» -> «доне», «тверская» -> «твер». Жодна
# з цих областей вади не має (їхній запис ADM1 і так виграє в міста), тож поріг
# нічого потрібного не втрачає.
def _adj_base(w: str) -> str | None:
    if not ADJ_FULL.search(w):
        return None
    base = ADJ_FULL.sub("", w)
    return base if len(base) >= 5 else None


def _roots(s: str) -> set[str]:
    words = [w for w in s.split() if w not in GENERIC] or s.split()[:1]
    return {_root(w) for w in words if len(w) >= 4} or {_root(words[0])}


def _stems(s: str) -> set[str]:
    """Ключі ВУЗЬКОГО пошуку. Свідомо лишились односкладовими (перше слово).

    Спокуса розширити їх на кожне слово сильна — саме через перше слово
    «Белой Березки» недосяжна. Але виміряно на 40 випадкових змінених
    розвʼязаннях: багатослівний вузький індекс робить резолвними склеєні
    розбором артефакти («Семисотка Ленинский», «Островское Первомайский»,
    «Приморский Посад») і відправляє їх у Ленінські гори, на Васильєвський
    острів і в Сергієв Посад — тобто рівно в ті великі омоніми, проти яких уся
    ця робота. Багатослівність живе в `_roots`, і лише під узгодженням поста,
    де вибір робить не населення.
    """
    return {_stem(s)}


# Радіус узгодження топонімів усередині поста. Пост описує один наліт: «Каланчак,
# Мирное, Ставки», «Желябовка, Советский, Кировское» — це сусідні НП, а не різні
# кінці країни. 100 км підібрано на розміченому наборі: 60 і 80 недобирають
# (Октябрьское за 33 км від Мазанки проходить, а Красногвардейское за 49 км від
# Білогірська — вже ні при 40), 150 і 200 починають зшивати випадкових тезок.
CONSENSUS_KM = 100.0

# Скільки тезок ще лишає назву придатною для голосування. На розміченому наборі
# крива пласка від 150 і вище, нижче — падає (100 -> 106, 60 -> 105 із 113).
# 400 бере частотні, але цілком інформативні назви: «Октябрьское» має 353
# морфологічні збіги, «Первомайское» — 298, і при 200 вони голосу не мали.
# Поріг тут не заради цих одиниць, а щоб назва з сотнями точок по країні не
# «підтверджувала» будь-яку гіпотезу випадковим сусідом.
WIDE_VOTE_MAX = 400

# Слово ПІСЛЯ назви, яке робить її районом, а не селом. Пишеться з малої
# («Панинский район»), тому шаблон freeform його не бере — і в газетир іде
# «Панинский», тобто інша сутність. Наслідок заміряний: у 15 добах 1627
# розвʼязань conf="region" стоять поза всіма областями, які назвав їхній
# власний пост, і найчастіші серед них — саме районні прикметники
# (Черноморский 62, Ленинский 61, Погарский 53, Каменский 41…).
#
# Правильна відповідь при цьому В ГАЗЕТИРІ Є: «Панинский Район» ADM2 RU.86 за
# 64 км від центру Воронезької, тоді як обраний «Paninskiy» PPL RU.41 — за 214.
# У кандидати вона не потрапляє лише тому, що ключ у `by_name` двослівний.
# Перевірено на 11 найчастіших промахах — район у своїй області знайшовся для 10.
#
# Полігон області для цього НЕ годиться: перевірено окремо, серед 2055 фолбеків
# кандидат усередині полігону є лише в 4. Річ не у фільтрі, а в тому, що
# правильного запису серед кандидатів нема взагалі.
DISTRICT_AFTER = re.compile(
    r"\s*(?:муниципальн\w*\s+)?(?:район\w*|р-?н\b|округ\w*)", re.I)

# «Киевская область» — ЦІЛА область, а не село-тезка. Області України в конфізі
# нема (там субʼєкти РФ і ТОТ), тож прикметник іде у freeform як НП, і точний
# збіг назви обриває пошук: «киевская» в газетирі — лише село Kiyevskaya у
# Вологодській (pop 0), а «киевская область» — Kyiv Oblast (ADM1). Крапка
# «Киевская область фиксация самолётов F16» ставала у Вологодській за 1500 км.
#
# Результат — запис ADM1, тобто площа: крапкою область не стає, як і всюди.
# «от Киевской и Черниговской областей» — перший прикметник теж область.
REGION_AFTER = re.compile(
    r"\s*(?:и\s+[А-ЯЁа-яё]+(?:ск|цк)\w{2,3}\s+)?обл(?:асть|асти|астей|астью|\.)?(?!\w)", re.I)

# ---- ДЖЕРЕЛО ПУСКУ ------------------------------------------------------------
# У пості про пуск назва після «от / из-под / со стороны / с района» — звідки
# пустили. Визначення одне на весь конвеєр: extract витягує такі назви з усіх
# рядків, тут вони геокодуються, store.launch_origin бере з них крапку.
LAUNCH_WORD = re.compile(r"\b(?:за)?пуск", re.I)
LAUNCH_SRC_BEFORE = re.compile(
    r"(?:\bот|\bсо\s+стороны|\bиз-под|\bиз\s+района|\bс\s+района|\bиз|\bс|\bсо)"
    r"\s+(?:г\.\s*|города\s+|района\s+)?$", re.I)


def _nominatives(q: str) -> list[str]:
    """Називний відмінок для назви в родовому після «от»: «одессы» -> «одесса».

    Для коротких назв (до 6 літер) `_word_stem` відмінка не зрізає, тож
    «Одессы», «Днепра», «Сум» не зустрічались із «Одесса», «Днепр», «Сумы» у
    жодному кошику і не знаходились узагалі. Варіанти — лише для джерела
    пуску, де відмінок гарантований прийменником.
    """
    out = [q]
    if " " in q:
        return out
    if q.endswith("ы"):
        out += [q[:-1] + "а"]
    if q.endswith("и"):
        out += [q[:-1] + "а", q[:-1] + "ь"]
        out += [q[:-1] + "я"]              # «Ивни» -> «ивня»
    if q.endswith("а"):
        out += [q[:-1], q[:-1] + "ь"]
    if q.endswith("я"):
        out += [q[:-1] + "ь", q[:-1] + "й"]
    if q.endswith("ов") or q.endswith("ев"):
        out += [q + "ка"]
    if not q.endswith(("ы", "и", "а", "я")):
        out += [q + "ы", q + "и"]          # «от Сум» -> «сумы»
    return out
# Загальні слова, які в родовому відмінку збігаються з назвою села:
# «Дня Победы» -> Победа, «Силы ПВО» -> Сила, «Уйти в укрытие» -> Уйта.
#
# Річки теж: «вдоль Днепра в сторону Каховки» ставало містом Дніпро, «Десны»,
# «Волги», «Дуная» — селами. Абстрактні іменники з переліку рецензії (21
# вересня 2026) усі розвʼязувались у села-тезки.
NOT_PLACES = {"победы", "силы", "уйти", "службы", "группы", "цели", "атаки",
              "угрозы", "тревоги", "области", "власти", "стороны", "границы",
              "днепра", "десны", "волги", "дуная", "дона", "донца", "оки",
              "почти", "куда", "китая", "радости", "славы", "мира",
              "правды", "свободы", "надежды", "родины", "весны", "звезды",
              "искры", "бригады", "нивы", "зори", "воли", "зари",
              "линии", "станции", "трассы", "дороги", "реки", "моря", "залива",
              "россии", "украины", "высоко", "низко", "далее", "очень"}

# Будь-який прикметник, не лише «-ский»: «Чёрного моря», «Чёрное море»
# давали Чернський район і село Чорне (третя рецензія).
_ANY_ADJ = re.compile(r"(?:ый|ий|ой|ая|яя|ое|ее|ого|его|ому|ему|ым|им|ом|ем|ую|юю|ей)$")
# Родовий маркер-місто — місце лише після прийменника місця («от Льгова»,
# «Севернее Джанкоя», «у Анапы») або на початку рядка («Керчи и
# близлежащие»). Перелік ДОЗВІЛЬНИЙ: заборонний («лише після слова
# напрямку») обходили «В основном Москвы», «в сторону Тулы, Москвы»,
# «города Тюмени» — усе цілі.
_PLACE_BEFORE_MARKER = re.compile(
    r"(?:(?:^|\n)\s*|\b(?:от|из-под|из|со\s+стороны|у|возле|около|недалеко\s+от|"
    r"в\s+районе|район[еа]?|севернее|южнее|западнее|восточнее)\s+(?:г\.\s*)?)$", re.I)

_UNIT_NEXT = re.compile(r"(?:район|област|округ|кра[йяюе]|республик|р-н|обл|го\b|мо\b|"
                        r"полуостров|море|мор[яюе]|залив|водохранилищ)", re.I)
_LOWER_NEXT = re.compile(r"[ \t]+([а-яё][а-яё\-]{2,})")

SEA_AFTER = re.compile(r"\s+(?:мор[еяюмь]\w*|залив\w*|водохранилищ\w*)", re.I)

# Непрямий відмінок прикметника -> називний, для першого слова складеної
# назви: «великую» -> «великая», «белой» -> «белая», «нового» -> «новое».
_ADJ_OBL = re.compile(r"(ую|юю|ой|ей|ого|его|ом|ем|ых|их)$")
_ADJ_NOM = {"ую": "ая", "юю": "яя", "ой": "ая", "ей": "яя", "ого": "ое",
            "его": "ее", "ом": "ое", "ем": "ее", "ых": "ые", "их": "ие"}


def _adj_nominatives(q: str) -> list[str]:
    """Прикметникова назва в родовому: «От Веселого» -> «веселое», «Широкого»
    -> «широкое», «Мирного» -> «мирное»/«мирный». Лише «-ого/-его»: «-ой»
    неоднозначне («Брянской» — частіше область)."""
    if len(q) >= 6 and q.endswith(("ого", "его")):
        b = q[:-3]
        return [b + "ое", b + "ее", b + "ый", b + "ий"]
    return []


def _hyphen_nominatives(q: str) -> list[str]:
    """«каменки-днепровской» -> «каменка-днепровская» (кожна частина окремо)."""
    import itertools
    opts = []
    for part in q.split("-"):
        v = [part] + [x for x in _nominatives(part)[1:] if not x.startswith(part)]
        adj = _ADJ_OBL.sub(lambda m: _ADJ_NOM[m.group(1)], part)
        if adj != part:
            v.append(adj)
        opts.append(v[:5])
    return ["-".join(c) for c in itertools.islice(itertools.product(*opts), 60)
            if "-".join(c) != q]


def _fleeting(q: str) -> list[str]:
    """Випадний голосний: «Орла» -> «орел», «Льгова» теж не сюди, лише -ла/-ра."""
    if len(q) >= 4 and q[-1] == "а" and q[-2] in "лр" and q[-3] not in "аеиоуыэюяь":
        return [q[:-2] + "е" + q[-2]]
    return []


#: непрямий відмінок прикметника -> називний жіночого роду, як в alt-назвах
#: GeoNames: «Николаевской области» -> «николаевская область»
_ADJ_TO_NOM = re.compile(r"(ск|цк)(?:ой|ую|ая|ом|ою)$")
_ADJ_STEM = re.compile(r"(?:ск|цк)(?:ий|ая|ое|ие|ой|ую|ого|ому|ом|ою|их|им|ими|ых|ым|ей)$")


def _consensus(queries: list[str], gaz: "Gazetteer", radius: float = CONSENSUS_KM):
    """Точка, на якій сходяться щонайменше два РІЗНІ топоніми поста.

    Навіщо взагалі. Коли в пості нема назви області, лишався фолбек «найбільший
    однойменний за населенням» — він і кидав кримський Красногвардейський район
    у Санкт-Петербург (pop 337 тис.), а Советский із Криму в Марій Ел за 1500 км.
    Взаємна узгодженість назв усередині поста — сильніший сигнал за населення:
    у «Желябовка, Советский, Кировское» три назви мають кримські варіанти за
    десятки кілометрів одна від одної, і жодного спільного скупчення деінде.

    Стеля методу відома й невелика: постів без регіону з ≥2 резолвними
    топонімами — 778 із 3379 (23%), і в них лежить 1133 з 2384 неоднозначних
    розвʼязань (47.5%). Решта — один топонім на пост, там перевіряти нема чим,
    і фолбек лишається як був.

    Голосують РІЗНІ назви, не входження: «Армянск … Армянск» — це один голос,
    інакше повтор назви сам себе й підтверджував би.
    """
    groups, exact = {}, {}
    for q in queries:
        nq = norm(q)
        if nq and nq not in groups:
            cands = gaz.candidates(q, wide=True)
            # Назва, під яку підпадають сотні точок, голосу не має: поруч із
            # будь-якою точкою країни знайдеться якийсь її «тезка», і
            # узгодження стає випадковим. «Красный Партизан» дає 848
            # кандидатів (обидва слова частотні) і тягнув Крим під Пітер.
            if cands and len(cands) <= WIDE_VOTE_MAX:
                groups[nq] = cands
                exact[nq] = {id(c) for c in (gaz.by_name.get(nq) or [])}
    if len(groups) < 2:
        return None
    keys = list(groups)
    best = None
    for i, k in enumerate(keys):
        for c in groups[k]:
            pt = (c["lat"], c["lon"])
            votes, support = 0, 0.0
            for j, o in enumerate(keys):
                if j == i:
                    continue
                # Точний збіг назви важить удвічі проти морфологічного:
                # «Белогорск» біля Пітера — це Бєлогорка, натягнута через
                # корінь, а кримський Білогірськ збігається буквально.
                w = [(2 if id(x) in exact[o] else 1) * (x["pop"] + 500) /
                     (1 + haversine(pt, (x["lat"], x["lon"])) / 50.0)
                     for x in groups[o]
                     if haversine(pt, (x["lat"], x["lon"])) <= radius]
                if w:
                    votes += 1
                    # НАЙВАГОМІШИЙ тезка в колі, а не найближчий. З найближчим
                    # «Войково … Гвардейское» підтверджувалось хутором
                    # Гвардійське (pop 772) за 15 км, і пара програвала
                    # дніпровській; за селищем Гвардійське (pop 12 589) за
                    # 45 км кримська пара виграє.
                    support += max(w)
            # Населення САМОЇ гіпотези у вагу не входить — саме воно й було
            # джерелом помилки. Питання не «чи велике це місце», а «чи багато
            # й близько підтверджують його інші назви поста». Інакше район
            # Пітера на 337 тис. перебиває кримську пару як завгодно щільну.
            if votes:
                cand = (votes, support, c["pop"], pt)
                if best is None or cand[:3] > best[:3]:
                    best = cand
    return best[3] if best else None


def geocode_posts(posts: list[dict], gaz: Gazetteer, region_geo: dict,
                  entity_type: str = "нп", max_km: float = 400.0,
                  refine_regions: bool = True, aliases: dict | None = None,
                  region_a1: dict | None = None) -> dict:
    """Проставляє lat/lon сутностям.

    refine_regions: місто-маркер області ("Керчь" -> Крим) віддає власні
    координати замість центроїда регіону. Інакше вся Керч сидить у центрі Криму
    і метрика глибини втрачає сотні кілометрів точності.
    """
    stats = collections.Counter()
    for p in posts:
        regions = [e["value"] for e in p.get("entities", [])
                   if e["type"] == "регіон" and e["value"] in region_geo]
        near = region_geo[regions[0]] if regions else None
        # код області з ПЕРШОЇ згаданої: саме її бере store.py як region
        a1 = (region_a1 or {}).get(regions[0]) if regions else None
        consensus = None
        if near is None:
            # Прохід 0: узгодження назв усередині поста. Йде ПЕРЕД якорем, бо
            # якір бере найбільший за населенням збіг і тому сам себе валідує:
            # «Красногвардейский район» ставав якорем на однойменному районі
            # Пітера, а далі та сама помилка виходила з conf="region", ніби її
            # підтвердив контекст. Виміряно: 713 розвʼязань мали conf="region",
            # отриманий саме так — з єдиного неоднозначного топоніма в пості.
            near = consensus = _consensus(
                [e.get("match") or e.get("value") or ""
                 for e in p.get("entities", []) if e["type"] == entity_type], gaz)
            if consensus:
                stats["consensus"] += 1
        if near is None:
            # Прохід 1: якір. Регіону з конфіга нема ("Республика Мордовия"),
            # але в тексті є однозначний топонім — адмінодиниця чи велике місто.
            # Без цього кроку "Дальний Валуйского района" ловить тезку за 1500 км.
            anchors = []
            for e in p.get("entities", []):
                q = e.get("match") or e.get("value") or ""
                # Якорити може лише ТОЧНИЙ збіг назви. Інакше якір ставить
                # морфологічний здогад: «Дорога Красногвадейское» (з друкарською
                # помилкою, точного збігу нема) через основу дотягувалась до
                # Красногвардійського району Пітера на 337 тис. і тягнула туди
                # весь пост. Однозначні топоніми, заради яких прохід і є —
                # «Республика Адыгея», «Краснодар» — збігаються точно.
                if not gaz.by_name.get(norm(q)):
                    continue
                hit = gaz.lookup(q, None, max_km)
                if hit and (hit["fclass"] == "A" or hit["pop"] >= 50000):
                    anchors.append((hit["pop"], (hit["lat"], hit["lon"])))
            if anchors:
                near = max(anchors)[1]
                stats["anchored"] += 1
        if refine_regions:
            for e in p.get("entities", []):
                if e["type"] != "регіон" or not e.get("match"):
                    continue
                base = region_geo.get(e["value"])
                # Назва самої області маркером БУТИ НЕ МОЖЕ. «Волгоградская
                # область» через стем «волгоград» діставала місто Волгоград, і
                # сутність-регіон ставала точкою з населенням 1.01 млн. Далі
                # store.point_entity бере найбільший за населенням топонім —
                # тож місто перебивало РОЗВʼЯЗАНИЙ район того самого поста:
                # «Урюпинский район / Волгоградская область» їхало з 50.82°
                # на 48.71°, помилка 301 км.
                #
                # Чому це вилізло на Волгоградській, а не всюди: `lookup` важить
                # (pop+500)/(1+dist/50), і в решті областей виграє запис ADM1
                # (fclass A -> centroid, а centroid point_entity відкидає).
                # Волгоград стоїть у дальньому кутку витягнутої області, тому
                # центроїд ADM1 за 105 км програє місту за 1 км: 813 тис. проти
                # 993 тис. Те саме в Астраханській. Заміряно у вікні сховища:
                # 5367 постів Волгоградської прибито до міста, у 1778 з них
                # район чи село всередині RU.84 вже було розвʼязано.
                codes = (region_a1 or {}).get(e["value"])
                # Маркер, з якого `extract` уже зробив ТОПОНІМ, містом не є.
                # Без цього кроку правка про зʼїдені райони не спрацьовує там,
                # де маркер таки резолвиться в місто: «Бердянский район» дало б
                # місто Бердянськ (176 тис.), і воно за населенням перебило б
                # сам район. Те саме з Мелітопольським, Шебекинським.
                #
                # Ознака — НЕ повторна перевірка тексту, а наявність топоніма на
                # тій самій позиції. Перевірка тексту тут розходилась із
                # `extract`: `DISTRICT_AFTER` має `\s*`, тобто перестрибує
                # перенос рядка, а freeform читає лише перший рядок. У 18
                # постах вікна слово «район» стоїть на наступному рядку — там
                # маркер гасився, топонім не створювався, і подія втрачала
                # крапку зовсім. Спільна позиція такого розходження не має за
                # побудовою: обидві сутності роблять з ОДНОГО слова.
                district = e.get("pos") is not None and any(
                    x["type"] == entity_type and x.get("pos") == e["pos"]
                    for x in p.get("entities", []))
                hit = (None if district or gaz.names_the_region(e["match"], codes)
                       else gaz.lookup(e["match"], base, max_km))
                # Місто-маркер — лише пряма назва. Родовий фолбек тут ставив би
                # ціль: «в направлении Москвы» (маркер Московської) ставало
                # крапкою в Москві, хоч до фолбека подія була площею області.
                placed = e.get("pos") is not None and _PLACE_BEFORE_MARKER.search(
                    p["text"][max(0, e["pos"] - 30):e["pos"]])
                if (hit and hit["fclass"] == "P" and hit["pop"] >= 1000
                        and not (hit.get("morph") and not placed)):
                    e["lat"], e["lon"] = hit["lat"], hit["lon"]
                    e["geo_name"], e["geo_pop"] = hit["name"], hit["pop"]
                    e["geo_conf"] = "city-marker"
                    stats["region_refined"] += 1
                elif base:
                    e["lat"], e["lon"] = base
                    e["geo_conf"] = "centroid"
                    stats["region_centroid"] += 1
        for e in p.get("entities", []):
            if e["type"] != entity_type:
                continue
            q = e.get("match") or e["value"]
            # Складена назва з другим словом із малої: «Малой белозерки»,
            # «Широкой балки», «Нижнего песочного», «Геническая горка».
            # Шаблон розбору бере лише слова з великої, тож приходило саме
            # перше слово. Друге беремо, лише коли ПАРА є в газетирі.
            #
            # «район», «область», «край» — не друге слово назви: для них є свої
            # правила (DISTRICT_AFTER, REGION_AFTER), і склеєна «Архангельская
            # область» їх обходила.
            if e.get("pos") is not None and " " not in str(q):
                tail = p["text"][e["pos"] + len(str(q)):]
                nx = _LOWER_NEXT.match(tail)
                if (nx and not DISTRICT_AFTER.match(tail) and not REGION_AFTER.match(tail)
                        and not _UNIT_NEXT.match(nx.group(1))
                        and gaz.has_compound(f"{q} {nx.group(1)}")):
                    q = f"{q} {nx.group(1)}"
            al = (aliases or {}).get(str(q).lower().strip())
            # «над Азовским морем», «Чёрного моря» — море, не станиця Азовська
            # (прикметник із «-ским» тепер доходить до основи «азов»). Лише для
            # ПРИКМЕТНИКА: «Западнее Тарханкута морем» — орудний відмінок
            # («морем» = по морю), і Тарханкут там місце.
            if (not al and e.get("pos") is not None
                    and _ANY_ADJ.search(norm(q).split()[-1] if norm(q) else "")
                    and SEA_AFTER.match(p["text"][e["pos"] + len(str(q)):])):
                continue
            if al:                       # ручне виправлення має пріоритет
                hit = {"lat": al[0], "lon": al[1], "name": q, "pop": 0,
                       "fclass": "P", "conf": "alias", "dist_km": None}
            elif consensus:
                # Скупчення вже вибрано; далі — звичайний компроміс населення
                # й відстані, але від точки узгодження і по ШИРОКОМУ набору.
                # Саме тут стає видимим кримський Курман для «Красногвардейского».
                #
                # Коло — CONSENSUS_KM, але велике місто пускаємо й здалеку.
                # У «Каневская … в сторону Краснодара» сам Краснодар за 115 км
                # випадав із кола, і перемагав хутір Краснодарський за 85 км із
                # населенням 0. Розширити коло до max_km для ВСІХ не можна —
                # тоді Мирне під Сімферополем (pop 9284, 147 км) знову б'є
                # Мирне Каланчацької громади за 14 км. Місто-стотисячник у
                # пості випадковим не буває, хутір-тезка — буває.
                cands = [(haversine(consensus, (c["lat"], c["lon"])), c)
                         for c in gaz.candidates(q, wide=True)]
                cands = [dc for dc in cands
                         if dc[0] <= CONSENSUS_KM
                         or (dc[0] <= max_km and dc[1]["pop"] >= 50000)]
                # Цілий субʼєкт — не населений пункт. «Советского района» при
                # кримському скупченні віддавав «Автономну Республіку Крим» із
                # населенням 1.9 млн: за формулою населення/відстань вона б'є
                # будь-яке село, а точка виходить у центрі півострова.
                #
                # Виняток той самий, що й у гілці регіону: область російською
                # називають прикметником, і «Харьковская» має лишитись
                # областю, а не стати містом Харковом.
                nq = norm(q)
                if not (nq and ADJ_SUFFIX.search(nq.split()[0])):
                    cands = [dc for dc in cands
                             if dc[1].get("fcode") not in ("ADM1", "ADM1H")] or cands
                # Точний збіг назви б'є стемовий, навіть якщо той ближчий:
                # інакше «Комсомольское» біля Докучаєвська стає Графським за
                # 50 км, хоч Кальміуське (точна альт-назва) поруч.
                ex = {id(c) for c in (gaz.by_name.get(norm(q)) or [])}
                cands = [dc for dc in cands if id(dc[1]) in ex] or cands
                if cands:
                    # «Сельцо» при Дятькові — це місто за 32 км (pop 18 тис.),
                    # а не хутір-тезка за 17 км (pop 0).
                    d, c = max(cands, key=lambda dc:
                               (dc[1]["pop"] + 500) / (1 + dc[0] / 50.0))
                    hit = {**c, "dist_km": round(d), "conf": "consensus"}
                else:
                    hit = gaz.lookup(q, near, max_km, near_a1=a1, prefer_seat=True)
            else:
                hit = gaz.lookup(q, near, max_km, near_a1=a1, prefer_seat=True)
            # Джерело пуску: область поста — це ЦІЛЬ, а джерело за кордоном,
            # тож пошук «у своїй області» тягнув до російського села-тезки:
            # «из-под Харькова в направлении Белгородской» -> Харьковское на
            # Білгородщині. Тут — без near_a1, з називним відмінком і перевагою
            # українського запису (канали російські, пуски з українського боку).
            if (e.get("pos") is not None and LAUNCH_WORD.search(p["text"])
                    and LAUNCH_SRC_BEFORE.search(p["text"][max(0, e["pos"] - 24):e["pos"]])):
                nq = norm(q)
                src_hits = [h for h in (gaz.lookup(v, near, max_km, allow_far=True,
                                                   prefer_seat=True)
                                        for v in _nominatives(nq)) if h]
                ua = [h for h in src_hits if h.get("cc") == "UA"]
                if ua:
                    # місто перед площею: «от Очаков» — місто, а не Очаківський
                    # район, хоч у району більше населення
                    hit = max(ua, key=lambda h: (h.get("fclass") == "P", h["pop"]))
                    # Власна позначка, а не «global»: пошук поза радіусом
                    # області поста повертав «global», і редактор малював
                    # Одесу-джерело кільцем «здогад», ніби її вгадано за
                    # населенням. Тут назву вибрано граматикою й перевірено
                    # країною — це розвʼязання, а не здогад.
                    hit = {**hit, "conf": "source"}
                    stats["launch_src"] += 1
            # Пост сказав «район» — шукаємо район. Беремо його ТІЛЬКИ якщо він
            # у названій області: інакше це той самий здогад, лише інший.
            # Тому правка не може погіршити — вона замінює позарегіональний
            # відповідник на внутрішньорегіональний або не робить нічого.
            if a1 and e.get("pos") is not None:
                after = p["text"][e["pos"] + len(str(e.get("match") or q)):]
                if DISTRICT_AFTER.match(after):
                    d = gaz.lookup(f"{q} район", near, max_km, near_a1=a1)
                    if d and (d.get("cc"), d.get("a1")) in a1:
                        hit = d
                        stats["district"] += 1
                        if d["fclass"] == "P" and " " not in norm(q):
                            # «Кашинского района» -> місто Кашин: знайдено
                            # місто, а названо район — площа (друга рецензія,
                            # «Пустынька, Кашинского района» ставала Кашином)
                            e["_district_word"] = True
                    elif hit and " " not in norm(q):
                        # Району в газетирі нема, і прикметник розвʼязався
                        # МІСТОМ («Куйбышевский район» -> Більмак, колишнє
                        # Куйбишеве). Координата лишається, але це площа: інакше
                        # місто за населенням перебиває село, назване поруч, —
                        # «Розовка, Куйбышевский район» ставала Більмаком.
                        e["_district_word"] = True
            if e.get("pos") is not None:
                after = p["text"][e["pos"] + len(str(e.get("match") or q)):]
                nq = norm(q)
                if (REGION_AFTER.match(after) and nq and " " not in nq
                        and _ADJ_TO_NOM.search(nq)):
                    key = _ADJ_TO_NOM.sub(r"\1ая", nq) + " область"
                    adm = [c for c in gaz.by_name.get(key, [])
                           if c.get("fcode") in ("ADM1", "ADM1H")]
                    if adm:
                        c = adm[0]
                        hit = {**c, "conf": "region" if near else "global",
                               "dist_km": (round(haversine(near, (c["lat"], c["lon"])))
                                           if near else None)}
                        stats["region_named"] += 1
            # Цілий субʼєкт — не крапка події. Принцип уже діяв під узгодженням
            # («Советского района» віддавало АР Крим на 1.9 млн), але лише там,
            # і в звичайній гілці лишався. Видно його стало, коли назва області
            # перестала бути маркером: у переліку «Астраханская область,
            # Республика Калмыкия, Ставропольский край» Калмикії в конфізі нема,
            # вона падає у freeform як НП, резолвиться в запис ADM1 і забирає
            # крапку в центр республіки за 300 км від названої першою області.
            #
            # Виняток той самий, що й скрізь: область російською називають
            # прикметником, тож «Харьковская» має лишитись областю, а не
            # втратити координату взагалі.
            # Винятку для прикметникової форми тут НЕМА, на відміну від гілки
            # узгодження. Там субʼєкт ВИКИДАЛИ з кандидатів, тому «Харьковская»
            # без винятку лишалась би без координати зовсім. Тут координата
            # зберігається завжди — міняється лише те, крапка це чи площа, а
            # «Харьковская» площею і є. З винятком крізь нього проходили
            # прикметникові республіки: «Чеченская», «Чувашская» — і в переліку
            # «Республика Дагестан, Республика Ингушетия, Республика Северная
            # Осетия» крапку забирала Чечня на 1.2 млн.
            subject = bool(hit) and hit.get("fcode") in ("ADM1", "ADM1H")
            if hit:
                e["lat"], e["lon"] = hit["lat"], hit["lon"]
                e["geo_name"] = hit["name"]
                e["geo_pop"] = hit["pop"]
                # Країна запису газетира. Потрібна store.launch_origin: джерело
                # пуску з російських каналів — український бік, і «Шебекинский
                # район — пуски» не має ставати пуском ІЗ Шебекиного.
                e["geo_cc"] = hit.get("cc")
                e["geo_morph"] = bool(hit.get("morph"))
                # Координату лишаємо — «Республика Чувашия — опасность по БПЛА»
                # це подія по площі, і центр республіки для неї чесний. Відсів
                # такого розвʼязання геть коштував 1321 поста координати, зокрема
                # «Пуски БПЛА Одесса» (місто лежить у газетирі під записом
                # області). Але КРАПКОЮ площа бути не може, тому conf той самий,
                # що в області, і point_entity її не бере.
                e["geo_conf"] = "centroid" if subject else hit["conf"]
                # Район — це ПЛОЩА, хай і менша за область. Мітка потрібна
                # store.point_entity, щоб район не перебивав село за населенням.
                e["geo_fcode"] = hit.get("fcode")
                e["geo_area"] = (str(hit.get("fcode") or "").startswith("ADM")
                                 or bool(e.pop("_district_word", False)))
                # І чи ця площа лежить у названій області. Потрібне там само:
                # пост часто перелічує кілька районів («Богучарский район,
                # Воронежская область — фиксации на Шолоховский район,
                # Ростовская»), і без цієї мітки серед площ вигравала б просто
                # більша за населенням, хоч би з чужої області.
                e["geo_in_region"] = bool(
                    a1 and (hit.get("cc"), hit.get("a1")) in a1)
                if subject:
                    stats["subject_area"] += 1
                e["geo_dist_km"] = hit["dist_km"]
                stats["ok"] += 1
                stats["ok_" + hit["conf"]] += 1
            else:
                stats["miss"] += 1
        if a1:
            _scope_to_district(p, gaz, a1, entity_type, stats)
    return dict(stats)


# Село, назване поруч із районом, шукається в цьому районі, а не по всій
# області. Доки район розвʼязувався містом-тезкою («Токаревский» -> Токарьовка),
# крапка стояла там; коли район почав знаходитись як ПЛОЩА (21 вересня 2026,
# наголоси в GeoNames), `point_entity` слушно віддає перевагу селу — але село
# шукалось по області, і перемагав тезка: «Васильевка, Токаревский район,
# Тамбовская» ставала іншою Васильєвкою за 40+ км від району.
#
# Район — 40-60 км завширшки, його точка в GeoNames — центроїд, тому поріг
# 50 км: село далі за нього від СВОГО району — це вже не воно.
DISTRICT_SCOPE_KM = 50.0


def _scope_to_district(p, gaz, a1, entity_type, stats):
    """Лише канонічний формат «Село, X район»: між селом і районом тільки
    розділовий знак, район — справжній запис ADM у своїй області, а нова
    відповідь — ТОЧНИЙ збіг назви. Перша версія брала будь-яку сутність далі
    50 км від будь-якої площі поста й шукала за основою — і переносила міста-
    цілі на сіл-тезок біля району джерела: «Старый Оскол» -> Staryy Gorod,
    «Краснодар» -> Krasnodarskiy (друга рецензія, 1237 переносів)."""
    ents = sorted((e for e in p.get("entities", [])
                   if e["type"] == entity_type and "lat" in e and e.get("pos") is not None),
                  key=lambda e: e["pos"])
    for x, d in zip(ents, ents[1:]):
        if (x.get("geo_area") or x.get("geo_conf") != "region"
                or not d.get("geo_in_region") or d.get("geo_conf") != "region"
                or not str(d.get("geo_fcode") or "").startswith("ADM")):
            continue
        gap = p["text"][x["pos"] + len(str(x.get("match") or x["value"])):d["pos"]]
        if not _VILLAGE_GAP.fullmatch(gap):
            continue
        # Район — лише коли так і сказано: у переліку «Белоглинский,
        # Новопокровский, Тихорецкий» без слова «район» сусід — не село цього
        # району (третя рецензія: перенос за 196 км).
        if not DISTRICT_AFTER.match(p["text"][d["pos"] + len(str(d.get("match") or d["value"])):]):
            continue
        c = (d["lat"], d["lon"])
        if haversine(c, (x["lat"], x["lon"])) <= DISTRICT_SCOPE_KM:
            continue
        near = [(haversine(c, (h["lat"], h["lon"])), h)
                for h in gaz.by_name.get(norm(x.get("match") or x["value"]), [])
                if h["fclass"] == "P" and (h.get("cc"), h.get("a1")) in a1]
        near = [dh for dh in near if dh[0] <= DISTRICT_SCOPE_KM]
        if not near:
            continue
        dist, hit = min(near, key=lambda dh: dh[0])
        x["lat"], x["lon"] = hit["lat"], hit["lon"]
        x["geo_name"], x["geo_pop"] = hit["name"], hit["pop"]
        x["geo_cc"] = hit.get("cc")
        x["geo_dist_km"] = round(dist)
        stats["district_scoped"] += 1


# Між селом і його районом — лише розділовий знак: «Анненка, Гавриловский»,
# «Ржавец, \u200bЗалегощенский», «Мещеряковский (Верхнедонской».
_VILLAGE_GAP = re.compile(r"[\s,;/(\u200b-]*")
