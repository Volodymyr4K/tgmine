"""Назви регіонів для читача.

Ключі регіонів — внутрішні. Вони лежать у полі `region` кожної зі 102 тисяч
подій, у `regions.json`, у `geo` конфіга і в `MATCH` у `mkregions.py`.
Перейменувати їх означає розсинхронізувати сховище з конфігом, тому виправлення
живе на межі подання: дані зберігають ключ, читач бачить назву.

Помічено при обході опублікованого сайту: «ТОТ_Херсон» із підкресленням і
«Ивановська» російською йшли просто в інтерфейс — у таблицях, у стрічці
спостережень, у переліку областей під тривогою і на картах нальотів.

Один модуль, а не копія в кожному генераторі: сайт і карти малюють ті самі
назви, і розʼїхатись вони не мають.
"""
from __future__ import annotations

REGION_LABEL = {
    "ТОТ_Донецьк":   "Донеччина (ТОТ)",
    "ТОТ_Луганськ":  "Луганщина (ТОТ)",
    "ТОТ_Запоріжжя": "Запоріжжя (ТОТ)",
    "ТОТ_Херсон":    "Херсонщина (ТОТ)",
    "Ивановська":    "Іванівська",
}


def region_label(name):
    """Ключ регіону -> назва для читача. Незнайоме віддається як є."""
    return REGION_LABEL.get(name, name)
