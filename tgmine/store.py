# Курс, названий словами. 2040 точкових подій (5.6%) кажуть «пролёт БПЛА на
# северо-восток» або «с юго-запада фиксации», і досі ці слова викидались, а
# вектори (vectors.py) беруть лише напрямки на топонім. Для оператора, який
# малює коридор рукою, це пряме свідчення: коротка стрілка з точки — рівно
# те, що написав канал, без жодної вигаданої геометрії.
#
# Лише знахідний відмінок після «на»/«в сторону»/«в направлении»: «на
# востоке области» (місцевий) — це місце, а не рух. «С юго-запада» — звідки
# летять, тобто курс протилежний. Кілька напрямків у пості («на север,
# северо-восток») — береться перший; таких 24 на корпус.
#
# Критична перевірка на корпусі (1934 точкові події з курсом) додала три
# винятки: «на юг от Джанкой» — це місце на південь від, не рух (8);
# «на север области/района» — теж місце (6); і збіг шукається лише в перших
# 200 символах: 92% курсів стоять у перших ста, а далі за 200 — «#Сводка»
# на пів екрана і переліки з десятка місць, де напрямок стосується
# останнього з них, а не точки події (23 випадки, з них 5 зведень).
COMPASS = {"север": 0, "северо-восток": 45, "восток": 90, "юго-восток": 135,
           "юг": 180, "юго-запад": 225, "запад": 270, "северо-запад": 315}
_DIR = r"(северо-?восток|северо-?запад|юго-?восток|юго-?запад|север|юг|восток|запад)"
_NOT_PLACE = r"(?!\s+от\b|\s+(?:области|района|края|республики|крыма|региона|города)\b)"
BEARING_TO = re.compile(
    r"(?:\bна|и\s+далее\s+на|далее\s+на|уход[яи]т\s+на|ушл[иа]\s+на|ид[ёе]т\s+на|"
    r"идут\s+на|лет[яи]т\s+на|курс(?:ом)?\s+на)\s+" + _DIR + r"\b" + _NOT_PLACE +
    r"|(?:в\s+сторону|в\s+направлении)\s+" + _DIR + r"а?\b" + _NOT_PLACE, re.I)
BEARING_FROM = re.compile(r"\b(?:с|со|от)\s+" + _DIR + r"а\b", re.I)
BEARING_SPAN = 200


def bearing_of(text: str):
    """Курс у градусах (0 — північ, 90 — схід) або None."""
    text = (text or "")[:BEARING_SPAN]
    m = BEARING_TO.search(text)
    if m:
        word = (m.group(1) or m.group(2)).lower().replace("--", "-")
        word = re.sub(r"(северо|юго)(восток|запад)", r"\1-\2", word)
        return COMPASS.get(word)
    m = BEARING_FROM.search(text)
    if m:
        word = re.sub(r"(северо|юго)(восток|запад)", r"\1-\2", m.group(1).lower())
        d = COMPASS.get(word)
        return None if d is None else (d + 180) % 360
    return None

# Число апаратів. Єдине місце в даних, де воно взагалі є, — і воно ж єдине,
# що йде у видах числом (`declared()["largest"]`), тому ціна хибного збігу
# найвища в проєкті: одне зведення МО РФ у наборі робить «найбільшу групу»
# ночі втричі більшою.
#
# Стара регулярка була `от\s+(\d+)\s*БПЛА` — 67.1% постів, де число є.
# Решту писав locatorru іншими словами: «Фиксация 2 БПЛА» (402), «пролёт
# 2 БПЛА» (328), «пролёт ещё 2 БПЛА» (80), «ещё пролёт» (53), «ещё 2 БПЛА»
# (34). Стало 83.4%.
#
# Розширювати без якоря не можна: у корпусі 1629 збігів «N БПЛА» на початку
# рядка — це майже все зведення «За прошедшую ночь ... было уничтожено 76
# БПЛА: 33 БПЛА над Саратовской...». Тому потрібен тригер спостереження ПЕРЕД
# числом і заборона на слова зведення.
DRONE_N = re.compile(r"(\d+)\s*(?:БПЛА|бпла)", re.I)
#: Тригер спостереження впритул перед числом.
DRONE_OBS = re.compile(
    r"\b(?:фиксац\w*|прол[её]т\w*|прошло|наблюда\w*|групп\w*|зашл\w*|"
    r"ид[уеё]т|появит\w*|от|ещ[ёе])\s*$", re.I)
#: Зведення, впритул перед числом: «было уничтожено 76 БПЛА». Саме впритул,
#: а не будь-де у вікні: «Приготовиться к сбитию … Фиксация от 3 БПЛА» — це
#: спостереження, і широка заборона його зʼїдала (заміряно, 3 пости).
DRONE_BAN_NEAR = re.compile(
    r"\b(?:уничтож\w*|сбит\w*|перехвач\w*|около|сосредоточ\w*)"
    r"\s*(?:более\s+)?$", re.I)
#: Маркер зведення будь-де у вікні — ці слова в спостереженнях не трапляються.
#: `\b` обовʼязкове: без нього «от» збігався всередині «сосредот-от-очить»,
#: і аналітичний абзац зі «сводки» віддавав 1600.
DRONE_BAN_FAR = re.compile(
    r"\b(?:прошедш\w*|за\s+ноч\w*|в\s+период|итог\w*)", re.I)


def drones_of(text):
    """Скільки апаратів заявлено. None, якщо числа нема або це зведення.

    Береться НАЙБІЛЬШЕ число поста, не перше. Постів із двома валідними
    числами всього 12 у корпусі, і в двох перше не найбільше: «Фиксация 8
    БПЛА / Еще от 20 БПЛА» віддавало 8. Поле годує `declared()["largest"]`,
    тобто саме «найбільша заявлена група», тож максимум тут узгоджений із
    тим, як число потім читають.
    """
    found = []
    for m in DRONE_N.finditer(text):
        back = text[max(0, m.start() - 40):m.start()]
        if DRONE_BAN_FAR.search(back) or DRONE_BAN_NEAR.search(back):
            continue
        if DRONE_OBS.search(back):
            found.append(int(m.group(1)))
    return max(found) if found else None
