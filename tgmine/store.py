def target_id(o: dict) -> str:
    """Стабільний ідентифікатор цілі. Виводиться з обʼєкта, не зберігається.

    Раніше події посилались на ціль **назвою**, і це роздувало статистику:
    назви генеруються автоматично як «категорія + найближчий НП», тож на 4659
    обʼєктів припадає лише 1983 унікальні імені. `rank_targets` робив
    `hits.get(o["name"])` — і кожен із 12 різних складів БК під Севастополем
    отримував ПОВНІ 143 попадання замість своєї частки. Виміряно: 13197
    роздано проти 4694 реальних, роздування 2.81×.

    `osm` унікальний для всіх 4623 обʼєктів з OSM (перевірено, 0 дублів).
    Куровані записи (`refineries.py`, 36 шт) osm не мають — для них ключем
    служать координати, ті самі, на яких `fetch_targets` робить дедуп.

    Не поле у файлі, а функція — щоб не тримати ще один стан, який може
    розʼїхатись, і щоб наявний targets.json не потребував міграції.
    """
    if o.get("osm"):
        return o["osm"]
    return f"c:{o.get('cat','')}:{o.get('lat')}:{o.get('lon')}"


class TargetIndex:
    """Просторовий індекс по сітці 0.25°. Без нього прив'язка 6800 подій до
    4659 обʼєктів — це 31 млн haversine; із сіткою кожна подія дивиться лише
    у свою й сусідні комірки."""
    CELL = 0.25

    def __init__(self, objects):
        self.grid = collections.defaultdict(list)
        for o in objects:
            if o.get("lat") is None:
                continue
            k = (int(o["lat"] / self.CELL), int(o["lon"] / self.CELL))
            self.grid[k].append(o)

    def nearest(self, lat, lon):
        ci, cj = int(lat / self.CELL), int(lon / self.CELL)
        best = None
        for di in (-1, 0, 1):
            for dj in (-1, 0, 1):
                for o in self.grid.get((ci + di, cj + dj), ()):
                    d = GC.haversine((lat, lon), (o["lat"], o["lon"]))
                    prio, rad = TARGET_PRIORITY.get(o["cat"], (4, 8))
                    if d > rad:
                        continue
                    # tid у ключі — щоб нічия розвʼязувалась однаково завжди.
                    # Без нього вигравав той, хто раніше у targets.json, а цей
                    # порядок перетасовує rank_targets (сортує за -imp). Сусідні
                    # будівлі одного обʼєкта (w1088757379/…80) на рівній відстані
                    # перекидались між запусками. Раніше це було непомітно, бо
                    # nearest() віддавав лише cat/name/km — у близнюків однакові.
                    score = (prio, round(d, 1), target_id(o))
                    if best is None or score < best[0]:
                        best = (score, o, d)
        if not best:
            return None
        _, o, d = best
        # tid — для звʼязку з targets.json, name — лише для показу людині.
        # Приєднуватись за name не можна: назви не унікальні (див. target_id).
        return {"tid": target_id(o), "cat": o["cat"], "name": o["name"],
                "km": round(d, 1)}


def strip_promo(text, cfg):
    """Прибирає рекламні РЯДКИ, а не весь пост.

    Пости часто змішані: «Движение по Крымскому мосту перекрыто. … Чтобы
    получать информацию, подписывайтесь на канал». Перекриття мосту — цінний
    сигнал (його закривають саме через загрозу), а фільтр по цілому посту
    викидав і його разом із рекламним хвостом.

    Повертає (очищений_текст, скільки_рядків_викинуто). Якщо після чистки
    не лишилось нічого змістовного — пост справді був суто рекламним.
    """
    if not cfg.noise:
        return text, 0
    lines = [l.strip() for l in re.split(r"\n|\s+/\s+", text) if l.strip()]
    keep = [l for l in lines if not cfg.noise.search(l)]
    return " / ".join(keep), len(lines) - len(keep)


# Заперечення, що стоїть БЕЗПОСЕРЕДНЬО перед тригером: «Ложные фиксации» — це
# спростування, канал каже «не зараховуйте», а класифікатор бачив «фиксации» й
# записував повноцінне точкове спостереження.
#
# Чому саме впритул, а не «є десь у тексті»: у корпусі 28 повідомлень зі словом
# «ложн*», але лише 3 — справжні спростування. Решта — довгі аналітичні зведення
# («#Сводка на утро…»), де слово трапляється мимохідь, а сама подія реальна.
# Виміряно: у спростуваннях відстань до тригера = 1 символ, у зведеннях —
# від 239 до 2275. Розділення чисте, поріг підбирати не довелось. Правило «є
# заперечення будь-де» зіпсувало б 11 коректно розібраних подій.
NEG_BEFORE = re.compile(r"(?:ложн|фейков|ошибочн)\w*\s*$", re.I)

# Слово «пуск» саме по собі НЕ означає, що пуск був. Заміряно на 1156 подіях
# класу: 363 з них — не пуск.
#
#   «Приготовиться к пускам УАБ самолётами противника» — пуску ще не було,
#   а назване місце (Гуляйполе) це те, куди прилетить;
#   «Ожидаем пуски УАБ или ПРР в направлении Сватово» — Сватове це ЦІЛЬ;
#   «Отбой внимания по возможной подготовке к пускам Штормов» — це відбій.
#
# Ціна помилки видна на карті: 20 вересня 2026 пуски підсвітили в редакторі,
# і на перевіреній ночі 2026-09-08 усі чотири виявились хибними — два
# попередження, одна ціль і одне «Юг» (слово «юг» стало селом Югський).
#
# Правило те саме, що в NEG_BEFORE: слово стоїть ВПРИТУЛ перед тригером, у
# вікні 24 символів. «Є десь у тексті» тут не годиться — «Пуски БПЛА от
# Одессы, возможно реактивные» це справжній пуск, а «возможно» стосується
# типу апарата й стоїть ПІСЛЯ.
#
# Минулий час лишається пуском свідомо: «возможно были пуски Штормов от
# Вознесенск» — це звіт із невпевненістю, а не план, тому «был/были» у
# перелік слів-заповнювачів не входить.
# «готов» покриває всі форми наміру, які в корпусі справді стоять перед
# тригером: «готовность к пускам», «готовьтесь», і головне «Противник готовит
# пуски БПЛА от Николаевской области» — 65 подій одним шаблоном, усі з
# майбутнім часом. Перевірено переліком форм: інших, крім цих, нема.
PLAN_BEFORE = re.compile(
    r"(?:возмож|ожида|приготов|подготовк|готов|угроз|не\s+исключ|будут|будет|для)\w*"
    r"(?:\s+(?:к|от\s+\d+|\d+|ещ[её]|будут|сейчас|снова|опять|массов\w*|очередн\w*"
    r"|повторн\w*|новы\w*|следующ\w*|единичн\w*))*\s*$", re.I)

#: Тригер «фіксації», який сам по собі спостереженням не є. У пості про
#: ОЧІКУВАНИЙ пуск «в направлении» називає задум, а не проліт: без цього
#: винятку «Ожидаем пуски УАБ в направлении Сватово» просто переїжджало з
#: «пуску» у «фіксацію» — тобто лишалось крапкою на карті, ще й під виглядом
#: спостереження. Заміряно: 36 подій.
WEAK_FIX = re.compile(r"в\s+направлении", re.I)

#: «Наблюдаем за направлением», «наблюдаем за самолётами», «наблюдаем
#: направление» у пості про ОЧІКУВАНИЙ пуск — це «стежимо», а не «бачимо».
#: Тригер фіксації «наблюда\w*» тут ловив моніторинг, і попередження
#: ставало крапкою-фіксацією: «Возможны пуски Штормов от 6 единиц.
#: Наблюдаем направление». Діє лише разом із PLAN_BEFORE, як і WEAK_FIX:
#: поза попередженням «наблюдаем» лишається спостереженням. Заміряно: 3 події.
MONITOR_AFTER = re.compile(r"\s+(?:за\b|направлени)", re.I)

#: Заперечення, що стоїть ПІСЛЯ «пуску»: «Ранее была ракетная опасность …,
#: пусков не было». NEG_BEFORE дивиться лише перед тригером, тож такий пост
#: лишався пуском. Вікно те саме, що в NEG_BEFORE, — упритул. Заміряно: 2 події.
NEG_AFTER = re.compile(
    r"\s*(?:не\s+было|нет\b|не\s+(?:за)?фиксир\w*|не\s+наблюда\w*)", re.I)

# «ё» у тригерах. Канали пишуть «пролёт» і «прилёт», а патерни KIND — «пролет»
# і «прилет», тому справжнє точкове спостереження падало в «інше».
#
# Виміряно на корпусі: «ё» є в 6.3% текстів, тип міняється у 2942 подій (1.73%),
# з них 2690 «інше» -> «фіксація». На останніх 14 добах це +514 точкових
# спостережень, тобто **+16.1%** — свіжі дані страждають удвічі більше за
# середнє по корпусу, бо locatorru (у сховищі з 22.07) пише саме з «ё».
# Ціна одного рядка: подія з «пролёт» більше не лишається без типу, а отже
# потрапляє на точковий шар карти, у жар цілей і в асоціацію треків.
#
# Нормалізуємо ЛИШЕ для класифікації, не в тексті події й не в геокоді: у
# назвах місць «ё» значуща («Орёл» узятий у configs як [её]), а газетир тримає
# обидві форми. Заміна там дала б інший клас помилок замість цього.
YO = str.maketrans("ёЁ", "еЕ")

# «вибух» лишається на СИРОМУ тексті. Перевірено поіменно всі 16 подій, які
# нормалізація перевела б у цей клас: жодна не є вибухом. Це зведення «#Сводка»
# («после прилётов горит»), попередження «возможны прилёты», звернення до
# підписників і «Множественные прилёты в окраины Одессы» — тобто удар по
# Україні. Клас «вибух» у корпусі всього 89 подій, і 16 хибних це +18% до
# єдиного класу, який говорить про НАСЛІДКИ; ціна помилки тут найвища.
# «пролёт» такої проблеми не має: там 2690 подій і всі — справжні фіксації.
RAW_KINDS = {"вибух"}

# Прийменник ПЕРЕД назвою, який робить її ціллю руху, а не місцем події.
# Голе «на X» сюди НЕ входить свідомо: у корпусі воно трапляється 21893 рази
# проти 13330 у «в направлении», і серед них «опасность по БПЛА на Крым»,
# «атака на» тощо — тобто відсів був би ширший за саме явище.
# «От X» навпаки лишається місцем: «От Белой Березки группа БПЛА» описує
# спостереження БІЛЯ Білої Березки (перевірено на 692 постах, див. конфіг).
# Роздільник переліку: кома, тире, скісна, «или»/«и». Далі за них ланцюг не
# тягнеться — крапка, новий рядок чи будь-яке слово його рвуть.
# «района» між пунктами теж не розрив: «в сторону Шаблыкинского района,
# Сосковского района» — обидва цілі (третя рецензія: ціль-район ставала
# місцем). «области» — розрив свідомо: «в сторону Курской области, Суджа — …».
ENUM_GAP = re.compile(r"[\s,\-–—/]*(?:(?:район\w*|р-н)[\s,\-–—/]*)?(?:или|и)?[\s,\-–—/]*", re.I)

# «г.»/«города» між прийменником і назвою — не розрив: «в направлении
# г.Мелитополь» ставило крапку в Мелітополі замість Михайлівки, звідки
# летіли, бо збіг вимагав назву впритул до прийменника.
DIR_BEFORE = re.compile(
    r"(?:в\s+направлени\w*|в\s+сторону|и\s+далее\s+на|курс(?:ом)?\s+на|"
    r"в\s+напр\.?)\s+(?:примерно\s+)?(?:г\.\s*|города\s+)?$", re.I)

# «От X» / «со стороны X» для топоніма, який НЕ ПЕРШИЙ у пості, — це звідки
# летять, не місце. Перший топонім лишається місцем (див. вище): «От Белой
# Березки группа БПЛА», «От Чаплынки в направлении Армянск» описують
# спостереження біля першої назви. А «Тобольск, Тюмень, Тюменская область -
# внимание по БПЛА от Свердловской области» ставило крапку в Єкатеринбурзі
# (маркер області, 1.5 млн) замість Тобольська.
#
# Спершу правило діяло лише для МАРКЕРІВ ОБЛАСТІ, і на НП не поширювалось.
# Видно це стало, коли назва області перестала бути маркером: у «Волгоградская
# область — опасность по БПЛА от Миллерово, Чертково» крапку почало забирати
# Міллерово, тобто джерело. Заміряно ІЗОЛЬОВАНО (обидві сторони геокодовані
# однаково, різниця лише у версії point_entity): 250 змін, за полігонами
# Natural Earth 47 поліпшень проти 19 погіршень.
#
# Перша версія правила брала будь-який маркер області після «от», і
# критична перевірка на сховищі до/після спіймала регрес: маркери міст
# (Маріуполь, Чаплинка, Геническ) теж мають тип «регіон», тож «От Мариуполь
# в направлении Новоазовск, Таганрог» віддавало Таганрог — ціль руху.
# Ознака «не перший топонім» розділяє обидва випадки й для області, й для
# міста: «Знаменск / … от Г. Волгоград» — Волгоград джерело.
#
# Заміряно на сховищі до/після (спільні id): 550 подій міняють крапку,
# точок далі 250 км від власної області 3886 -> 3863. Загальний пріоритет
# села над маркером міста натомість відкинуто: 14 533 змін і «далеких»
# більше на 2271 — маркер надійніша координата за село-тезку.
SRC_BEFORE = re.compile(
    r"(?:\bот|со\s+стороны)\s+(?:г\.\s*|города\s+|Республики\s+)?$", re.I)


# ---- ПУСК: крапка стоїть на ДЖЕРЕЛІ ------------------------------------------
#
# Для фіксації місце події — де бачили, і «от X» там джерело, яке треба
# ВІДКИНУТИ (SRC_BEFORE вище). Для пуску навпаки: подія — це сам пуск, і його
# місце — звідки пустили. Розбір 21 вересня 2026 на 547 крапках-пусках: на
# джерелі стояли лише 219 (40%), решта — на цілі, бо координата бралась
# звичайним способом: найбільший НП, а без нього — перша область поста, тобто
# область-ціль. У 147 випадках джерело було назване прямо.
#
# Прийменник джерела ширший, ніж у SRC_BEFORE: «из-под Чернигова», «с района
# Днепра», «из Сум» у пості про пуск означають те саме, що «от». Визначення
# живе в geocode — там такі назви ще й геокодуються окремо.
LAUNCH_SRC_BEFORE = GC.LAUNCH_SRC_BEFORE

#: «Суджанский район — пуски с авиации», «Рыльск — пуски с авиации в вашу
#: сторону»: пускають із літака В БІК названого місця, тож воно — ціль. Форма
#: поста та сама, що в «Таирово — пуски БПЛА в акваторию» (там місце —
#: джерело); відрізняє саме носій. 102 крапки-пуски стояли так у РФ.
LAUNCH_FROM_AIR = re.compile(
    r"пуск\w*\s+(?:\S+\s+){0,2}?(?:(?:с|со)\s+)?(?:авиаци|самол[её]т|воздух|борт|носител)"
    r"|(?:авиаци\w*|самол[её]т\w*)\s+(?:\S+\s+){0,2}?пуск", re.I)


def launch_origin(p):
    """Сутність-джерело для поста про пуск, або None, якщо джерела в тексті нема.

    Порядок: явний прийменник джерела; далі, якщо пуск не з літака, — перше
    місце поста (формат «Таирово — пуски», «Славянск ещё пуски РСЗО»).

    Джерело має бути в Україні за газетиром (`cc`): канали — російські й
    пишуть про пуски з українського боку. Без цього «Шебекинский район —
    пуски РСЗО» ставав би пуском ІЗ Шебекиного. Підконтрольна чи окупована —
    правило свідомо не питає: це робота незалежного арбітра
    (`territory.depth_km`) під час заміру, інакше замір став би колом.
    """
    text = p["text"]
    ents = sorted((e for e in p.get("entities", [])
                   if "lat" in e and e.get("pos") is not None
                   and e.get("type") in ("нп", "регіон")),
                  key=lambda e: e["pos"])

    def before(e):
        return text[max(0, e["pos"] - 24):e["pos"]]

    def ukrainian(e):
        return e.get("geo_cc") == "UA"

    # Перше УКРАЇНСЬКЕ джерело, а не перше будь-яке: «опасность по БПЛА от
    # Брянской области. / Продолжаются пуски БПЛА от Чернигов» — перше «от»
    # тут про загрозу по області РФ, і правило здавалось, не дійшовши до
    # Чернігова.
    # «От Крынки до Великая Лепетиха … готовность к атаке БПЛА, запускаемых из
    # Николаевской области» — «от X до Y» це ПРОМІЖОК місцевості під загрозою,
    # а не джерело; джерело там — Миколаївщина.
    def span_start(e):
        tail = text[e["pos"] + len(str(e.get("match") or e["value"])):]
        return re.match(r"\s+до\s", tail) is not None
    srcs = [e for e in ents if LAUNCH_SRC_BEFORE.search(before(e)) and not span_start(e)]
    if srcs:
        return next((e for e in srcs if ukrainian(e)), None)
    if LAUNCH_FROM_AIR.search(text):
        return None
    for e in ents:
        if DIR_BEFORE.search(before(e)):
            return None
        return e if ukrainian(e) else None
    return None


# Фолбек для «іншого»: апарат названий і сказано, КУДИ він іде, але жодного
# слова-тригера в пості нема. «От Светлодарска в сторону Дебальцево группа
# БПЛА», «2 БПЛА через Сельцо в сторону Калужской области» — це точкові
# спостереження, які лежали в «іншому» з `scope="область"`, тобто не бачила
# ні карта, ні жар цілей.
#
# Чому саме фолбеком, а не тригером у KIND: додати «в сторону» просто до
# «фіксації» — виміряно — перекидає 127 ТРИВОГ у точкові спостереження
# («опасность по БПЛА и в сторону Калужской области»). Це рівно те змішування
# тривоги зі спостереженням, від якого карта стає безінформативною. Фолбек
# спрацьовує лише там, де не виграв ніхто, тож тривоги не чіпає взагалі.
#
# Заміряно: 1709 подій по сховищу, 84 за останні 15 діб; 82 зі 84 мають
# координату, з промо-рядками лише 1.
DRONE_MOVE = re.compile(
    r"(?:БПЛА|бпла|дрон\w*)[\s\S]{0,60}?"
    r"(?:в\s+сторону|в\s+направлении|направление|ид[уёе]т|движени\w*|"
    r"заход\w*|прошл\w*)"
    r"|(?:в\s+сторону|в\s+направлении|направление|ид[уёе]т|движени\w*|"
    r"заход\w*)[\s\S]{0,60}?(?:БПЛА|бпла|дрон\w*)", re.I)


# Фолбек не має права спрацьовувати там, де про БпЛА пишуть, а не бачать:
# зведення, збір на квадрокоптери («Эти дроны — не каприз»), довідка «Возможные
# цели БПЛА Севастополь» і шаблон «Дорожное направление Акимовка - Мелитополь»
# (перелік трас, не точка; freeform ще й бере з нього село Дорожне). Заміряно
# на 1709 спрацюваннях: під цей список потрапляє рівно 9, усі — не
# спостереження. Стоїть ЛИШЕ у фолбеку: 7 справжніх фіксацій із тригером KIND
# мають ті самі слова у хвості й лишаються фіксаціями.
MOVE_GUARD = re.compile(
    r"#Сводка|#Обзорная|нуждаются|донат|возможные\s+цели|Дорожное\s+направление",
    re.I)

# Тактичні дрони ПРИФРОНТУ — не на карту (рішення оператора 22-23.09.2026:
# «ніякої баби яги, хорнетів, фпв», уточнено — «прибрати тільки прифронт,
# все інше треба залишити, якщо це скиди фпв з бортів бпла які далеко
# літають»). Карта — нічний наліт дальніх ударних БпЛА; FPV, «Баба Яга»,
# «Хорнет», «Шарк», «Дартс», розвідники на лінії фронту — інше явище. А те
# саме далеко від фронту — ФПВ із дронів-носіїв і морських дронів у Криму,
# Бердянську, Генічеську, Хорнети на Джанкой чи Севастополь — удар у
# глибину, лишається. Правило одне для назв моделей і для ФПВ: v29 прибирав
# моделі скрізь, і це розійшлось зі словами оператора (810 подій далеко від
# фронту, рецензія 23.09). Пост лишається в сирому шарі; вид «інше» — лише
# в похідному, тож рішення обертається перебудовою.
#
# «Шарк» — лише назва з відмінками: `\bшарк` ловив Шарканський район
# Удмуртії. «fpv» без кінця слова — «fpvпротивника».
TACTICAL = re.compile(
    r"\bфпв|\bfpv|баба[\s-]?яг|хорнет|hornet|\bшарк(?:а|у|ом|и|ов)?\b|\bshark"
    r"|дартс|чаклун|\bмайя\b|мавик|mavic|разведчик|разведыват"
    r"|разведк\w*\s+(?:бпла|дрон)|(?:бпла|дрон\w*)[\s-]+разведк", re.I)
#: Прифронт — ближче цього до підконтрольної Україні території. `depth_km`
#: рахується до ЦІЛИХ підконтрольних областей (чотири спірні вилучено), тож
#: там, де фронт іде всередині області, глибина завищена — і поріг свій:
#: Донеччина — Горлівка 84, Світлодарськ 89 (фронт), Шахтарськ 113 (тил);
#: Запоріжжя — Кам'янка-Дніпровська 3, Токмак 67 (фронт), Мелітополь 83;
#: решта ≤60 — Олешки 24 (фронт), Каланчак 73, Генічеськ 151, Луганськ 129.
FRONT_KM = 60
FRONT_KM_BY_REGION = {"ТОТ_Донецьк": 90, "ТОТ_Запоріжжя": 70}
#: Події без надійної крапки (центр області, відкат, найслабший геокод): там
#: глибина — до центру області чи до тезки (Брянська — 107 км, «Любимовка»
#: під Севастополем -> Любимівка на Херсонщині) і нічого не каже. Пост про
#: всю область із ФПВ у цих областях — прикордоння («Приграничные районы
#: Брянской, Курской, Белгородской…»); Херсонщини тут нема — «Все районы
#: Херсонской… носители ФПВ» це носії.
BORDER_AREAS = {"Бєлгородська", "Брянська", "Курська", "ТОТ_Донецьк"}
#: Слова прикордоння — лише для постів без надійної крапки («БПЛА-разведка
#: над Белой Березкой», коли село не розвʼязалось): у всьому тексті вони
#: ловили довгі зведення глибокого тилу (14 «#Сводка»).
BORDER_WORDS = re.compile(r"пригранич|госграниц|\bгг\b|бел(?:ой|ая)\s+березк", re.I)

_REGION_POLYS = None


def point_region(lat, lon):
    """Область за КРАПКОЮ (полігони `regions.json`), а не за текстом поста:
    «Авдеевка … фпв» без слова «ДНР» мала region=None і лишалась на карті,
    а той самий текст зі словом — прибирався (рецензія v29)."""
    global _REGION_POLYS
    if _REGION_POLYS is None:
        raw = json.loads((Path(__file__).resolve().parent.parent / "regions.json")
                         .read_text(encoding="utf-8"))
        _REGION_POLYS = []
        for name, rings in raw.items():
            pts = [p for r in rings for p in r]
            bb = (min(p[0] for p in pts), min(p[1] for p in pts),
                  max(p[0] for p in pts), max(p[1] for p in pts))
            _REGION_POLYS.append((name, rings, bb))
    for name, rings, (la0, lo0, la1, lo1) in _REGION_POLYS:
        if not (la0 <= lat <= la1 and lo0 <= lon <= lo1):
            continue
        inside = False
        for ring in rings:
            n = len(ring)
            for k in range(n):
                y1, x1 = ring[k]
                y2, x2 = ring[(k + 1) % n]
                if (y1 > lat) != (y2 > lat) and lon < (x2 - x1) * (lat - y1) / (y2 - y1) + x1:
                    inside = not inside
        if inside:
            return name
    return None


def plain_kind(text):
    """Вид лише з тексту, без фолбеку й з тактичними словами як «іншим» —
    для ознаки шуму й дедуплікації дзеркала, яким місце поста невідоме.
    Без тактики тут збори коштів зі словом «ФПВ» ставали подіями (6), а
    пара kupol/lpr1 розбивалась, коли одна сторона тактична (рецензія v29)."""
    if TACTICAL.search(text.translate(YO)):
        return "інше"
    return kind_of(text, fallback=False)


def tactical(text, region, places=(), sure=True):
    """Пост про тактичний дрон ПРИФРОНТУ — такий на карту не йде.

    `places` — [(lat, lon)] місць поста (крапка й інші місця «тут»): пост
    прифронтовий, якщо прифронтове хоч одне («Климово … тревога по ФПВ /
    Брянск…» — крапка на Брянську за 109 км, а Климово на кордоні).
    Область для кожного місця — за крапкою, запасна — з тексту. `sure` —
    чи крапка надійна; інакше вирішують область і слова прикордоння."""
    t = text.translate(YO)
    # Зведення й огляди («#Сводка на утро … FPV … приграничные районы …») —
    # не пост про тактичний дрон: серед десятків місць завжди знайдеться
    # прифронтове, і v29-правка прибирала зведення Москви й Ленінграда.
    if not TACTICAL.search(t) or len(t) > DRONE_MAXLEN:
        return False
    if not sure:
        return region in BORDER_AREAS or bool(BORDER_WORDS.search(t))
    for lat, lon in places:
        reg = point_region(lat, lon) or region
        if depth_km((lat, lon)) <= FRONT_KM_BY_REGION.get(reg, FRONT_KM):
            return True
    return False


# Другий фолбек «іншого»: апарат названий, і пост каже, що він ТУТ, але без
# слова-тригера і без слова руху. «Ярославль / 3 БПЛА над городом», «Сольцы …
# группа БПЛА на север», «От Узловая на Новомосковск БПЛА». Навпаки,
# «Мелитополь приготовиться к массовой атаке БПЛА» — тривога: апарата ще нема.
# Порядок як у DRONE_MOVE: лише коли жоден тригер KIND не виграв, тож «тревога
# по БПЛА» лишається тривогою.
#
# Історія (22.09.2026). Перша версія (v27) брала й назви моделей, і «в вашем
# направлении», і «группа» — сліпа розмітка 60 випадкових нових фіксацій із
# контекстом дала 83% правильних; хибні — «в вашем направлении» / «в вашу
# сторону» (7 з 10: апарат летить СЮДИ, ще не тут, крапка ставала на цілі) і
# «возможно группа». Рецензія знайшла ще: тактичні моделі (див. `tactical`),
# крапки в Україні й на найслабшому геокоді (`_event` тепер їх не пускає),
# пуски («готовит запуски … на Горловку») і мертву велику літеру в «от X на
# Y» (`re.I` робив `[А-ЯЁ]` будь-якою).
DRONE_WORD = re.compile(r"бпла|беспилотник\w*|дрон\w*", re.I)
#: Апарата ще нема: готуються, чекають, летить СЮДИ, можливо. Голе «атака»
#: сюди не входить: «В результате атаки БПЛА … возгорание», «отражена атака
#: на НПЗ» — звіти про наслідки (153 пости по сховищу).
DRONE_PREP = re.compile(
    r"приготов\w*|возможн\w*|вероятн\w*|(?:под|к)\s+атак\w*|\bготов\w*\s+к"
    r"|\bбуд(?:ет|ут)\b|ожида\w*|в\s+вашем\s+направлении|в\s+вашу\s+сторону"
    r"|в\s+ваш\w*\s+район", re.I)
#: Спостереження коротке (медіана спрацювань 63 символи). Довші за межу —
#: звернення, огляди, новини про наслідки («Убедительно просим не снимать
#: работу ПВО»): 124 із 5125 спрацювань по сховищу, справжніх серед них
#: одиниці, а 18 зборів коштів переставали б бути шумом (`noise` у `_event`
#: — промо-рядок І вид «інше»).
DRONE_MAXLEN = 220
#: Ознаки присутності: «в небе», «над», число апаратів, «много», курс
#: сторонами світу, «от X на Y», траса, «летит/кружит».
DRONE_HERE = re.compile(
    r"в\s+небе|\bнад\s|\b\d+\s*(?:\w+\s+)?(?:бпла|дрон)|больш\w+\s+количеств|\bмного\b"
    r"|несколько|подход\w*|лет(?:ит|ят|ает|ают)|кружит|(?:по|вдоль|над)\s+трасс"
    r"|\bна\s+(?:юг|север|восток|запад|ю-?в|с-?в|ю-?з|с-?з)"
    r"|\bот\s+\S+[^/\n]{0,40}?\bна\s+(?-i:[А-ЯЁ])", re.I)
#: Пуск і вихід у море — не спостереження над місцем, навіть із «БПЛА»:
#: «Возможно пуски … от Чугуев», «выход БПЛА в море от Затоки».
DRONE_LAUNCHISH = re.compile(r"пуск|выход\w*|вылет\w*", re.I)


def kind_of(text, fallback=True):
    """Вид поста. `fallback=False` — без другого фолбеку (DRONE_*): так вид
    бачить `plain_kind` для шуму й дзеркала (копія kupol без рядка загрози
    інакше ставала фіксацією при тривозі-оригіналі в lpr1, і пара дзеркала
    розбивалась — 30 пар у v27) і `_event`, щоб знати, чи вид узято
    фолбеком."""
    norm = text.translate(YO)
    # Пуск, який ще ТІЛЬКИ ОЧІКУЮТЬ, не є пуском — по КОЖНІЙ згадці, як
    # NEG_BEFORE: пуск є, якщо хоч одна згадка — факт.
    #
    # Історія рішення. Спершу прапорець був на весь пост: єдиний змішаний
    # пост тоді — брянський огляд, де «по згадці» ставив би пуск на Брянщині.
    # Відколи пуск стоїть на джерелі (launch_origin), такий огляд стає пуском
    # БЕЗ джерела, тобто без крапки, і причина зникла. А з «запуском» у
    # тригері зʼявилась протилежна вада: «Продолжаются пуски БПЛА от
    # Черниговской … не исключаем, что противник готовит массовый запуск на
    # 12 июня» — речення про майбутнє знищувало пуск, що вже йде.
    #
    # «автоматического запуска» (звіт про збір на РЕБ) — механізм, а не подія.
    #
    # Коли в пості є намір, гасяться три речі: сам «пуск», слабкі тригери
    # фіксації («в направлении», «наблюдаем за …») і фолбек «БпЛА + слово
    # руху». Без останніх попередження не зникало, а переїжджало у «фіксацію»
    # і лишалось крапкою на карті. Заміряно на сховищі (1156 пусків): після
    # першої версії 793, після «готовит» 728, після третьої ітерації 715;
    # далі «запуск» у тригері ДОДАВ 437 справжніх пусків, а широке вікно
    # наміру прибрало 29 — стало 1105 (21 вересня 2026; числа включають свіжі
    # пости, що доходили між правками).
    def launch_is(m):
        before = norm[max(0, m.start() - 24):m.start()]
        if NEG_BEFORE.search(before):
            return "ні"
        # Для наміру вікно ширше: між словом наміру й «пуском» дозволені
        # заповнювачі, і «готовит очередной массовый запуск» — 27 символів,
        # «готовит» випадало з 24-символьного вікна (29 подій, зокрема
        # підсвічений у редакторі «пуск» 10 серпня). Шаблон і так прикутий до
        # кінця вікна й пропускає лише перелічені заповнювачі.
        if PLAN_BEFORE.search(norm[max(0, m.start() - 60):m.start()]):
            return "намір"
        if NEG_AFTER.match(norm, m.end()):
            return "ні"
        if re.search(r"автоматическ\w*\s*$", before, re.I):
            return "ні"
        return "так"
    verdicts = [launch_is(m) for m in LAUNCH_RX.finditer(norm)]
    launched = "так" in verdicts
    planned = "намір" in verdicts and not launched

    def weak(m, s):
        w = m.group(0)
        return (WEAK_FIX.fullmatch(w) is not None
                or (w.lower().startswith("наблюда")
                    and MONITOR_AFTER.match(s, m.end()) is not None))

    for n, rx in KIND:
        if n == "пуск":
            if launched:
                return n
            continue
        s = text if n in RAW_KINDS else norm
        # finditer, а не search: якщо перший збіг заперечений, а далі є
        # незаперечений — тип усе одно чинний.
        ms = [m for m in rx.finditer(s)
              if not NEG_BEFORE.search(s[max(0, m.start() - 24):m.start()])]
        if planned and n == "фіксація":
            ms = [m for m in ms if not weak(m, s)]
        if ms:
            return n
    if DRONE_MOVE.search(norm) and not MOVE_GUARD.search(norm) and not planned:
        return "фіксація"
    # намір окремо не перевіряється: він буває лише зі словом «пуск», а пост
    # із ним сюди не йде (DRONE_LAUNCHISH)
    if fallback and DRONE_WORD.search(norm) and len(norm) <= DRONE_MAXLEN \
            and not DRONE_LAUNCHISH.search(norm) \
            and not MOVE_GUARD.search(norm):
        if DRONE_PREP.search(norm):
            return "тривога"
        if DRONE_HERE.search(norm):
            return "фіксація"
    return "інше"


_FROM_WORD = re.compile(r"\bот\b|со\s+стороны|\bиз(?:-под)?\b", re.I)
_TOWARD_WORD = re.compile(r"в\s+направлени|в\s+сторону|\bдалее\b|\bна\b|\bкурс", re.I)


def _from_side(text, e):
    """Останнє слово руху в рядку перед назвою — «от/из»: назва є джерелом."""
    pos = e.get("pos")
    if pos is None:
        return False
    line = text[text.rfind("\n", 0, pos) + 1:pos]
    src = [m.start() for m in _FROM_WORD.finditer(line)]
    dst = [m.start() for m in _TOWARD_WORD.finditer(line)]
    return bool(src) and (not dst or src[-1] > dst[-1])


def _aim_ids(p, pts, first_pos):
    """id() сутностей поста, що є ЦІЛЛЮ руху (або джерелом для не-першої)."""
    def before(e):
        return p["text"][max(0, e.get("pos", 0) - 24):e.get("pos", 0)]
    named = [e for e in p.get("entities", []) if "lat" in e]
    aim = {id(e) for e in named if DIR_BEFORE.search(before(e))
           or (e in pts and e.get("pos") != first_pos and SRC_BEFORE.search(before(e)))}
    # Прийменник стоїть лише перед ПЕРШОЮ назвою переліку: «и далее на
    # Жуковку, Брянск», «в направлении Ялта - Алушта - Судак - Феодосия».
    # Без цього кроку правило ловило перший пункт, а крапка переїжджала на
    # другий — виміряно, 168 постів із 1026 (16%). Продовжуємо, поки між
    # назвами лише роздільники.
    order = sorted(named, key=lambda e: e.get("pos", 0))
    for prev, cur in zip(order, order[1:]):
        if id(prev) in aim and id(cur) not in aim:
            gap = p["text"][prev.get("pos", 0)
                            + len(str(prev.get("match") or "")):cur.get("pos", 0)]
            if ENUM_GAP.fullmatch(gap):
                aim.add(id(cur))
    return aim


#: Ближче — те саме місце, що вже показане.
ALSO_SAME_KM = 10.0
#: Район, у межах якого вже є показане місце, — підпис до нього, а не ще одне
#: місце («Алымова, Карачевский район»).
ALSO_AREA_KM = 40.0


#: Слово руху раніше в тому ж реченні — назва далі по реченню вже ціль
#: («пролёт БПЛА на Сагуны, Костомарово», «Возможно далее на
#: Новокуйбышевск», «траектория на Мирный»). Для крапки події цього
#: правила нема (там `DIR_BEFORE` упритул), для ДОДАТКОВИХ місць — є:
#: помилкове додаткове місце гірше за пропущене. «на территории» (РСЧС) —
#: не рух. «курс» — лише «курс(ом) на»: голе `курс\w*` без регістру ловило
#: «Курская/Курской/Курск», і всі місця після Курщини ставали цілями
#: (спіймано 22.09.2026 на зведенні МО «над территориями … Курской, …»).
#: Голе «на» — рух, крім частин назв («Славянск на Кубани», «Калач на Дону»)
#: і місця дії («на территории», «на границе», «на побережье»).
_MOVE_IN_SENT = re.compile(
    r"направлени|(?:\bв\s+)?\bсторон[уы]\b|далее|\bкурс(?:ом)?\s+на\b|траектори|\bвыход\w*\s+на|подвернуть|"
    r"\bуйти\b|\bпойд|\bчерез\b|\bв\s+обход|"
    r"\bна\s+(?!территори|границ|побереж|окраин|Дону\b|Кубани\b|Волге\b|участк|связи|"
    r"момент|высот|месте|стык)", re.I)
#: Рядок, що обривається словом руху: наступні рядки-місця — цілі.
_MOVE_DANGLING = re.compile(r"(?:направлени\w*|далее|сторону|\bна|\bв)\s*:?\s*$", re.I)
_EVENT_LINE = re.compile(r"тревог|опасн|фиксац|отбой|сбит|\bпво\b|внимани|угроз", re.I)


#: Крапка після скорочення («г.», «с.», «пгт.», «ст.») — не кінець речення:
#: «далее … на г.Ярославль» інакше рвало речення перед Ярославлем, і ціль
#: ставала місцем (сліпа перевірка 22.09.2026).
_ABBR_DOT = re.compile(r"(?:^|[\s,(])(?:г|с|п|д|х|ст|пгт|пос|р-н|обл|с/п)\.$", re.I)


def _sent_start(text, pos):
    i = pos
    while True:
        j = max(text.rfind(c, 0, i) for c in ".!?\n")
        if j < 0:
            return 0
        if text[j] == "." and _ABBR_DOT.search(text[max(0, j - 5):j + 1]):
            i = j
            continue
        return j + 1


def _label_district(text, e, ents):
    """Район одразу після іншої назви в тому ж рядку — підпис до неї
    («Клименково, Ровеньский район», «Донецк ДНР Пролетарский,
    Буденновский районы»), а не окреме місце."""
    ls = text.rfind("\n", 0, e["pos"]) + 1
    for o in ents:
        op = o.get("pos")
        if op is None or not (ls <= op < e["pos"]):
            continue
        if o.get("geo_area") or o.get("type") not in ("нп", "регіон"):
            continue
        if "lat" in o and o.get("geo_conf") == "centroid":
            continue
        # Нерозвʼязана назва — лише впритул перед районом («Клименково,
        # Ровеньский район»): інакше слово на початку речення («Продолжается
        # пролёт … от Харьковской области») робило підписом саму область.
        if "lat" not in o:
            gap = text[op + len(str(o.get("match") or "")):e["pos"]]
            if not re.fullmatch(r"[\s,]*", gap):
                continue
        return True
    return False


def _moving_to(text, pos):
    """Назва на позиції `pos` стоїть після слова руху — у реченні чи під
    обірваним рядком «И далее в направлении»."""
    start = _sent_start(text, pos)
    if _MOVE_IN_SENT.search(text[start:pos]):
        return True
    ls = text.rfind("\n", 0, pos)
    while ls > 0:
        prev_start = text.rfind("\n", 0, ls) + 1
        prev = text[prev_start:ls]
        if _MOVE_DANGLING.search(prev):
            return True
        if _EVENT_LINE.search(prev):
            return False
        ls = prev_start - 1
    return False


_CHAIN_GAP = re.compile(r"\bдалее\b|\bзатем\b|\bпотом\b|\bпосле\b|\bс\s+выходом", re.I)
#: «из Брянской области», «с Белгородской области» — джерело для ОБЛАСТІ
#: (для НП «с»/«из» надто багатозначні: «с моря», «с юга»).
_SRC_REGION = re.compile(r"(?:\bиз|\bс)\s+$", re.I)
#: Назва саме ОБЛАСТІ, а не міста-маркера («Крыма», «Ростовской», а не
#: «Луганск»): лише така ціль може бути «своєю областю» без змісту.
_REGION_NAME = re.compile(r"(?:ск|цк)(?:ой|ую|ая|ий|ого|ому|им)$|^Крым|^Республик|^ЛНР$|^ДНР$", re.I)
_VIA_BEFORE = re.compile(r"(?:\bчерез|\bв\s+обход|\bвдоль)\s+(?:г\.\s*)?$", re.I)


_SUMMARY = re.compile(r"за\s+прошедш|в\s+течение\s+прошедш|перехвачены\s+и\s+уничтожены|"
                      r"над\s+территори|#сводка|#обзор|уничтожено\s+\d+", re.I)


#: Між назвою й підписом-областю може стояти район: «Кутейниково,
#: Чертковский район, Ростовская область».
_LABEL_GAP = re.compile(r"[\s,]*(?:(?:район\w*|р-н|го|мо|округ\w*)[\s,]*)?", re.I)


def _region_label(text, e, regs, ents):
    """Область-підпис: окремий рядок «Липецкая область» або хвіст «Иловка
    Белгородская область» одразу після іншої назви — лише уточнює, де
    сусідні місця, і ні ціллю, ні джерелом не є."""
    if e.get("type") != "регіон" or e.get("geo_conf") != "centroid":
        return False
    ls = text.rfind("\n", 0, e["pos"]) + 1
    if GC._is_label(text, ls, regs):
        return True
    gap_start = max((o["pos"] + len(str(o.get("match") or "")) for o in ents
                     if o is not e and o.get("pos") is not None and ls <= o["pos"] < e["pos"]),
                    default=None)
    return gap_start is not None and _LABEL_GAP.fullmatch(text[gap_start:e["pos"]]) is not None


def _right_after_name(text, e, ents):
    """Назва стоїть упритул після іншої назви в тому ж рядку («Кутейниково,
    Чертковский район») — тоді район є її підписом, навіть після слова руху."""
    for o in ents:
        op = o.get("pos")
        if op is None or o is e or op >= e["pos"]:
            continue
        end = op + len(str(o.get("match") or ""))
        if end <= e["pos"] and re.fullmatch(r"[ \t,]*", text[end:e["pos"]]):
            return True
    return False


def legs_of(p, best=None):
    """Рух, який ЗАЯВИВ пост: [(звідки, куди)] сутностями поста.

    До 22.09.2026 рух читав окремий розбір (`vectors.parse`) зі своїм
    шаблоном назв: одна ланка на пост, кінці-області відкидались, і за
    еталоном витягувалась третина заявленого руху (BACKLOG §16.11). Тут —
    ті самі сутності й ролі, що й для крапки: ціль — `_aim_ids` або слово
    руху раніше в реченні (`_moving_to`); джерело — «от X»/«со стороны X»;
    «через X» — проміжна точка; решта — місце «тут».

    Звідки: джерело поста, інакше його крапка (`best`), інакше перше місце.
    Ціль після «далее/затем» продовжує ланцюг від попередньої цілі
    («… на Анна, Эртиль и далее на Тамбовскую область»); ціль переліку
    («в сторону Кирсанов, Умет») — від того самого «звідки». Кінцем може
    бути ціла область — позначка площі їде далі (жирна стрілка, §16.10).
    """
    text = p.get("text") or ""
    # Зведення МО РФ («уничтожено 512 БПЛА над территориями Белгородской,
    # Брянской…») — перелік областей, не рух.
    if _SUMMARY.search(text):
        return []
    regs = [e for e in p.get("entities", []) if e.get("type") == "регіон"]
    ents = sorted((e for e in p.get("entities", [])
                   if "lat" in e and e.get("pos") is not None and not e.get("inherited")
                   and not _region_label(text, e, regs, p.get("entities", []))
                   and not (e.get("geo_area") and _label_district(text, e, p.get("entities", []))
                            and (not _moving_to(text, e["pos"])
                                 or _right_after_name(text, e, p.get("entities", []))))),
                  key=lambda e: e["pos"])
    if len(ents) < 2:
        return []

    def before(e):
        return text[max(0, e["pos"] - 24):e["pos"]]
    first_pos = ents[0]["pos"]
    aim = _aim_ids(p, [e for e in ents if e.get("geo_conf") != "centroid"], first_pos)
    role = {}
    for e in ents:
        if SRC_BEFORE.search(before(e)) or _SRC_REGION.search(before(e)) and e.get("type") == "регіон":
            role[id(e)] = "from"
        elif _VIA_BEFORE.search(before(e)):
            role[id(e)] = "via"
        elif id(e) in aim or _moving_to(text, e["pos"]):
            role[id(e)] = "to"
        else:
            role[id(e)] = "here"
    targets = [e for e in ents if role[id(e)] == "to"]
    if not targets:
        return []
    sources = [e for e in ents if role[id(e)] == "from" and e["pos"] < targets[0]["pos"]]
    here = [e for e in ents if role[id(e)] == "here" and e["pos"] < targets[0]["pos"]]
    # Ціла область — «звідки», лише коли пост так і каже («от Брянской
    # области») або іншого місця нема. Підпис «Краснодарский край» у пості
    # про Керч інакше ставав початком руху (сліпа перевірка 22.09.2026).
    here_pts = [e for e in here if e.get("geo_conf") != "centroid"]
    if sources:
        origin = sources[-1]
    elif best is not None and role.get(id(best)) == "here" and best.get("geo_conf") != "centroid":
        origin = best
    elif here_pts:
        origin = here_pts[0]
    elif here:
        origin = here[0]
    else:
        return []
    legs, prev = [], None
    vias = [e for e in ents if role[id(e)] == "via" and origin["pos"] < e["pos"] < targets[0]["pos"]]
    cur = origin
    for v in vias:
        legs.append((cur, v))
        cur = v
    start = cur
    for t in targets:
        if prev is not None and _CHAIN_GAP.search(text[prev["pos"]:t["pos"]]):
            src = prev
        else:
            src = start
        # «…в направлении Крыма» зі старту в Криму — ланка без змісту.
        same_region = (t.get("geo_conf") == "centroid" and src.get("geo_conf") != "centroid"
                       and _REGION_NAME.search(str(t.get("match") or ""))
                       and any(o is not t and o.get("type") == "регіон"
                               and o.get("value") == t.get("value") and o.get("pos") is not None
                               and not _moving_to(text, o["pos"])
                               for o in p.get("entities", [])))
        if src is not t and not same_region and \
                GC.haversine((src["lat"], src["lon"]), (t["lat"], t["lon"])) > 5:
            legs.append((src, t))
        prev = t
    return legs


def also_places(p, best):
    """Інші місця поста, де бачили, крім `best` — для карти (поле `also`).

    Пост -> одна крапка губив половину місць: за еталоном (BACKLOG §16.11)
    карта показувала 40-54% місць «тут». Сюди йдуть усі розвʼязані НП і
    райони поста, що НЕ є ціллю чи джерелом руху (та сама логіка, що в
    `point_entity`), не центр області, не успадковані від батька; ближчі за
    ALSO_SAME_KM до вже взятого — повтор; район поруч із уже взятим місцем
    — підпис до нього.
    """
    if best is None or "lat" not in best:
        return []
    # Пуск стоїть на джерелі; решта місць поста про пуск — цілі й траси.
    if kind_of(p.get("text") or "") == "пуск":
        return []
    ents = [e for e in p.get("entities", []) if "lat" in e and not e.get("inherited")
            and e.get("geo_conf") not in ("centroid", "region-snap", None)
            and e.get("pos") is not None]
    if not ents:
        return []
    first_pos = min((e.get("pos", 0) for e in p.get("entities", [])
                     if e.get("pos") is not None and "lat" in e
                     and e.get("type") in ("нп", "регіон")), default=None)
    aim = _aim_ids(p, ents, first_pos)
    taken = [best]
    out = []
    for e in sorted(ents, key=lambda e: (bool(e.get("geo_area")), e.get("pos", 0))):
        if id(e) in aim or e is best or _moving_to(p["text"], e["pos"]):
            continue
        if e.get("geo_area") and _label_district(p["text"], e, p.get("entities", [])):
            continue
        near = min(GC.haversine((e["lat"], e["lon"]), (t["lat"], t["lon"])) for t in taken)
        if near < ALSO_SAME_KM or (e.get("geo_area") and near < ALSO_AREA_KM):
            continue
        taken.append(e)
        out.append(e)
    return sorted(out, key=lambda e: e.get("pos", 0))


def point_entity(p):
    """Топонім, який дає події координату.

    Береться найбільший за населенням — і саме тому в крапку перетворювалась
    ЦІЛЬ РУХУ: місто, куди летить, майже завжди більше за село, звідки
    дивляться. «Ст. Крыловская … в направлении Сальск» ставила крапку в
    Сальську за 200 км, «д. Сапогово Курский район в направлении Халино» —
    у Халіно, «Майкоп в направлении примерно Сочи» — у Сочі.

    Виміряно на 15 добах: так стояли 286 із 8414 координат (3.4%). Напрямки
    й так витягує `vectors.py` окремо, тобто в точковий шар вони потрапляли
    ВДРУГЕ й неправильно. Після правки крапка переїхала в 553 подіях,
    медіана зсуву 47 км.

    Незалежна міра (правило її не бачить): чи стоїть крапка на ПЕРШОМУ
    топонімі поста — у цих каналів рядок 1 це географія події. Було 21.3%,
    стало 28.6% на 2844 постах із двома й більше топонімами.

    Область тим самим фільтром чистити НЕ можна — перевірено окремо: із 422
    постів, де область названо після прийменника напрямку, у 361 іншої
    області в пості нема взагалі, і напрямок указує на ту саму область
    («Трубчевск и далее в направлении Брянск»). Фільтр там знищив би
    правильне.
    """
    pts = [e for e in p.get("entities", [])
           if "lat" in e and e.get("geo_conf") != "centroid"]
    # Повторний збіг області (`extra`, BACKLOG §7) — лише запасне місце. Далі
    # в пості він здебільшого ціль чи перелік під загрозою: «Лобановка,
    # Климовский район … могут пройти через Клинцы», «/ Котовск, Тамбов —
    # внимание». За населенням такий маркер перебивав село з першого рядка
    # (126 регресів арбітра «названий район»). Рятує він лише пости, що
    # інакше падали на центр області: «Саратовская область / Энгельс».
    #
    # Після «от» повторний збіг — джерело, і запасним місцем бути не може:
    # правило цілі нижче зробило б із нього «курс на X», тобто знак у
    # протилежний бік («От Каховки в направлении Чаплынка» — «курс на
    # Каховку», «От Новороссийска до Геленджика»). Вирішує ОСТАННЄ слово
    # руху перед назвою в її рядку: «от Багерово, Керчь … в сторону Тамань»
    # — Керч теж джерело.
    #
    # Місця з рядків 2+ (`extract.place_lines`, lpr1/vrv/kupol) — найнижчі
    # запасні, нижче навіть за повторний збіг області: крапка події лишається
    # там, де була, а самі вони йдуть у карту додатковими місцями
    # (`also_places`). Перша версія відсіювала їх ПІСЛЯ повторного збігу —
    # і «Керченский полуостров / Керчь / … / Тамань» ставало Таманню.
    if any(not e.get("lined") for e in pts):
        pts = [e for e in pts if not e.get("lined")]
    if any(not e.get("extra") for e in pts):
        pts = [e for e in pts if not e.get("extra")]
    else:
        pts = [e for e in pts if not (e.get("extra") and _from_side(p["text"], e))]

    def before(e):
        return p["text"][max(0, e.get("pos", 0) - 24):e.get("pos", 0)]

    # перший РОЗВʼЯЗАНИЙ топонім, не перша сутність: тип апарата («Хорнет:
    # от Чаплынки…») теж має позицію, а «Трассы от Мариуполь до Новоазовск»
    # витягує «Трассы» як назву без координати — і Маріуполь ставав «не
    # першим», тобто джерелом
    first_pos = min((e.get("pos", 0) for e in p.get("entities", [])
                     if e.get("pos") is not None and "lat" in e
                     and e.get("type") in ("нп", "регіон")), default=None)
    # Ланцюг цілей іде по ВСІХ названих сутностях, зокрема по області-
    # центроїду: «в сторону Смоленска или Рославля» — «Смоленска» це маркер
    # області (центроїд, крапкою не буває), і без нього ланцюг не починався,
    # тож Рославль лишався «місцем» і за населенням бив Єршичі (друга
    # рецензія 21 вересня 2026).
    aim = _aim_ids(p, pts, first_pos)
    # Слово руху раніше в реченні (не лише впритул, як `DIR_BEFORE`): «От
    # Вилино на Бахчисарай», «Калач на Дону и далее в направлении на
    # Волгоград», «пролёт БПЛА на Острогожск». Без цього за населенням
    # вигравала ціль — більше місто (BACKLOG §16.2). Те саме правило, що
    # відсіює цілі з додаткових місць (`_moving_to`); лише коли після нього
    # лишається хоч одне місце.
    moving = {id(e) for e in pts if e.get("pos") is not None and not e.get("inherited")
              and _moving_to(p["text"], e["pos"])}
    if moving and len(moving) < len(pts):
        pts = [e for e in pts if id(e) not in moving]
    # Якщо в пості нема НІЧОГО, крім цілі напрямку, лишаємо як було: краще
    # неточна крапка, ніж мовчазна втрата події. Таких 137 за 15 діб.
    aim_pts = {id(e) for e in pts if id(e) in aim}
    if aim_pts and len(aim_pts) < len(pts):
        pts = [e for e in pts if id(e) not in aim_pts]
    elif aim_pts:
        # Лишилась тільки ціль. Стара поведінка — крапка на ній — лишається,
        # але не для цілі, яку дав відмінковий фолбек чи яка лежить поза
        # областю поста: такі пости до фолбека падали на центр області, і
        # «Курская — в сторону Орла» не має ставати крапкою в Орлі (третя
        # рецензія 21 вересня 2026, 7 подій). Чи ставити ціль крапкою взагалі —
        # окреме рішення оператора (BACKLOG §15.4).
        home = GC.home_region(p)
        areas = [e for e in p.get("entities", []) if e["type"] == "регіон"
                 and e.get("geo_conf") == "centroid" and "lat" in e]
        area = next((e for e in areas if e["value"] == home), None) or next(iter(areas), None)
        if area is not None and all(e.get("geo_morph") or not e.get("geo_in_region", True)
                                    for e in pts):
            return area
        # Крапка лишається на цілі, але подія знає, що це ЦІЛЬ, а не місце
        # спостереження: «Ещё фиксации БПЛА в направлении Каланчак» — летять
        # туди, де саме бачили — не сказано. Редактор і плеєр малюють це
        # окремим знаком «курс на X» (поле `aim`, конвеєр v21), а не крапкою
        # «тут бачили». Заміряно: ~440 подій, ~3 за ніч, 79% — ціль у тій
        # самій області.
        for e in pts:
            e["_aim"] = True
    # Населений пункт б'є РАЙОН, хоч би яке в того населення. Район — площа
    # завширшки 40-60 км, і «Староивановка, Волоконовский район» це Староіванівка,
    # а не центр району. Без цього правила правка про зʼїдені райони ламала б
    # те, що працювало: заміряно, у 2032 постах район зʼявляється поруч із уже
    # розвʼязаним НП, і за населенням вигравав би він (Яковлевський 56 773
    # програвав Бєлгородському 119 135 за 33 км).
    #
    # Порядок саме такий, а не «спершу найменша площа»: серед НП і далі
    # вирішує населення — це стара, перевірена поведінка, і чіпати її тут
    # не треба.
    # Серед ПЛОЩ населення не вирішує взагалі. Спершу належність до області
    # поста, тоді — ПЕРШИЙ названий. Пост часто перелічує сусідні райони
    # («Богучарский район, Воронежская область — фиксации на Шолоховский
    # район, Ростовская»), і за населенням вигравав би більший, часто чужий.
    # Порядок — той самий принцип, який у цих каналів уже заміряний вище:
    # рядок 1 це географія події, і перший топонім є місцем.
    #
    # Для НП не змінюється НІЧОГО: у них третій член ключа однаковий, тож
    # вирішує населення, як і було.
    return max(pts, key=lambda e: (
        # 1. Належність до області, яку назвав сам пост. Найсильніший сигнал:
        #    «Богучарский район, Воронежская область — фиксации на Шолоховский
        #    район, Ростовская» давало Шолоховський, бо той розвʼязався СЕЛОМ
        #    на 10 тис. у чужій області й бив правильний район у своїй.
        e.get("geo_in_region", True),
        # 1а. Пряма назва перед відмінковим здогадом. Родовий відмінок
        #     («в сторону Смоленска или Рославля», «в сторону на Орла») майже
        #     завжди ціль; знайдений фолбеком геокода, він перебивав назване
        #     місце за населенням (друга рецензія 21 вересня 2026). Сам по собі
        #     він лишається («Пуски из Одессы» — Одеса). ПЕРШИЙ топонім
        #     поста — місце за правилом цих каналів, тож його не понижуємо:
        #     «От Алушты до Судак» — Алушта.
        not (e.get("geo_morph") and e.get("pos") != first_pos),
        # 2. Крапка над площею. Район — це 40-60 км завширшки, і «Староивановка,
        #    Волоконовский район» це Староіванівка, а не центр району.
        not e.get("geo_area"),
        # 3. Серед ПЛОЩ — перший названий, не найбільший. Пости перелічують
        #    сусідні райони, і за населенням вигравав би просто більший.
        #    Принцип той самий, що вже заміряний вище: рядок 1 це географія.
        -(e.get("pos") or 0) if e.get("geo_area") else 0,
        # 4. Серед НП — населення, як було завжди.
        e.get("geo_pop", 0)), default=None)


_REPLY_URL = re.compile(r"https?://t\.me/(?:s/)?(\w+)/(\d+)")
#: Відповідь, що спростовує чи коментує запізнення батька, — не подія на
#: його місці.
REPLY_RETRACT = re.compile(r"\bложн|не\s+подтверд|ошибочн|опоздал|уже\s+не\s+существ", re.I)


def link_replies(posts):
    """Відповідь на власний пост без жодного свого місця дістає місце батька.

    locatorru відповідає на свої ж пости оновленнями: «Продолжаются пролёты
    БПЛА», «Ещё фиксации БПЛА с моря», «От 5 БПЛА в направлении. НПЗ
    внимание!» — місце названо лише в батьку. До 22.09.2026 скрапер для
    відповіді зберігав ЦИТАТУ батька замість власного тексту (див.
    `scrape._parse`), тож такі пости розбирались як фантомна копія батька з
    часом відповіді. Після виправлення вони без звʼязку з батьком лишились
    би без місця взагалі.

    Успадковується те, що батько сам показав би: його крапка
    (`point_entity`, разом із позначкою цілі `_aim`) і його область
    (`geocode.home_region`). Вид події — з ВЛАСНОГО тексту відповіді
    («Отбой» під тривогою — відбій на тому самому місці). Відповідь, що
    назвала своє місце, не чіпається: вона каже про інше.

    Батько шукається в тому самому пакеті постів; ланцюг відповідей
    розвʼязується по порядку часу (пакет відсортовано), тож відповідь на
    відповідь дістає вже успадковане. Повертає кількість звʼязаних.
    """
    by = {(p["channel"], p["id"]): p for p in posts}
    n = 0
    for p in posts:
        m = _REPLY_URL.match(p.get("reply_to") or "")
        if not m or m.group(1) != p["channel"]:
            continue
        par = by.get((m.group(1), int(m.group(2))))
        if par is None or any("lat" in e for e in p.get("entities", [])):
            continue
        # Спростування батька місця не дістає: «Ложные - на момент написания
        # поста этих фиксаций уже не существовало» інакше ставало фіксацією
        # на місці тих самих хибних фіксацій (перевірка 22.09.2026).
        if REPLY_RETRACT.search(p.get("text") or ""):
            continue
        home = GC.home_region(par)
        reg = next((e for e in par.get("entities", []) if e["type"] == "регіон"
                    and e["value"] == home and "lat" in e), None)
        # Батько-пуск стоїть на ДЖЕРЕЛІ (`launch_origin`), а не на звичайній
        # крапці: «Ещё пуски БПЛА, много» під «Пуски БПЛА от
        # Днепропетровской области в сторону ЛДНР» діставало ціль (Донеччину).
        origin = launch_origin(par) if kind_of(par.get("text") or "") == "пуск" else None
        best = origin or point_entity(par)
        # позиція 0: успадковане стоїть «на початку» тексту відповіді, тобто
        # не після слова руху — роль ціль/місце несе `_aim`, узятий у батька
        if origin is not None:
            # Лише джерело: область батька-пуску — це його ЦІЛЬ («в сторону
            # ЛДНР»), і без джерела відповідь падала б на неї.
            inh = [dict(origin, pos=0, match="", inherited=True, _origin=True)]
        else:
            inh = [dict(e, pos=0, match="", inherited=True)
                   for e in (reg, best) if e is not None]
            if best is not None and reg is not None and best is reg:
                inh = inh[:1]
        if inh:
            p["entities"] = list(p.get("entities", [])) + inh
            p["_reply_of"] = f"{par['channel']}/{par['id']}"
            n += 1
    return n


# ---- ВИД З КОНТЕКСТУ: голий пост -------------------------------------------
#
# «Климово и близлежащие / Брянская область», «Оренбург / Оренбургская
# область / Меры безопасности» — пост називає лише місце. Сам по собі він не
# каже, що сталось, і до 22.09.2026 ставав «іншим», тобто на карту не йшов
# узагалі: на еталоні ролей це 21.5% усіх місць «тут», які загубились.
#
# Заміряно розміткою З КОНТЕКСТОМ (два незалежні розмітники, дві вибірки:
# 150 постів 22.08-21.09 і свіжі 100 за 24.07-22.08; `tools/ctx/`):
#   - голий пост у потоці каналу — здебільшого тривога (65 із 89 згідних на
#     свіжій вибірці), і «все голе -> тривога» дає 69% проти 10% зараз;
#   - «поруч є фіксація» (20-40 км, ±30 хв) як ознака фіксації — 67-70%, не
#     краще за «все -> тривога»: наліт поруч не робить пост спостереженням;
#   - вид НАЙБЛИЖЧОГО поста про те саме місце (≤15 км, 30 хв) на першій
#     вибірці 83% проти 78%, на свіжій 71% проти 69%, а успадкованих фіксацій
#     там 7 правильних і 5 хибних («Шатура / Меры безопасности» через 21 хв
#     після фіксації — обидва розмітники читали тривогою). Для крапки «тут
#     бачили» 58% — неприйнятно (основна крапка влучна у 83-88%), тож
#     фіксація від сусіда НЕ успадковується.
# З тієї ж причини голі тривоги не йдуть у шар свідчень редактора
# (`mknight._linked_alerts` — 20 км, ±30 хв, тобто те саме відкинуте
# правило, ще ширше; рецензія: ~40% правильних) і в хронологію стартів
# тривог (одна денна голa тривога ховала область на всю ніч).
# Відкрите: сліпа розмітка 36 випадкових голих тривог знайшла 6 справжніх
# фіксацій — усі з ППО чи збиттям ТАМ САМО за 1-4 хв («Алексин / Меры
# безопасности» після «Алексин / Работа ПВО по БПЛА»). Вузька ознака, але
# підказана даними — вмикати лише після свіжої відкладеної вибірки.
#
# Відповідь на власний пост — вид батька (правило оператора: «якщо це
# відповідь на його ж пост, то з цим і повʼязується»); місце вона вже
# дістала в `link_replies`.

#: Слова, які не змінюють того, що пост — лише перелік місць.
BARE_FILLER = re.compile(
    r"\b(?:и|в|по|с|г|гг|пгт|нп|"
    r"близлежащ\w*|ближайш\w*|окрестност\w*|прилегающ\w*|район\w*|р-н|округ\w*|го|мо|мр|"
    r"област\w*|кра[йя]\w*|республик\w*|рф|днр|лнр|лднр|"
    r"повторно|ещ[её]|снова|опять|сейчас|"
    r"меры|безопасност\w*|предосторожност\w*|соблюда\w*|принять|примите|"
    r"укрыти\w*|займите|занять|безопасн\w*|мест\w*|находитесь|пройдите|"
    r"срочно|немедленно|внимательно|аккуратно|всем)\b"
    r"|📡|@\w+|Локатор\s+России|[❗️⚠!.,:()/—-]", re.I)
#: Вид батька -> вид голої відповіді. ППО, збиття, вибух у батька означають,
#: що апарат там був — відповідь-продовження є фіксацією, а не збиттям.
CTX_KIND = {"фіксація": "фіксація", "ППО": "фіксація", "збиття": "фіксація",
            "вибух": "фіксація", "тривога": "тривога", "відбій": "відбій"}


def is_bare(p):
    """Пост — лише розпізнані місця і загальні слова безпеки.

    Вирізаються тільки місця, знайдені в газетирі (`lat`): нерозвʼязана
    «назва» буває словом («Феодосия / Учения» — «Учения» freeform ловить як
    НП), і тоді пост не голий."""
    text = p["text"]
    spans = sorted((e["pos"], e["pos"] + len(e["match"])) for e in p.get("entities", [])
                   if "lat" in e and e.get("pos") is not None and e["pos"] >= 0
                   and e.get("match"))
    out, cur = [], 0
    for a, b in spans:
        if a >= cur:
            out.append(text[cur:a])
        cur = max(cur, b)
    out.append(text[cur:])
    rest = BARE_FILLER.sub(" ", " ".join(out))
    return not re.search(r"[А-Яа-яЁёA-Za-z]{2,}", rest)


def _parent_id(p):
    """id батька, якщо пост — відповідь на пост свого ж каналу."""
    m = _REPLY_URL.match(p.get("reply_to") or "")
    return f"{m.group(1)}/{m.group(2)}" if m and m.group(1) == p["channel"] else None


def _ctx_point(e):
    return e.get("lat") is not None and e.get("geo_conf") not in ("centroid", "region-snap")


def context_kinds(events, lookup=None):
    """Голі пости (`_bare`) з крапкою: відповідь — вид батька, решта — тривога.

    `kind_ctx` — id батька або «—» (батька нема). Батько з видом, якого тут
    нема в CTX_KIND (тактичний дрон, «інше»), лишає відповідь «іншою»: «Ещё
    1.» під «Белая Березка Баба яга» — той самий тактичний дрон. Тип апарата
    теж від батька: відповідь на тривогу по «Фламинго» — не «БпЛА».

    Батько шукається в пакеті, а якщо його там нема — через `lookup(id)` у
    записаному сховищі: щогодинний `sync --since 2d` бачить батька лише у
    своєму вікні, і без цього відповідь на межі розходилась би з повною
    перебудовою (рецензія v27: лаг відповіді до 210 хв). Події обходяться за
    часом, тож батько-голий уже має свій вид. Голий пост без крапки (лише
    область) лишається «іншим» — цей клас не перевірявся. Повертає
    кількість змінених.
    """
    by_id = {e["id"]: e for e in events}
    n = 0
    for e in events:
        parent = e.pop("_parent", None)
        if not e.pop("_bare", False) or e["kind"] != "інше" or e.get("noise") \
                or not _ctx_point(e):
            continue
        # сирий `reply_to`, а не `reply_of`: той заповнений, лише коли
        # відповідь без свого місця, а голий пост місце має
        par = by_id.get(parent) if parent else None
        if parent and par is None and lookup is not None:
            par = lookup(parent)
        if par is not None and par["kind"] not in CTX_KIND:
            continue
        k = CTX_KIND[par["kind"]] if par else "тривога"
        e["kind"] = k
        e["scope"] = "точка" if k in POINT_KINDS else "область"
        e["kind_ctx"] = par["id"] if par else "—"
        if par is not None and not e.get("utype"):
            e["utype"] = par.get("utype")
        n += 1
    return n


