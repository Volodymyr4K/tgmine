    ("ПКР",                r"\bпкр\b|противокорабел|протикорабел"),
    ("балістична ракета",  r"баллист|баліст"),
    ("крилата ракета",     r"крылат|крилат"),
    ("керована авіаційна ракета", r"керован\w* авіаційн\w* ракет"),
