    # Реактивний БпЛА — ПЕРЕД генеричною «ракетою». «Ракетная опасность» у
    # РФ — формальний сигнал, який вмикають і на реактивні БпЛА: «Ракетная
    # опасность / По реактивным БПЛА», «отбой ракетной опасности, опасность
    # по реактивным БПЛА сохраняется» — 284 пости, де обидва слова, і в
