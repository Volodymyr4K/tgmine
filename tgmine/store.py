    #   «реактивный снаряд»   6  — НУРС/боєприпас РСЗО, не апарат;
    #   «реактивные выходы»   6  — пуски РСЗО з-під Слов'янська;
    #   «реактивный звук/гул» 5  — почутий ЗВУК, а не побачений обʼєкт.
