"""Відсів обʼєктів, які не є предметом моніторингу.

Проєкт стежить за ударами по РФ. Плитки Overpass у `fetch_targets` прямокутні,
а кордон — ні, тому у вибірку падають обʼєкти сусідніх країн. Серед них
українські: аеродроми, полігони, військові частини — з координатами, ярусом і
місцем у рейтингу. Публікувати такий перелік не можна, і справа не в
секретності (усе взято з відкритого OSM), а в подачі: формат перетворює
нейтральні дані на щось, що читається як список цілей.

Різати доводиться у два кроки, бо країна й контроль — різні речі.

1. Геометрія: точка в полігоні Natural Earth (`adm0_a3`). NE відносить Крим і
   Севастополь до RUS — для нас це саме те, що треба: обʼєкти під контролем РФ
   лишаються в наборі.

2. Ручний список: чотири області мають і окуповану, і підконтрольну Україні
   частину, і геометрія їх не розділяє. Мелітопольський аеродром і Краматорськ
   лежать в одному наборі. Лінію розмежування вивести з наявних даних
   неможливо, і апроксимувати її не варто — вона рухається.

Правило для сумнівних — **прибирати**. Асиметрія: зайве прибрати означає трохи
менше покриття, зайве лишити означає рівно ту шкоду, від якої все це.
"""
