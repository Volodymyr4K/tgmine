class Borders:
    """Точка -> країна за Natural Earth. Полігони читаються один раз."""

    def __init__(self, polys):
        self.polys = polys

    @classmethod
    def load(cls, shp: str | Path = SHP):
        import shapefile

        sf = shapefile.Reader(str(shp))
        flds = [f[0] for f in sf.fields[1:]]
        i_a3, i_ru, i_en = flds.index("adm0_a3"), flds.index("name_ru"), flds.index("name")
        polys = []
        for sr in sf.iterShapeRecords():
            sh = sr.shape
            parts = list(sh.parts) + [len(sh.points)]
            polys.append((
                sr.record[i_a3],
                sr.record[i_ru] or sr.record[i_en],
                sh.bbox,
                [sh.points[parts[k]:parts[k + 1]] for k in range(len(parts) - 1)],
            ))
        return cls(polys)

    @staticmethod
    def _in_ring(x, y, ring) -> bool:
        c = False
        n = len(ring)
        for k in range(n):
            x1, y1 = ring[k]
            x2, y2 = ring[(k + 1) % n]
            if (y1 > y) != (y2 > y) and x < (x2 - x1) * (y - y1) / (y2 - y1) + x1:
                c = not c
        return c

    def locate(self, lat: float, lon: float) -> tuple[str | None, str | None]:
        """(код країни, назва регіону) або (None, None) поза всіма полігонами."""
        for a3, name, bb, rings in self.polys:
            if not (bb[0] <= lon <= bb[2] and bb[1] <= lat <= bb[3]):
                continue
            if sum(self._in_ring(lon, lat, r) for r in rings) % 2:
                return a3, name
        return None, None

    #: Скільки кілометрів до берега ще вважається «той самий регіон».
    #: Усі 48 нелокалізованих обʼєктів набору лежать у межах 4.5 км від
    #: полігону (причали Севастополя й Новоросійська, коси Азова, Приморськ
    #: на Балтиці) — це похибка контуру NE, а не інша країна. 10 лишає запас
    #: і не дотягується через жодну протоку.
    NEAR_KM = 10.0

    def nearest(self, lat: float, lon: float,
                max_km: float = NEAR_KM) -> tuple[str | None, str | None]:
        """Найближчий полігон, якщо точка не потрапила в жоден.

        Відстань рахується до ВІДРІЗКА контуру, не до вершини. Різниця не
        косметична: у полігонах театру 2348 відрізків довші за 10 км (у
        Ленінградській є 163-кілометровий), і точка за кілометр від такої
        прямої лежить за десятки кілометрів від обох її кінців — за
        вершинами вона б не знайшлась і обʼєкт пішов би у відсів.

        Рівнокутне наближення: на цих широтах похибка часток відсотка, а
        радіус усього 10 км. Тягнути сюди haversine із `geocode` заради
        цього не варто — `territory` навмисно не залежить від газетира.
        """
        deg = max_km / 111.0
        klon = math.cos(math.radians(lat)) or 1e-9
        best = None
        for a3, name, bb, rings in self.polys:
            if not (bb[0] - deg <= lon <= bb[2] + deg
                    and bb[1] - deg <= lat <= bb[3] + deg):
                continue
            for ring in rings:
                for (x1, y1), (x2, y2) in zip(ring, ring[1:]):
                    d = self._seg_km(lat, lon, y1, x1, y2, x2, klon)
                    if best is None or d < best[0]:
                        best = (d, a3, name)
        if best is None or best[0] > max_km:
            return None, None
        return best[1], best[2]

    @staticmethod
    def _seg_km(lat, lon, y1, x1, y2, x2, klon) -> float:
        """Відстань від точки до відрізка контуру, у кілометрах."""
        px, py = (lon - x1) * klon, lat - y1
        vx, vy = (x2 - x1) * klon, y2 - y1
        L = vx * vx + vy * vy
        t = 0.0 if L == 0 else max(0.0, min(1.0, (px * vx + py * vy) / L))
        return math.hypot(px - t * vx, py - t * vy) * 111.0


def is_excluded(obj: dict, borders: Borders) -> str | None:
    """Причина відсіву, або None якщо обʼєкт лишається.

    Правило для сумнівних — прибирати: зайве прибрати означає трохи менше
    покриття, зайве лишити означає рівно ту шкоду, від якої все це. Тому
    точка, яку межі не впізнали ЗОВСІМ, теж іде геть.

    Але «наосліп прибирати нелокалізоване» неприпустимо: у наборі таких 48,
    і всі до одного — прибережні (причали Севастополя, Шесхаріс у
    Новоросійську, коси Азова, Приморськ на Балтиці), максимум 4.5 км від
    контуру. Серед них Шесхаріс і склад БК Yany Kapu з ненульовим жаром.
    Тому спершу дивимось найближчий полігон у межах 10 км і судимо за ним,
    і лише коли й його нема — відсіваємо.
    """
    a3, region = borders.locate(obj["lat"], obj["lon"])
    if a3 is None:
        a3, region = borders.nearest(obj["lat"], obj["lon"])
    if obj.get("osm") in EXCLUDE_OSM:
        return "ручний відсів (підконтрольна Україні територія)"
    if region in UA_REAR:
        return f"тил України ({region})"
    if a3 is None:
        return "межі не впізнали точку (правило сумніву)"
    if a3 == "UKR" and region not in UA_CONTESTED:
        # Нова назва регіону в NE або область, якої нема в жодному списку —
        # мовчки лишати не можна, бо це рівно той випадок, який ми ловимо.
        return f"територія України ({region or 'регіон невідомий'})"
    return None


def filter_objects(objects: list[dict], borders: Borders | None = None,
                   log=print) -> list[dict]:
    """Прибирає українські обʼєкти. Повертає новий список."""
    borders = borders or Borders.load()
    kept, dropped = [], {}
    for o in objects:
        why = is_excluded(o, borders)
        if why:
            dropped.setdefault(why, []).append(o)
        else:
            kept.append(o)
    total = sum(len(v) for v in dropped.values())
    log(f"відсіяно {total} з {len(objects)}:")
    for why, objs in sorted(dropped.items(), key=lambda kv: -len(kv[1])):
        log(f"  {len(objs):4}  {why}")
    return kept


